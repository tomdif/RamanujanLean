# Writes RamanujanTau/GORZXiEff/CVData{M,B,A}.lean from cv_cells.txt (three lines: breakpoints for
# cellM, cellB, cellA, in units of 2^-12; produced by `lake env lean scripts/gorzxi_eff/cv_subdiv.lean`).
import ast, os
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.abspath(os.path.join(here, '..', '..'))
L = [ast.literal_eval(l) for l in open(os.path.join(here, 'cv_cells.txt')).read().strip().split('\n')]
names = {'M': L[0], 'B': L[1], 'A': L[2]}
cellfn = {'M': 'cellM', 'B': 'cellB', 'A': 'cellA'}
for key, lst in names.items():
    out = [f"""/-
# Kernel-checked cover data for `{cellfn[key]}` ({len(lst)-1} cells, `u = p/2^12`)

Each cell is a separate `decide +kernel` (keeps the kernel cache per declaration small).
Generated by `scripts/gorzxi_eff/cv_gen_data.py` from the adaptive subdivision in `cv_cells.txt`.
-/
import RamanujanTau.GORZXiEff.CVRegionB

set_option autoImplicit false

namespace GORZXiEff.CV
"""]
    for i in range(len(lst) - 1):
        out.append(f"theorem {key.lower()}cell_{i} : {cellfn[key]} {lst[i]} {lst[i+1]} = true := by decide +kernel")
    out.append(f"\ndef pts{key} : List ℤ := {lst}\n")
    out.append(f"theorem cover{key}_ok : allCells {cellfn[key]} pts{key} = true := by")
    out.append(f"  simp only [pts{key}, allCells, " + ", ".join(f"{key.lower()}cell_{i}" for i in range(len(lst) - 1)) + ", Bool.and_self]")
    out.append("\nend GORZXiEff.CV\n")
    open(os.path.join(root, 'RamanujanTau', 'GORZXiEff', f'CVData{key}.lean'), 'w').write("\n".join(out))
