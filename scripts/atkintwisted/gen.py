#!/usr/bin/env python3
"""Generate RamanujanTau/AtkinTwisted/Group{1..4}.lean and All.lean from scan500.json, crosscheck.json.
Each group: one kernel-certified prefix of p(n) mod 13 (length 14*Qmax^2+1), the Sturm certificate
(15 coefficients of T(Q^2)F - mu F) for every prime Q of the group, and the Atkin/Ono corollaries."""
import json, sys, os
from sympy import legendre_symbol

def leg(a, Q):
    a %= Q
    return 0 if a == 0 else legendre_symbol(a, Q)

def pentLow(j): return (j + 1) * (3 * (j + 1) - 1) // 2

def params(Npre):
    k = 1
    while pentLow(k * 256) < Npre: k += 1
    kN = Npre.bit_length(); n = kN
    ku = 4; kb = 18; kc = ku + kb + kN
    assert ku + kb + kN < 64 and k * 256 <= 2 ** 20 and 2 ** 22 + 13 * 2 ** kc <= 2 ** 64 and Npre <= 2 ** kN
    R = 13 * (2 ** 18 // 13)
    return R, 8, k, n, ku, kb, kc, kN

GROUPS = [(5, 110), (110, 250), (250, 360), (360, 500)]
OUT = sys.argv[3] if len(sys.argv) > 3 else '../../RamanujanTau/AtkinTwisted'

def main():
    scan = json.load(open(sys.argv[1]))['res']; cc = json.load(open(sys.argv[2]))
    hits = {(r['Q']): r for r in cc}
    names = []
    for gi, (lo, hi) in enumerate(GROUPS, 1):
        rows = [x for x in scan if lo <= x['Q'] < hi]
        assert all(x['sturm_ok'] for x in rows)
        Qmax = max(x['Q'] for x in rows)
        Npre = 14 * Qmax ** 2 + 1
        R, d, k, n, ku, kb, kc, kN = params(Npre)
        L = ', '.join(f"({x['Q']}, {x['mu']})" for x in rows)
        o = []
        o.append(f"""import RamanujanTau.AtkinTwisted.Core

/-!
# Atkin's twisted class modulo 13: primes `{lo} ≤ Q < {hi}` (generated by `scripts/atkintwisted/gen.py`)

One kernel-certified prefix of {Npre:,} partition numbers modulo 13 (`cert`) gives the 15 Sturm
coefficients of `T(Q²)F̄ − μF̄` for every prime `Q` of the list, so `F̄` is a `T(Q²)`-eigenform
with the listed `μ` (`eigen`). Atkin type (`μ = s ε Q¹⁶⁶`): `13 ∣ p(N)` when `24N − 1 = Q²m`,
`(m/Q) = ε`, `(m/13) = −1`. Ono type (`μ = 0`): `13 ∣ p(N)` when `24N − 1 = Q³n`, `Q ∤ n`,
`(Qn/13) = −1`.
-/

set_option autoImplicit false

namespace RamanujanTau.AtkinTwisted.G{gi}
open PowerSeries BoylanWebb RamanujanTau.AtkinSporadic RamanujanTau.AtkinTwisted
open Twist13

/-- The pairs `(Q, μ)`: `T(Q²)F̄ = μF̄` modulo 13. -/
def pairs : List (ℕ × ZMod 13) := [{L}]

set_option maxRecDepth 100000 in
/-- **The kernel certificate**: one partition prefix, every pair. -/
theorem cert : allOk {R} {Npre} {d} {k} {n} {ku} {kb} {kc} pairs = true := by
  decide +kernel

/-- `F̄` is a `T(Q²)`-eigenform for every `Q` of the list. -/
theorem eigen (Q : ℕ) [Fact Q.Prime] (hQ5 : 5 ≤ Q) (μ : ZMod 13) (hmem : (Q, μ) ∈ pairs) :
    TT Q = C μ * Ψ 13 twPGF :=
  eigen_of_allOk (kN := {kN}) (by norm_num) (by norm_num) (by norm_num) (by norm_num) (by norm_num)
    (by decide) cert Q hQ5 μ hmem
""")
        for x in rows:
            Q = x['Q']
            if Q not in hits: continue
            h = hits[Q]; mu = x['mu']; s = x['s']
            A, r, w = h['modulus'], h['residue'], h['witness']
            o.append(f"""
instance fact{Q} : Fact (Nat.Prime {Q}) := ⟨by norm_num⟩

theorem sign{Q} : heckeSign {Q} 167 = {s} := by
  rw [heckeSign, legendreSym_val {Q} (by norm_num), legendreSym_val {Q} (by norm_num)]
  decide +kernel

theorem eigen{Q} : TT {Q} = C {mu} * Ψ 13 twPGF := eigen {Q} (by norm_num) {mu} (by decide)
""")
            if h['type'].startswith('atkin'):
                eps = 1 if h['type'] == 'atkin+' else -1
                epsL = '1' if eps == 1 else '-1'
                c1, c2 = w % Q, w % 13
                nm = f"atkin_13_{Q}"
                o.append(f"""
/-- Atkin type at `Q = {Q}` (`μ = {mu}`): `13 ∣ p(N)` whenever `24N − 1 = {Q}²m`, `(m/{Q}) = {epsL}`,
`(m/13) = −1`. -/
theorem {nm}_class (N m : ℕ) (hm : 24 * N = {Q} ^ 2 * m + 1) (hQ : legendreSym {Q} m = {epsL})
    (h13 : legendreSym 13 m = -1) : 13 ∣ Fintype.card (Nat.Partition N) :=
  Atkin13.vanish_of_eigen {Q} (by norm_num) {mu} (by decide) eigen{Q} ({epsL}) (by norm_num)
    (by rw [sign{Q}]; decide +kernel) (by norm_num) N m hm hQ h13

/-- **`13 ∣ p({A} n + {r})`** (`{A} = 13·{Q}³`; `m = {312*Q} n + {w}`). -/
theorem {nm} (n : ℕ) : 13 ∣ Fintype.card (Nat.Partition ({A} * n + {r})) := by
  refine {nm}_class _ ({312 * Q} * n + {w}) (by ring) ?_ ?_
  · rw [legendreSym.mod, show (({312 * Q} * n + {w} : ℕ) : ℤ) % ({Q} : ℕ) = {c1} by push_cast; omega,
      legendreSym_val {Q} (by norm_num)]
    decide +kernel
  · rw [legendreSym.mod, show (({312 * Q} * n + {w} : ℕ) : ℤ) % (13 : ℕ) = {c2} by push_cast; omega,
      legendreSym_val 13 (by norm_num)]
    decide +kernel
""")
                names.append((Q, h['type'], mu, f"G{gi}.{nm}_class", f"G{gi}.{nm}", A, r))
            else:
                nm = f"ono_13_{Q}"
                c = (Q * w) % 13
                o.append(f"""
/-- Ono type at `Q = {Q}` (`μ = 0`): `13 ∣ p(N)` whenever `24N − 1 = {Q}³n`, `{Q} ∤ n`,
`({Q}n/13) = −1`. -/
theorem {nm}_class (N n : ℕ) (hm : 24 * N = {Q} ^ 3 * n + 1) (hQn : ¬ {Q} ∣ n)
    (h13 : legendreSym 13 (({Q} : ℕ) * (n : ℤ)) = -1) : 13 ∣ Fintype.card (Nat.Partition N) :=
  vanish_ono {Q} (by norm_num) (by decide) eigen{Q} N n hm hQn h13

/-- **`13 ∣ p({A} n + {r})`** (`{A} = 13·{Q}⁴`; `n' = {312*Q} n + {w}`). -/
theorem {nm} (n : ℕ) : 13 ∣ Fintype.card (Nat.Partition ({A} * n + {r})) := by
  refine {nm}_class _ ({312 * Q} * n + {w}) (by ring) (by omega) ?_
  rw [legendreSym.mod, show ((({Q} : ℕ) : ℤ) * (({312 * Q} * n + {w} : ℕ) : ℤ)) % (13 : ℕ) = {c} by
      push_cast; omega, legendreSym_val 13 (by norm_num)]
  decide +kernel
""")
                names.append((Q, 'ono', mu, f"G{gi}.{nm}_class", f"G{gi}.{nm}", A, r))
        o.append(f"\nend RamanujanTau.AtkinTwisted.G{gi}\n")
        open(os.path.join(OUT, f"Group{gi}.lean"), 'w').write(''.join(o))
        print(f"Group{gi}: Q in [{lo},{hi}), {len(rows)} primes, Npre={Npre}, params={params(Npre)}")
    json.dump(names, open('theorem_names.json', 'w'), indent=0)

main()
