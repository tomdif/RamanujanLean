#!/usr/bin/env python3
"""Generate kernel-checked witnesses for the four-factor product at 97.

The infinite zero direction comes from the existing reflection theorem.
The search supplies one exact nonzero coefficient for every other residue;
Lean independently checks the finite sums and their actual-product bridge.
"""
from pathlib import Path
import re

from quintuple_vanishing_scan import product_coefficients

ROOT = Path(__file__).resolve().parents[1]


def generate():
    p, indices, zeros = 97, (5, 4, 9, 13), {9, 13, 55, 64}
    coefficients = product_coefficients(p, indices, 1509)
    witnesses = {}
    for r in range(p):
        if r in zeros:
            continue
        for n in range(16):
            if coefficients.get(p*n+r, 0):
                witnesses[r] = (n, p*n+r, coefficients[p*n+r])
                break
        else:
            raise AssertionError(f"missing witness for residue {r}")
    assert len(witnesses) == 93 and witnesses[54] == (15, 1509, 1)
    assert all(coefficients.get(97*n+54, 0) == 0 for n in range(15))
    out = ['''import RamanujanTau.MultiQuintupleFourReflection

/-!
# Complete four-factor classification at 97, with an optimal finite test

Generated by `scripts/generate_four97_converse.py`. Every numerical claim is
checked by `decide +kernel`; the generator is outside the trusted proof.
-/
namespace Ramanujan.MultiQuintuple
open PowerSeries
set_option maxRecDepth 100000
set_option maxHeartbeats 4000000

private lemma short_index97_one (b : Bool) (i : ℕ) (n : ℤ)
    (hi : 1 ≤ i) (hi13 : i ≤ 13) (he : quintExp2 b 97 i n ≤ 838) :
    n.natAbs ≤ 1 := by
  have hn : -1 ≤ n ∧ n ≤ 1 := by
    interval_cases i <;> cases b <;>
      norm_num [quintExp2,quintExpA2,quintExpB2] at he <;>
      constructor <;> by_contra h <;>
      have hside : n ≤ -2 ∨ 2 ≤ n := by omega
    all_goals rcases hside with hside | hside <;>
      nlinarith [sq_nonneg (n+2),sq_nonneg (n-2)]
  omega

private lemma short_index97_two (b : Bool) (i : ℕ) (n : ℤ)
    (hi : 1 ≤ i) (hi13 : i ≤ 13) (he : quintExp2 b 97 i n ≤ 2118) :
    n.natAbs ≤ 2 := by
  have hn : -2 ≤ n ∧ n ≤ 2 := by
    interval_cases i <;> cases b <;>
      norm_num [quintExp2,quintExpA2,quintExpB2] at he <;>
      constructor <;> by_contra h <;>
      have hside : n ≤ -3 ∨ 3 ≤ n := by omega
    all_goals rcases hside with hside | hside <;>
      nlinarith [sq_nonneg (n+3),sq_nonneg (n-3)]
  omega

private lemma short_index97_three (b : Bool) (i : ℕ) (n : ℤ)
    (hi : 1 ≤ i) (hi13 : i ≤ 13) (he : quintExp2 b 97 i n ≤ 3018) :
    n.natAbs ≤ 3 := by
  have hn : -3 ≤ n ∧ n ≤ 3 := by
    interval_cases i <;> cases b <;>
      norm_num [quintExp2,quintExpA2,quintExpB2] at he <;>
      constructor <;> by_contra h <;>
      have hside : n ≤ -4 ∨ 4 ≤ n := by omega
    all_goals rcases hside with hside | hside <;>
      nlinarith [sq_nonneg (n+4),sq_nonneg (n-4)]
  omega

def four97Radius (K : ℕ) : ℕ := if K ≤ 419 then 0 else if K ≤ 1059 then 1 else 2

private lemma short_index97 (b : Bool) (i : ℕ) (n : ℤ) (K : ℕ)
    (hi : 1 ≤ i) (hi13 : i ≤ 13) (hK : K ≤ 1509)
    (he : quintExp2 b 97 i n ≤ 2*(K : ℤ)) :
    n.natAbs ≤ four97Radius K+1 := by
  unfold four97Radius
  split_ifs with h0 h1
  · exact short_index97_one b i n hi hi13 (by omega)
  · exact short_index97_two b i n hi hi13 (by omega)
  · exact short_index97_three b i n hi hi13 (by omega)

private lemma mem_short_box97 (K : ℕ) (hK : K ≤ 1509) (x : QuadQuintBranchIndex)
    (he : quadExp2 97 5 4 9 13 x = 2*(K : ℤ)) : x ∈ quadBox (four97Radius K) := by
  rcases x with ⟨⟨⟨⟨b1,n1⟩,⟨b2,n2⟩⟩,⟨b3,n3⟩⟩,⟨b4,n4⟩⟩
  simp only [quadExp2,pointTripleExp2,tripleQuintExp2,pointB1,pointB2,pointB3,
    pointN1,pointN2,pointN3,quadB4,quadN4] at he
  have h1 := quintExp2_nonneg b1 97 5 n1 (by norm_num) (by norm_num)
  have h2 := quintExp2_nonneg b2 97 4 n2 (by norm_num) (by norm_num)
  have h3 := quintExp2_nonneg b3 97 9 n3 (by norm_num) (by norm_num)
  have h4 := quintExp2_nonneg b4 97 13 n4 (by norm_num) (by norm_num)
  norm_num only [Nat.cast_ofNat] at he h1 h2 h3 h4
  have hn1 := short_index97 b1 5 n1 K (by norm_num) (by norm_num) hK (by norm_num only [Nat.cast_ofNat]; omega)
  have hn2 := short_index97 b2 4 n2 K (by norm_num) (by norm_num) hK (by norm_num only [Nat.cast_ofNat]; omega)
  have hn3 := short_index97 b3 9 n3 K (by norm_num) (by norm_num) hK (by norm_num only [Nat.cast_ofNat]; omega)
  have hn4 := short_index97 b4 13 n4 K (by norm_num) (by norm_num) hK (by norm_num only [Nat.cast_ofNat]; omega)
  rw [quadBox,tripleQuintBranchBox]
  exact Finset.mem_product.mpr ⟨Finset.mem_product.mpr
    ⟨Finset.mem_product.mpr ⟨mem_quintBranchBox_of_natAbs_le (four97Radius K) b1 n1 hn1,
    mem_quintBranchBox_of_natAbs_le (four97Radius K) b2 n2 hn2⟩,
    mem_quintBranchBox_of_natAbs_le (four97Radius K) b3 n3 hn3⟩,
    mem_quintBranchBox_of_natAbs_le (four97Radius K) b4 n4 hn4⟩

noncomputable def four97ShortCoeff (K : ℕ) : ℤ :=
  ∑ x ∈ quadBox (four97Radius K), quadContribution 97 5 4 9 13 K x

lemma coeff_four97_eq_short (K : ℕ) (hK : K ≤ 1509) :
    coeff K (quintupleSpecialized 97 5 * quintupleSpecialized 97 4 *
      quintupleSpecialized 97 9 * quintupleSpecialized 97 13) = four97ShortCoeff K := by
  rw [coeff_quad_eq_finiteBox 97 5 4 9 13 K
    (by norm_num) (by norm_num) (by norm_num) (by norm_num)
    (by norm_num) (by norm_num) (by norm_num) (by norm_num)]
  unfold four97ShortCoeff
  apply Finset.sum_congr_of_eq_on_inter
  · intro x hx hnx
    by_contra hn
    have he : quadExp2 97 5 4 9 13 x = 2*(K : ℤ) := by
      by_contra h; simp [quadContribution,h] at hn
    exact hnx (mem_short_box97 K hK x he)
  · intro x hx hnx
    by_contra hn
    have he : quadExp2 97 5 4 9 13 x = 2*(K : ℤ) := by
      by_contra h; simp [quadContribution,h] at hn
    exact hnx (mem_quadBox_of_exp 97 5 4 9 13 K x
      (by norm_num) (by norm_num) (by norm_num) (by norm_num)
      (by norm_num) (by norm_num) (by norm_num) (by norm_num) he)
  · intro x hx hy; rfl

''']
    for r, (_, k, value) in witnesses.items():
        out.append(f'''set_option maxHeartbeats 0 in
private theorem coefficient97_{r} : four97ShortCoeff {k} = ({value} : ℤ) := by
  decide +kernel

''')
    product = '''(quintupleSpecialized 97 5 * quintupleSpecialized 97 4 *
      quintupleSpecialized 97 9 * quintupleSpecialized 97 13)'''
    out.append(f'''/-- Every other residue has a nonzero coefficient by progression index 15. -/
theorem four97_residue_or_witness (R : ℕ) (hR : R < 97) :
    (R=9 ∨ R=13 ∨ R=55 ∨ R=64) ∨
    ∃ N : ℕ, N ≤ 15 ∧ coeff (97*N+R) {product} ≠ 0 := by
  interval_cases R
''')
    for r in range(p):
        if r in zeros:
            out.append('  · left; norm_num\n')
        else:
            n, _, _ = witnesses[r]
            out.append(f'''  · right
    refine ⟨{n}, by norm_num, ?_⟩
    rw [coeff_four97_eq_short _ (by norm_num)]
    exact ne_of_eq_of_ne coefficient97_{r} (by norm_num)
''')
    out.append(f'''
/-- Exactly four residue progressions vanish for this product, for all N. -/
theorem four97_persistent_vanishing_iff (R : ℕ) (hR : R < 97) :
    (∀ N : ℕ, coeff (97*N+R) {product} = 0) ↔
    R=9 ∨ R=13 ∨ R=55 ∨ R=64 := by
  constructor
  · intro hz
    rcases four97_residue_or_witness R hR with hr | ⟨N,_,hn⟩
    · exact hr
    · exact False.elim (hn (hz N))
  · intro hr N
    exact coeff_fourReflection_97 R N hr

/-- Sixteen terms are an exact finite test for every residue of this product. -/
theorem four97_finite_test_iff (R : ℕ) (hR : R < 97) :
    (∀ N : ℕ, coeff (97*N+R) {product} = 0) ↔
    (∀ N : ℕ, N ≤ 15 → coeff (97*N+R) {product} = 0) := by
  constructor
  · exact fun h N _ => h N
  · intro h
    apply (four97_persistent_vanishing_iff R hR).mpr
    rcases four97_residue_or_witness R hR with hr | ⟨N,hle,hn⟩
    · exact hr
    · exact False.elim (hn (h N hle))

set_option maxHeartbeats 0 in
private theorem coefficient97_54_before :
    ∀ N : Fin 15, four97ShortCoeff (97*N.val+54) = 0 := by
  decide +kernel

/-- The cutoff is attained: residue 54 first becomes nonzero at N=15. -/
theorem first_witness_four97 :
    (∀ N : ℕ, N < 15 → coeff (97*N+54) {product} = 0) ∧
    coeff (97*15+54) {product} = 1 := by
  constructor
  · intro N hN
    rw [coeff_four97_eq_short _ (by omega)]
    exact coefficient97_54_before ⟨N,hN⟩
  · rw [coeff_four97_eq_short _ (by norm_num)]
    exact coefficient97_54

end Ramanujan.MultiQuintuple
''')
    return ''.join(out)


def generate_files():
    """Bound each kernel-evaluation batch and chain imports to bound build memory."""
    source = generate()
    first = source.index('set_option maxHeartbeats 0 in')
    body_start = source.index('/-- Every other residue')
    core = source[:first]+'\nend Ramanujan.MultiQuintuple\n'
    entries = []
    pattern = re.compile(r'set_option maxHeartbeats 0 in\nprivate theorem coefficient97_\d+ : '
                         r'four97ShortCoeff (\d+) = .*?\n  decide \+kernel\n\n', re.S)
    for match in pattern.finditer(source[first:body_start]):
        entries.append((int(match[1]), match[0].replace('private theorem', 'theorem')))
    assert len(entries) == 93
    for n in range(15):
        k = 97*n+54
        entries.append((k, f'''set_option maxHeartbeats 0 in
theorem before97_{n} : four97ShortCoeff (97*{n}+54) = 0 := by
  decide +kernel

'''))
    batches, current, cost = [], [], 0
    for k, declaration in entries:
        radius = 0 if k <= 419 else 1 if k <= 1059 else 2
        weight = (2*(2*radius+3))**4
        if current and (len(current) >= 8 or cost+weight > 40000):
            batches.append(current)
            current, cost = [], 0
        current.append(declaration)
        cost += weight
    if current:
        batches.append(current)
    directory = 'RamanujanTau/MultiQuintupleFourNinetySeven'
    files = {f'{directory}/Core.lean': core}
    previous = 'RamanujanTau.MultiQuintupleFourNinetySeven.Core'
    for number, batch in enumerate(batches):
        name = f'Certificates{number:02d}'
        files[f'{directory}/{name}.lean'] = f'''import {previous}

/-! Generated kernel certificate batch; imports are chained to bound build memory. -/
namespace Ramanujan.MultiQuintuple.Four97Certificates
set_option maxRecDepth 100000

'''+''.join(batch)+'end Ramanujan.MultiQuintuple.Four97Certificates\n'
        previous = f'RamanujanTau.MultiQuintupleFourNinetySeven.{name}'
    body = source[body_start:]
    original_before = '''set_option maxHeartbeats 0 in
private theorem coefficient97_54_before :
    ∀ N : Fin 15, four97ShortCoeff (97*N.val+54) = 0 := by
  decide +kernel
'''
    new_before = '''private theorem coefficient97_54_before :
    ∀ N : Fin 15, four97ShortCoeff (97*N.val+54) = 0 := by
  intro N
  fin_cases N
'''+''.join(f'  · exact before97_{n}\n' for n in range(15))
    assert original_before in body
    body = body.replace(original_before, new_before)
    files['RamanujanTau/MultiQuintupleFourNinetySevenConverse.lean'] = f'''import {previous}

/-!
# Complete four-factor classification at 97, with an optimal finite test

Generated by `scripts/generate_four97_converse.py`. The coefficient certificates
are kernel checked in small, sequentially imported batches.
-/
namespace Ramanujan.MultiQuintuple
open PowerSeries Four97Certificates
set_option maxRecDepth 100000
set_option maxHeartbeats 4000000

'''+body
    return files


if __name__ == '__main__':
    files = generate_files()
    for name, source in files.items():
        path = ROOT/name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(source)
    print(f'Generated {len(files)} Lean files (core, certificate batches, public converse)')
