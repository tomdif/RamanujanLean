"""Generate RamanujanTau/MTC/Zeros232.lean: HM Theorem 0.3 for f_{2,3,2} at y = -t^{6b}, q = t^{36} (t = Q^{1/6}),
for each b in BS. F lies in Th(11) (period x -> t^{180} x); we use 9 B-zeros and 3 A-zeros."""
import sys
QE=36
BS=[int(a) for a in sys.argv[1:]] or [7,13,17,19,25]
Zp={1:0,-1:42}
def B_zeros(b):
    out=[]
    for l in (0,1,2):
        ex=60*l-48+4*b
        assert (QE*4+3*ex-2*6*b)==5*QE*l
        for m in (42,14,70):   # cx^3 = -1
            out.append(('B',l,ex,m))
    return out
def A_zeros(b):
    out=[]
    for l in (0,1):
        ex=72+9*b-90*l
        assert QE*4+3*6*b-2*ex==5*QE*l
        for m in (84,42):      # cx^2 = 1 (Z^84 = 1 keeps zsimp uniform)
            out.append(('A',l,ex,m))
    return out
def gen(b):
    ey=6*b
    zs=B_zeros(b)
    As=A_zeros(b)
    pts=zs[:]
    for a in As:
        if len(pts)>=12: break
        if all(not ((a[2]-p[2])%180==0 and (a[3]-p[3])%84==0) for p in pts): pts.append(a)
    assert len(pts)==12
    s=[]
    nm=f'b{b}'
    s.append(f'''
/-! ## `y = −t^{{{ey}}}` -/

noncomputable abbrev F{nm} : ℤ → L := FS hq36 {ey} (-1)
''')
    cases=[]
    for i,(kind,l,ex,m) in enumerate(pts):
        t1=l%2; k1=(l+t1)//2
        cx=f'(Z84 ^ ({m} : ℤ))'
        thm=f'z{nm}_{i}'
        if kind=='B':
            s.append(f'''
theorem {thm} : ev F{nm} ({ex}) {cx} = 0 := by
  have hcx : {cx} ≠ 0 := zpow_ne_zero _ Z_ne
  have hB : eBT (qe := 36) {ey} ({ex}) = 5 * ((36 : ℕ) : ℤ) * {l} := by norm_num [eBT]
  have hc : cBT (-1) {cx} = 1 := by
    unfold cBT; rw [Z_neg1]; zsimp; first | exact Z_eq_one (by omega) | norm_num | (simp; exact Z_eq_one (by omega))
  unfold F{nm}
  rw [FS_ev_B hq36 {ey} _ (ℓ0 := {l}) (t1 := {t1}) (k1 := {k1}) hB hc hcx hm1 ⟨by norm_num, by norm_num⟩
      (by norm_num [lK]),
    brB_zero hq36 {ey} _ hB hc hcx hm1 (by norm_num [lK]) (by
      simp only [sig1, Msh, eTn, cTn, mono_mul]
      apply mono_add_zero
      · norm_num [eAT, c2]
      · unfold cAT; rw [Z_neg1]; zsimp; exact Z_mod (by first | omega | (ring_nf; omega)))]
  simp
''')
        else:
            s.append(f'''
theorem {thm} : ev F{nm} ({ex}) {cx} = 0 := by
  have hcx : {cx} ≠ 0 := zpow_ne_zero _ Z_ne
  have hA : eAT (qe := 36) {ey} ({ex}) = 5 * ((36 : ℕ) : ℤ) * {l} := by norm_num [eAT]
  have hc : cAT (-1) {cx} = 1 := by
    unfold cAT; rw [Z_neg1]; zsimp; first | exact Z_eq_one (by omega) | norm_num | (simp; exact Z_eq_one (by omega))
  unfold F{nm}
  rw [FS_ev_A hq36 {ey} _ (ℓ0 := {l}) (t1 := {t1}) (k1 := {k1}) hA hc hcx hm1 ⟨by norm_num, by norm_num⟩
      (by norm_num [lK]),
    brA_zero hq36 {ey} _ hA hc hcx hm1 (by norm_num [lK]) (by
      simp only [SA, sig2, Msh, eTn, cTn, mono_mul]
      apply mono_add_zero
      · norm_num [eBT, c2]
      · unfold cBT; rw [Z_neg1]; zsimp; exact Z_mod (by first | omega | (ring_nf; omega)))]
  simp
''')
        cases.append(f'  · exact {thm}')
    pe=', '.join(str(p[2]) for p in pts); pm=', '.join(str(p[3]) for p in pts)
    s.append(f'''
def pe{nm} : Fin 12 → ℤ := ![{pe}]
def pm{nm} : Fin 12 → ℤ := ![{pm}]

lemma zeros{nm} (i : Fin 12) : ev F{nm} (pe{nm} i) (Z84 ^ pm{nm} i) = 0 := by
  fin_cases i
{chr(10).join(cases)}

lemma dist{nm} : ∀ i j : Fin 12, i ≠ j → (pe{nm} i - pe{nm} j) % 180 = 0 → (pm{nm} i - pm{nm} j) % 84 ≠ 0 := by decide

theorem F{nm}_eq_zero : F{nm} = 0 :=
  zero_count (NQ := 5 * 36) (by norm_num) 11 (neg_ne_zero.mpr (zpow_ne_zero _ hm1))
    (FS_mem_Th hq36 {ey} (-1) (by simp)) pe{nm} (fun i => Z84 ^ pm{nm} i) (fun i => zpow_ne_zero _ Z_ne)
    (fun i j hij a ha => Z_ne_Z (dist{nm} i j hij (by rw [ha]; push_cast; omega))) zeros{nm}

/-- **HM Theorem 0.3 for `f_{{2,3,2}}` at `y = −t^{{{ey}}}`, `q = t^{{36}}`**, at every good `x`. -/
theorem hm03_{nm} (ex : ℤ) {{cx : ℂ}} (h : CGood (-1) cx) :
    Jb hq36 * ev (fS hq36 {ey} (-1)) ex cx =
      gNum hq36 {ey} (-1) ex cx + kap (h5 hq36) * thV hq36 {ey} (-1) ex cx := by
  have h1 := FS_ev hq36 {ey} (-1) ex hm1 h
  have h0 : ev F{nm} ex cx = 0 := by rw [F{nm}_eq_zero]; exact ev_zero ex _
  unfold F{nm} at h0
  rw [h0] at h1
  have := (mul_eq_zero.mp h1.symm).resolve_left (Pv_ne hq36 {ey} _ hm1 h ex)
  unfold Dv at this
  linear_combination this
''')
    return ''.join(s)
