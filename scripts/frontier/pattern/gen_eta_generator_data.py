#!/usr/bin/env python3
"""Produce S/T-word certificates for the level-six eta transformations.

The generated Lean files verify every matrix identity and phase divisibility
with `decide +kernel`. Python is only an untrusted certificate producer.
"""
from pathlib import Path
from math import gcd


def mul(a, b):
    return tuple(sum(a[2*i+k] * b[2*k+j] for k in range(2))
                 for i in range(2) for j in range(2))


def inv(a):
    return a[3], -a[1], -a[2], a[0]


ID, S = (1, 0, 0, 1), (0, -1, 1, 0)


def t(n):
    return 1, n, 0, 1


def word(a):
    if a[2] == 0:
        return [('t', a[1])] if a[0] == 1 else [('s', 0), ('s', 0), ('t', -a[1])]
    q = a[0] // a[2]
    reduced = mul(mul(inv(S), t(-q)), a)
    return [('t', q), ('s', 0)] + word(reduced)


def evaluate(w):
    a = ID
    for kind, n in w:
        a = mul(a, S if kind == 's' else t(n))
    return a


def exponent(w):
    return sum(-3 if kind == 's' else n for kind, n in w)


def cusp_data(reps, scales):
    """Factor diag(d,1) R = gamma [[A,B],[0,D]] over the integers."""
    data = []
    for i, r in enumerate(reps):
        for j, d in enumerate(scales):
            aa, cc = d*r[0], r[2]
            A = gcd(aa, cc)
            a, c = aa//A, cc//A
            # These fixed certificates have tiny coprime first columns.
            b, e = next((b, e) for b in range(-12, 13) for e in range(-12, 13)
                        if a*e-b*c == 1)
            gamma = a, b, c, e
            triangular = mul(inv(gamma), (aa, d*r[1], cc, r[3]))
            _, B, zero, D = triangular
            assert triangular[0] == A and zero == 0 and A > 0 and D > 0
            w = word(gamma)
            assert evaluate(w) == gamma
            data.append((i, j, A, B, D, w))
    lines = [
        'import RamanujanTau.TheoremA.EtaGeneratorData', '',
        '/-! Exact cusp factorizations; generated by',
        '`scripts/frontier/pattern/gen_eta_generator_data.py`. -/', '',
        'set_option autoImplicit false', '',
        'namespace RamanujanTau.TheoremA.EtaSquared', '',
    ]
    for name, column in [('cuspA', 2), ('cuspB', 3), ('cuspD', 4)]:
        lines += [f'def {name} (i : Fin 12) (j : Fin 4) : ℤ :=',
                  '  match i.val, j.val with']
        lines += [f'  | {x[0]}, {x[1]} => {x[column]}' for x in data]
        lines += ['  | _, _ => 1', '']
    lines += ['def cuspWord (i : Fin 12) (j : Fin 4) : List Step :=',
              '  match i.val, j.val with']
    for i, j, A, B, D, w in data:
        steps = ', '.join('.s' if k == 's' else f'.t ({n})' for k, n in w)
        lines.append(f'  | {i}, {j} => [{steps}]')
    lines += ['  | _, _ => []', '',
        'theorem cusp_positive (i : Fin 12) (j : Fin 4) :',
        '    0 < cuspA i j ∧ 0 < cuspD i j := by revert i j; decide +kernel', '',
        'theorem cusp_factorization (i : Fin 12) (j : Fin 4) :',
        '    let γ := wordMatrix (cuspWord i j)',
        '    let R := LevelSix.rep i',
        '    (dilation j : ℤ) * R 0 0 = γ 0 0 * cuspA i j ∧',
        '    (dilation j : ℤ) * R 0 1 = γ 0 0 * cuspB i j + γ 0 1 * cuspD i j ∧',
        '    R 1 0 = γ 1 0 * cuspA i j ∧',
        '    R 1 1 = γ 1 0 * cuspB i j + γ 1 1 * cuspD i j := by',
        '  revert i j', '  decide +kernel', '',
        'theorem cusp_rate_positive (a : Fin 3) (i : Fin 12) :',
        '    (0 : ℚ) < ∑ j : Fin 4, (basisExponent a j : ℚ) * cuspA i j / cuspD i j := by',
        '  revert a i', '  decide +kernel', '',
        'end RamanujanTau.TheoremA.EtaSquared', '',
    ]
    target = Path(__file__).resolve().parents[3] / 'RamanujanTau/TheoremA/EtaCuspData.lean'
    target.write_text('\n'.join(lines))


def main():
    reps = [ID] + [mul(S, t(j)) for j in range(6)]
    reps += [mul((1, 0, 2, 1), t(j)) for j in range(3)]
    reps += [mul((1, 0, 3, 1), t(j)) for j in range(2)]
    permutations = [[1, 0, 6, 9, 10, 7, 2, 5, 11, 3, 4, 8],
                    [0, 2, 3, 4, 5, 6, 1, 8, 9, 7, 11, 10]]
    scales = [1, 2, 3, 6]
    exponents = [[3, 0, 3, 0], [0, 3, 0, 3], [2, -1, -2, 7]]
    cusp_data(reps, scales)
    lines = [
        'import RamanujanTau.TheoremA.EtaRescale',
        'import RamanujanTau.TheoremA.LevelSixGenerators', '',
        '/-! Exact finite word certificates; regenerate with',
        '`scripts/frontier/pattern/gen_eta_generator_data.py`. -/', '',
        'set_option autoImplicit false', '',
        'namespace RamanujanTau.TheoremA.EtaSquared',
        'open scoped MatrixGroups', '',
        'def dilation (j : Fin 4) : ℕ :=',
        '  match j.val with | 0 => 1 | 1 => 2 | 2 => 3 | _ => 6', '',
        'theorem dilation_pos (j : Fin 4) : 0 < dilation j := by revert j; decide', '',
        'def basisExponent (a : Fin 3) (j : Fin 4) : ℤ :=',
        '  match a.val, j.val with',
        '  | 0, 0 => 3 | 0, 2 => 3 | 1, 1 => 3 | 1, 3 => 3',
        '  | 2, 0 => 2 | 2, 1 => -1 | 2, 2 => -2 | 2, 3 => 7 | _, _ => 0', '',
        'def generatorWord (b : Bool) (i : Fin 12) (j : Fin 4) : List Step :=',
        '  match b, i.val, j.val with',
    ]
    for b, gen in enumerate([S, t(1)]):
        for i, r in enumerate(reps):
            g = mul(mul(r, gen), inv(reps[permutations[b][i]]))
            assert g[2] % 6 == 0
            phases = []
            for j, d in enumerate(scales):
                a = g[0], d*g[1], g[2]//d, g[3]
                w = word(a)
                assert evaluate(w) == a
                phases.append(exponent(w))
                body = ', '.join('.s' if kind == 's' else f'.t ({n})' for kind, n in w)
                lines.append(f'  | {str(bool(b)).lower()}, {i}, {j} => [{body}]')
            for e in exponents:
                assert sum(x*y for x, y in zip(e, phases)) % 12 == 0
    lines += [
        '  | _, _, _ => []', '',
        'theorem dilation_dvd_generator (b : Bool) (i : Fin 12) (j : Fin 4) :',
        '    (dilation j : ℤ) ∣ LevelSix.generator (b, i) 1 0 := by',
        '  revert b i j',
        '  decide +kernel', '',
        'theorem generatorWord_matrix (b : Bool) (i : Fin 12) (j : Fin 4) :',
        '    wordMatrix (generatorWord b i j) = rescale (dilation j)',
        '      (LevelSix.generator (b, i)) (dilation_dvd_generator b i j) := by',
        '  revert b i j',
        '  decide +kernel', '',
        'theorem basisExponent_sum (a : Fin 3) : ∑ j : Fin 4, basisExponent a j = 6 := by',
        '  revert a',
        '  decide +kernel', '',
        'theorem generator_phase_dvd (a : Fin 3) (b : Bool) (i : Fin 12) :',
        '    (12 : ℤ) ∣ ∑ j : Fin 4, wordExponent (generatorWord b i j) * basisExponent a j := by',
        '  revert a b i',
        '  decide +kernel', '',
        'end RamanujanTau.TheoremA.EtaSquared', '',
    ]
    target = Path(__file__).resolve().parents[3] / 'RamanujanTau/TheoremA/EtaGeneratorData.lean'
    target.write_text('\n'.join(lines))
    print('Generated 96 matrix words, 72 phase checks, and 48 cusp factorizations.')


if __name__ == '__main__':
    main()
