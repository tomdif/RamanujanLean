"""Write RamanujanTau/JensenThreshold/Data{d}.lean and Jensen{d}.lean from certs_d{d}.json (finite_check.py).

Data{d}.lean : the packed table literal tab{d} = sum_{m<=NT} p(m) 2^{mB}, chunked certificate lists, Laguerre point.
Jensen{d}.lean: kernel checks (`decide +kernel`): ptP B NT = tab{d} with range flag; one theorem per chunk; assembly.
"""
import json, sys
from math import comb
d = int(sys.argv[1]); CH = 100
C = json.load(open('certs_d%d.json' % d))
N, n0, fail = C['N'], C['n0'], C['fail_n']
certs = C['sign_certs']
NT = n0 - 1 + d
# exact p(m)
P = [0]*(NT+1); P[0] = 1
for n in range(1, NT+1):
    s = 0; k = 1
    while True:
        g1 = k*(3*k-1)//2
        if g1 > n: break
        g2 = k*(3*k+1)//2
        t = P[n-g1] + (P[n-g2] if g2 <= n else 0)
        s += t if k % 2 else -t
        k += 1
    P[n] = s
B = P[NT].bit_length() + 8
tab = sum(P[m] << (m*B) for m in range(NT+1))
chunks = [(lo, min(lo+CH, n0)) for lo in range(N, n0, CH)]
u, v = C['laguerre_x0']
SEG = 200
segs = list(range(0, NT, SEG)) + [NT]          # M_0 = 0 < M_1 < ... < M_last = NT
def tabM(M): return sum(P[m] << (m*B) for m in range(M+1))
D = ["/-", f"Certificate data for degree {d} (generated by scripts/jensen/gen_lean.py from certs_d{d}.json).",
     f"* `tab{d}` : the packed table Σ_{{m ≤ {NT}}} p(m)·2^{{{B}m}} (checked against `ptP {B} {NT}` in Jensen{d}.lean).",
     f"* `certs{d}_k` : for n = lo + i, points xₖ = −uₖ/vₖ at which J^{{{d},n}} alternates in sign.",
     f"* `lagPt{d}` : Laguerre failure point for n = {fail}.", "-/", "set_option autoImplicit false", "",
     "namespace JensenThreshold", ""]
for i, M in enumerate(segs[1:-1], 1):
    D += [f"/-- packed table p(0..{M}). -/", f"def tab{d}_s{i} : Nat := {tabM(M)}", ""]
D += [f"/-- packed table p(0..{NT}). -/", f"def tab{d} : Nat := {tab}", ""]
for ci, (lo, hi) in enumerate(chunks):
    rows = ['[' + ', '.join('(%d, %d)' % (a, b) for a, b in certs[str(n)]) + ']' for n in range(lo, hi)]
    D.append(f"/-- certificates for n = {lo}, …, {hi-1}. -/")
    D.append(f"def certs{d}_{ci} : List (List (Nat × Nat)) := [\n  " + ',\n  '.join(rows) + "]\n")
D += [f"def lagPt{d} : Nat × Nat := ({u}, {v})", "", "end JensenThreshold", ""]
open('../../RamanujanTau/JensenThreshold/Data%d.lean' % d, 'w').write('\n'.join(D))

L = ["/-", f"# Degree-{d} Jensen polynomials of p(n): finite range and last failure, by kernel computation", "",
     f"* `jensen{d}_finite` : `J^{{{d},n}}` is hyperbolic for every `{N} ≤ n ≤ {n0-1}` (sign-alternation certificates).",
     f"* `jensen{d}_fails`  : `J^{{{d},{fail}}}` is not hyperbolic (Laguerre's inequality fails at `x = −{u}/{v}`).",
     f"* `jensen{d}_threshold` : given the named tail hypothesis `JensenTail {d} {n0}` (proved on paper with certified",
     "  interval arithmetic, `scripts/jensen/tail_cert.py`, `docs/JENSEN_THRESHOLDS.md`), `J^{d,n}` is hyperbolic for",
     f"  all `n ≥ {N}` and not at `n = {fail}`.",
     f"The table `p(0..{NT})` is computed once by the kernel (`tab{d}_spec`) and then used as a literal.", "-/",
     "import RamanujanTau.JensenThreshold.Cert", f"import RamanujanTau.JensenThreshold.Data{d}", "",
     "set_option autoImplicit false", "", "namespace JensenThreshold", "",
     ]
names = ["⟨1, true⟩"] + [f"⟨tab{d}_s{i}, true⟩" for i in range(1, len(segs)-1)] + [f"⟨tab{d}, true⟩"]
for i in range(len(segs)-1):
    L += [f"theorem seg{d}_{i} : iterPT {B} {segs[i]} {names[i]} {segs[i+1]-segs[i]} = {names[i+1]} := by decide +kernel", ""]
L += [f"theorem tab{d}_eq : ptP {B} {NT} = ⟨tab{d}, true⟩ := by",
      f"  have h0 : ptP {B} 0 = ⟨1, true⟩ := rfl"]
for i in range(len(segs)-1):
    L += [f"  have h{i+1} : ptP {B} {segs[i+1]} = {names[i+1]} := ptP_of_seg (by norm_num) h{i} seg{d}_{i}"]
L += [f"  exact h{len(segs)-1}", "",
      f"theorem tab{d}_spec : (ptP {B} {NT}).T = tab{d} ∧ (ptP {B} {NT}).ok = true := by",
      f"  rw [tab{d}_eq]; exact ⟨rfl, rfl⟩", "",
     f"lemma look{d} {{m : ℕ}} (hm : m ≤ {NT}) : look {B} tab{d} m = pc m := by",
     f"  rw [← tab{d}_spec.1]; exact ptP_spec (by norm_num) tab{d}_spec.2 hm", "",
     f"lemma hyp{d}_of_check {{n : ℕ}} (hn : n + {d} ≤ {NT}) (pts : List (ℕ × ℕ))",
     f"    (h : checkPts {B} tab{d} {d} n pts = true) : Hyperbolic (jensen {d} n) := by",
     f"  rw [← tab{d}_spec.1] at h",
     f"  exact hyperbolic_of_checkPts (by norm_num) tab{d}_spec.2 hn pts h", ""]
for ci, (lo, hi) in enumerate(chunks):
    L += [f"theorem chunk{d}_{ci} : checkAll {B} tab{d} {d} {lo} certs{d}_{ci} = true := by decide +kernel", "",
          f"theorem len{d}_{ci} : certs{d}_{ci}.length = {hi-lo} := by decide +kernel", "",
          f"theorem jensen{d}_range{ci} {{n : ℕ}} (h1 : {lo} ≤ n) (h2 : n < {hi}) : Hyperbolic (jensen {d} n) := by",
          f"  have := checkAll_spec certs{d}_{ci} {lo} chunk{d}_{ci} (n - {lo}) (by rw [len{d}_{ci}]; omega)",
          f"  rw [show {lo} + (n - {lo}) = n by omega] at this",
          f"  exact hyp{d}_of_check (by omega) _ this", ""]
L += [f"theorem jensen{d}_finite {{n : ℕ}} (h1 : {N} ≤ n) (h2 : n ≤ {n0-1}) : Hyperbolic (jensen {d} n) := by"]
for ci, (lo, hi) in enumerate(chunks):
    if ci < len(chunks) - 1:
        L += [f"  rcases Nat.lt_or_ge n {hi} with c{ci} | c{ci}", f"  · exact jensen{d}_range{ci} (by omega) c{ci}"]
    else:
        L += [f"  exact jensen{d}_range{ci} (by omega) (by omega)"]
L += ["", f"theorem jensen{d}_fails : ¬ Hyperbolic (jensen {d} {fail}) := by",
      f"  have h : lagOK {B} tab{d} {d} {fail} lagPt{d}.1 lagPt{d}.2 = true := by decide +kernel",
      f"  rw [← tab{d}_spec.1] at h",
      f"  exact not_hyperbolic_of_lagOK (by norm_num) tab{d}_spec.2 (by norm_num) (by norm_num) _ _ h", "",
      f"/-- **Jensen threshold `N({d}) = {N}`**, conditional only on the named tail hypothesis `JensenTail {d} {n0}`. -/",
      f"theorem jensen{d}_threshold (htail : JensenTail {d} {n0}) :",
      f"    (∀ n, {N} ≤ n → Hyperbolic (jensen {d} n)) ∧ ¬ Hyperbolic (jensen {d} {fail}) := by",
      f"  refine ⟨fun n hn => ?_, jensen{d}_fails⟩",
      f"  rcases Nat.lt_or_ge n {n0} with h | h",
      f"  · exact jensen{d}_finite hn (by omega)",
      f"  · exact htail n h", "", "end JensenThreshold", ""]
open('../../RamanujanTau/JensenThreshold/Jensen%d.lean' % d, 'w').write('\n'.join(L))
print('d=%d: B=%d, NT=%d, %d chunks, Laguerre point (%d,%d)' % (d, B, NT, len(chunks), u, v))
