#!/usr/bin/env python3
"""Generate RamanujanTau/OnoWeaverMore/Instances<ell>.lean from scan500.json (scan.py output):
one kernel-certified partition prefix per ell, then one theorem per (ell, Q, eps).
Usage: gen_instances.py SCANJSON OUTDIR"""
import json, sys
from sympy import legendre_symbol

C = {13: 11, 17: 7, 19: 5, 23: 1}
EXISTING = {(13, 59), (13, 73), (17, 41), (17, 89), (17, 103), (19, 101), (23, 5), (23, 19), (23, 37), (23, 47), (23, 67)}
# headline progressions: (ell, Q)
HEAD = {(17, 23), (19, 13), (29, 17), (31, 101), (13, 97), (23, 107)}

def pentLow(j): return (j + 1) * (3 * (j + 1) - 1) // 2

def params(ell, Npre):
    k = 1
    while pentLow(k * 256) < Npre: k += 1
    kN = Npre.bit_length(); n = kN
    ku = (ell - 1).bit_length(); kb = 18; kc = ku + kb + kN
    assert ku + kb + kN < 64 and k * 256 <= 2 ** 20 and 2 ** 22 + ell * 2 ** kc <= 2 ** 64 and Npre <= 2 ** kN
    R = ell * (2 ** 18 // ell)
    return R, 8, k, n, ku, kb, kc, kN

def gen(r):
    ell = r['ell']; delta = r['delta']; lam = r['lam']; N0 = r['N0']
    pairs = []
    for x in r['res']:
        if not x.get('type'): continue
        t = x['type'][0]; e = 0 if t == 'ono' else (1 if t == 'atkin+' else -1)
        pairs.append((x['Q'], e))
    idx = []
    for Q, e in pairs:
        d = (Q * Q - 1) * ell // 24
        idx += [ell * (Q * Q * N0 - d) - delta, ell * N0 - delta]
        if (N0 + d) % (Q * Q) == 0: idx.append(ell * ((N0 + d) // (Q * Q)) - delta)
    Npre = max(idx) + 1
    R, d8, k, n, ku, kb, kc, kN = params(ell, Npre)
    L = '[' + ', '.join(f'({Q}, {e})' for Q, e in pairs) + ']'
    w = []
    big = ell > 23
    w.append(f'''import RamanujanTau.OnoWeaverMore.{"Eigen2931" if big else "Core"}

/-!
# Ono–Weaver congruences modulo {ell}, both types, for primes `Q < 500`

Generated by `scripts/onoweavermore/gen_instances.py` from `scan.py` (exact `p(n) mod {ell}`).
One kernel-certified prefix of {Npre:,} partition numbers modulo {ell} (`all{ell}`) supplies the
coefficient `q^{N0}` of `T(Q²) Σ p({ell}N − {delta}) q^N` for every `Q` in the list; the eigen-relation is
{"`eigen_" + str(ell) + "` (Shimura lift + dimension-one certificate at weight " + str(ell - 3) + ")" if big else "`EigenLift.etaHeckeMod_" + str(ell) + "` (Shimura lift + dimension-one certificate)"}.
Pairs `(Q, ε)`: `ε = 0` is Ono's type (`{ell} ∣ p(({ell}Q³n+1)/24)`, `Q ∤ n`), `ε = ±1` is Atkin's
type (`{ell} ∣ p(({ell}Q²m+1)/24)` whenever `(m/Q) = ε`).
-/

set_option autoImplicit false

namespace RamanujanTau.OnoWeaverMore.L{ell}
open PowerSeries BoylanWebb RamanujanTau.OnoWeaverMore

instance factL : Fact (Nat.Prime {ell}) := ⟨by norm_num⟩

/-- The pairs `(Q, ε)` certified modulo {ell}. -/
def pairs : List (ℕ × ℤ) := {L}

set_option maxRecDepth 100000 in
/-- **The kernel certificate**: one partition prefix, all pairs. -/
theorem all{ell} : allOk {ell} {R} {Npre} {d8} {k} {n} {ku} {kb} {kc} {N0} pairs = true := by
  decide +kernel

theorem coeff_ok (Q : ℕ) [Fact Q.Prime] (ε : ℤ) (hmem : (Q, ε) ∈ pairs) :
    coeff {N0} (TT {ell} Q (Ψ {ell} (Pser {ell} 1))) = muE {ell} Q ε * coeff {N0} (Ψ {ell} (Pser {ell} 1)) ∧
      coeff {N0} (Ψ {ell} (Pser {ell} 1)) ≠ 0 :=
  allOk_sound {ell} (by norm_num) (by decide) (kN := {kN}) (by norm_num) (by norm_num) (by norm_num)
    (by norm_num) (by norm_num) (by decide) all{ell} Q ε hmem
''')
    if big:
        w.append(f'''theorem eigen (Q : ℕ) [Fact Q.Prime] (hQ5 : 5 ≤ Q) (ε : ℤ) (hmem : (Q, ε) ∈ pairs) :
    TT {ell} Q (Ψ {ell} (Pser {ell} 1)) = C (muE {ell} Q ε) * Ψ {ell} (Pser {ell} 1) :=
  eigen_of_exists {ell} Q {N0} _ (eigen_{ell} Q hQ5) (coeff_ok Q ε hmem)
''')
    else:
        w.append(f'''theorem eigen (Q : ℕ) [Fact Q.Prime] (hQ5 : 5 ≤ Q) (ε : ℤ) (hmem : (Q, ε) ∈ pairs) :
    TT {ell} Q (Ψ {ell} (Pser {ell} 1)) = C (muE {ell} Q ε) * Ψ {ell} (Pser {ell} 1) :=
  eigen_of_etaHecke {ell} Q (by norm_num) (by norm_num) Cert{ell}.h24 Cert{ell}.f Cert{ell}.form_f
    (by rw [← coeff_zero_eq_constantCoeff_apply]; exact Cert{ell}.coeff_zero_f)
    (((({C[ell]} : ℤ)) : ZMod {ell})) (by decide) Cert{ell}.eigen.1
    (RamanujanTau.AtkinSporadic.EigenLift.etaHeckeMod_{ell} hQ5) _ (coeff_ok Q ε hmem).1
''')
    h24 = 'h24' if not big else 'h24'
    thm_names = []
    for Q, e in pairs:
        tag = '' if (ell, Q) not in EXISTING else ' (already in `AtkinSporadic.WeaverUnconditional`; reproved here)'
        w.append(f'instance factQ{Q} : Fact (Nat.Prime {Q}) := ⟨by norm_num⟩\n')
        if e == 0:
            name = f'ono_{ell}_{Q}'
            w.append(f'''/-- `p(({ell}·{Q}³n+1)/24) ≡ 0 (mod {ell})` for `{Q} ∤ n`{tag}. -/
theorem {name} (n : ℕ) (hn : ¬ {Q} ∣ n) (h : 24 ∣ {ell} * {Q} ^ 3 * n + 1) :
    {ell} ∣ Fintype.card (Nat.Partition (({ell} * {Q} ^ 3 * n + 1) / 24)) :=
  ono_of_eigen {ell} (by decide) {Q} (by norm_num) (eigen {Q} (by norm_num) 0 (by decide)) n hn h
''')
        else:
            name = f'atkin_{ell}_{Q}'
            sgn = '1' if e == 1 else '(-1)'
            w.append(f'''/-- Atkin type: `p(({ell}·{Q}²m+1)/24) ≡ 0 (mod {ell})` whenever `(m/{Q}) = {sgn}`{tag}. -/
theorem {name} (m : ℕ) (hm : 24 ∣ {ell} * {Q} ^ 2 * m + 1) (hQm : legendreSym {Q} m = {sgn}) :
    {ell} ∣ Fintype.card (Nat.Partition (({ell} * {Q} ^ 2 * m + 1) / 24)) :=
  atkin_of_eigen {ell} (by decide) {Q} (by norm_num) {sgn} (by norm_num)
    (eigen {Q} (by norm_num) {sgn} (by decide)) m hm hQm
''')
            if (ell, Q) in HEAD:
                # smallest progression
                M = ell * Q * Q
                for rr in range(1, 24 * M):
                    if (24 * rr - 1) % M == 0:
                        m0 = (24 * rr - 1) // M
                        if m0 % Q and legendre_symbol(m0 % Q, Q) == e: break
                w.append(f'''/-- Explicit progression: `{ell} ∣ p({ell * Q**3}n + {rr})` for all `n`
(`24·{rr} − 1 = {ell}·{Q}²·{m0}`, `({m0}/{Q}) = {e}`). -/
theorem {name}_progression (n : ℕ) : {ell} ∣ Fintype.card (Nat.Partition ({ell * Q**3} * n + {rr})) := by
  have h := {name} ({m0} + {24 * Q} * n) (by norm_num; omega) (by
    rw [legendreSym.mod]
    have : (((({m0} + {24 * Q} * n : ℕ)) : ℤ) % ({Q} : ℕ)) = {m0 % Q} := by push_cast; omega
    rw [this, RamanujanTau.AtkinSporadic.legendreSym_val {Q} (by norm_num)]
    decide)
  have e : ({ell} * {Q} ^ 2 * ({m0} + {24 * Q} * n) + 1) / 24 = {ell * Q**3} * n + {rr} := by
    norm_num; omega
  rwa [e] at h
''')
        thm_names.append(name)
    w.append(f'end RamanujanTau.OnoWeaverMore.L{ell}\n')
    return '\n'.join(w), thm_names, Npre

if __name__ == '__main__':
    data = json.load(open(sys.argv[1])); outdir = sys.argv[2]
    allnames = []
    for r in data:
        src, names, Npre = gen(r)
        open(f"{outdir}/Instances{r['ell']}.lean", 'w').write(src)
        allnames += [f"RamanujanTau.OnoWeaverMore.L{r['ell']}.{n}" for n in names]
        print(r['ell'], 'Npre', Npre, 'pairs', len(names), file=sys.stderr)
    json.dump(allnames, open(f"{outdir}/../../scripts/onoweavermore/theorem_names.json", 'w'))
