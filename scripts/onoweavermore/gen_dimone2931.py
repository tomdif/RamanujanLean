#!/usr/bin/env python3
"""Generate RamanujanTau/OnoWeaverMore/DimOneData2931.lean (dimension-one certificates at
ell = 29, 31, basis precision q^40). Usage: gen_dimone2931.py > ../../RamanujanTau/OnoWeaverMore/DimOneData2931.lean"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from dimcert2931 import certificate

def lst(v): return '[' + ', '.join(str(x) for x in v) + ']'
out = ['''import RamanujanTau.OnoWeaverMore.DimOne40

/-!
# Dimension-one certificates for ℓ = 29, 31 (weights 26, 28)

Generated by `scripts/onoweavermore/gen_dimone2931.py`. Each `certℓ` is checked by the kernel
(`decide +kernel`): the basis lists agree with `LevelSix40.basisL` (eta-product certified through
`q⁴⁰`), the rows are admissible, and `K L = d·I`.
-/

set_option autoImplicit false

namespace RamanujanTau.OnoWeaverMore.DimOne40
open RamanujanTau.TheoremA.SignLattice LevelSix40
open RamanujanTau.AtkinSporadic.DimOne (DimOneProp)
''']
for ell in [29, 31]:
    c = certificate(ell, 40)
    rows = '[' + ', '.join(f'({k}, {m})' for k, m in c['rows']) + ']'
    basis = '[' + ',\n    '.join(lst(c['E'][i][:41]) for i in range(c['n'])) + ']'
    Ks = '[' + ',\n    '.join(lst(r) for r in c['K']) + ']'
    out.append(f'''
instance fact{ell} : Fact (Nat.Prime {ell}) := ⟨by norm_num⟩

def cert{ell} : DimCert where
  e2 := {c['e2']}
  e3 := {c['e3']}
  basis := {basis}
  rows := {rows}
  K := {Ks}
  d := {c['d']}

theorem cert{ell}_basis : ∀ i : Fin (2 * halfWt {ell} + 1), cert{ell}.basis.getD i [] = basisL (halfWt {ell}) i := by
  decide +kernel

theorem cert{ell}_rows : ∀ r : Fin (2 * halfWt {ell} + 1), DimCert.rowOK (cert{ell}.rows.getD r (0, 0)) = true := by
  decide +kernel

theorem cert{ell}_inv : ∀ k i : Fin (2 * halfWt {ell} + 1),
    ∑ r : Fin (2 * halfWt {ell} + 1), cert{ell}.Kent k r * cert{ell}.Lrow r i = if k = i then cert{ell}.d else 0 := by
  decide +kernel

theorem eig2_{ell} : eig2 {ell} = cert{ell}.e2 := by
  rw [eig2, jacobiSym.legendreSym.to_jacobiSym]; norm_num [cert{ell}]

theorem eig3_{ell} : eig3 {ell} = cert{ell}.e3 := by
  rw [eig3, jacobiSym.legendreSym.to_jacobiSym]; norm_num [cert{ell}]

/-- **`W` is detected by `b(1)` at ℓ = {ell}** (weight {ell - 3}). -/
theorem dimOne_{ell} : DimOneProp {ell} :=
  DimCert.sound cert{ell} eig2_{ell} eig3_{ell} cert{ell}_basis cert{ell}_rows cert{ell}_inv (by decide)
''')
out.append('\nend RamanujanTau.OnoWeaverMore.DimOne40\n')
print('\n'.join(out))
