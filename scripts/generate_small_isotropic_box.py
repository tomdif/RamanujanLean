#!/usr/bin/env python3
"""Generate the small mod-three box certificates checked by Lean's kernel."""
from itertools import combinations, product
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def det(x, y, z):
    return (x[0]*(y[1]*z[2]-y[2]*z[1])
            - x[1]*(y[0]*z[2]-y[2]*z[0])
            + x[2]*(y[0]*z[1]-y[1]*z[0]))


def generators(q):
    a, b, c, d, e, f = q
    if (a*b*c+2*d*e*f-a*f*f-b*e*e-c*d*d) % 3 == 0:
        return []
    vs = [v for v in product(range(-2, 3), range(-2, 3), (0, 1))
          if any(t % 3 for t in v) and
          (a*v[0]**2+b*v[1]**2+c*v[2]**2+2*d*v[0]*v[1]
           +2*e*v[0]*v[2]+2*f*v[1]*v[2]) % 3 == 0]
    # All nonsingular forms admit a unimodular triple in this box.
    # Choosing it makes each kernel certificate a single determinant.
    for triple in combinations(vs, 3):
        if abs(det(*triple)) == 1:
            return list(triple)
    raise AssertionError(q)


def main():
    entries = []
    for code in range(729):
        q = tuple(code // (3**i) % 3 for i in range(6))
        vs = generators(q)
        if vs:
            coordinates = '[' + ', '.join(f'(({x}, {y}), {z})' for x, y, z in vs) + ']'
            entries.append('| ' + ', '.join(map(str, q)) + ' => ' + coordinates)
    data = '\n  '.join(entries)
    source = '''/-
# A small integral generating box for every nonsingular ternary form mod 3

The finite certificates are generated by scripts/generate_small_isotropic_box.py.
The kernel checks their coordinates, isotropy, and determinant gcd. The
integral spanning conclusion follows from the proved Bezout/minor theorem.
-/
import RamanujanTau.MultiQuintupleIntegralSpan

namespace Ramanujan.MultiQuintuple

def ternaryGramDetThree (a b c d e f : ZMod 3) : ZMod 3 :=
  a*b*c+2*d*e*f-a*f^2-b*e^2-c*d^2

def InSmallIsotropicBox (a b c d e f : ZMod 3) (x : TernaryIntPoint) : Prop :=
  -2 ≤ x.1.1 ∧ x.1.1 ≤ 2 ∧ -2 ≤ x.1.2 ∧ x.1.2 ≤ 2 ∧
  (x.2 = 0 ∨ x.2 = 1) ∧
  (x.1.1 % 3 ≠ 0 ∨ x.1.2 % 3 ≠ 0 ∨ x.2 % 3 ≠ 0) ∧
  a*(x.1.1 : ZMod 3)^2+b*(x.1.2 : ZMod 3)^2+c*(x.2 : ZMod 3)^2+
    2*d*x.1.1*x.1.2+2*e*x.1.1*x.2+2*f*x.1.2*x.2 = 0

set_option maxRecDepth 100000 in
set_option maxHeartbeats 0 in
def smallBoxGenerators (a b c d e f : ZMod 3) : List TernaryIntPoint :=
  match a.val, b.val, c.val, d.val, e.val, f.val with
  DATA
  | _, _, _, _, _, _ => []

set_option maxRecDepth 100000 in
set_option maxHeartbeats 0 in
private theorem smallBoxCertificates :
    ∀ a b c d e f : ZMod 3, ternaryGramDetThree a b c d e f ≠ 0 →
      generatorDetGcd (smallBoxGenerators a b c d e f) = 1 ∧
      ∀ x ∈ smallBoxGenerators a b c d e f, InSmallIsotropicBox a b c d e f x := by
  unfold InSmallIsotropicBox
  decide +kernel

/-- The small coefficient box generates Z^3 for every nonsingular ternary
Gram form modulo three. This is an integral, not just rational, span. -/
theorem small_isotropic_box_span_eq_top
    (a b c d e f : ZMod 3) (hdet : ternaryGramDetThree a b c d e f ≠ 0) :
    Submodule.span ℤ {x | InSmallIsotropicBox a b c d e f x} = ⊤ := by
  obtain ⟨hgcd,hmem⟩ := smallBoxCertificates a b c d e f hdet
  apply top_unique
  rw [← span_list_eq_top_of_generatorDetGcd (smallBoxGenerators a b c d e f) hgcd]
  exact Submodule.span_mono (fun x hx => hmem x hx)

end Ramanujan.MultiQuintuple
'''.replace('DATA', data)
    path = ROOT / 'RamanujanTau/MultiQuintupleSmallIsotropicBox.lean'
    path.write_text(source)
    print(f'Wrote {len(entries)} finite Gram entries to {path.name}')


if __name__ == '__main__':
    main()
