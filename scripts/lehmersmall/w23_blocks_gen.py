# Generates RamanujanTau/LehmerSmall/W23Blk*.lean and Lehmer1947.lean (block values of the
# pentagonal double sum for tau(p) mod 23 at Lehmer's two candidate primes). Run from repo root.
from math import isqrt
def pcfR(k,r):
    if r*r!=24*k+1: return 0
    if r%6==5: return (-1)**((r+1)//6)
    if r%6==1: return (-1)**((r-1)//6)
    return 0
pc=lambda k: pcfR(k,isqrt(24*k+1))
lo=lambda m:(m+1)*(3*m+2)//2; hi=lambda m:(m+1)*(3*m+4)//2
def term(N,m):
    t=0
    if 23*lo(m)<=N: t+=pc(N-23*lo(m))
    if 23*hi(m)<=N: t+=pc(N-23*hi(m))
    return (-1)**(m+1)*t
def J1(N):
    J=0
    while 23*lo(J)<=N: J+=1
    return J
L=2000; PER=6
primes=[('A',21492863999),('B',75225023999)]
info={}
for tag,p in primes:
    N=p-1; J=J1(N); blocks=[]
    a=0
    while a<J:
        n=min(L,J-a); v=sum(term(N,m) for m in range(a,a+n)); blocks.append((a,n,v)); a+=n
    files=[blocks[i:i+PER] for i in range(0,len(blocks),PER)]
    names=[]
    for fi,bl in enumerate(files):
        mod=f"W23Blk{tag}{fi}"; names.append(mod)
        with open(f"RamanujanTau/LehmerSmall/{mod}.lean","w") as f:
            f.write("import RamanujanTau.LehmerSmall.Wilton23Pent\n\n/-! GENERATED by w23_blocks_gen.py: kernel-checked block sums for `p = %d`. -/\n\nnamespace RamanujanTau.LehmerSmall\n\n"%p)
            for (a0,n,v) in bl:
                f.write(f"theorem blk{tag}_{a0} : rsum (termC 23 {N}) {a0} {n} = {v} ∧ rall (okC 23 {N}) {a0} {n} = true := by\n  decide +kernel\n\n")
            f.write("end RamanujanTau.LehmerSmall\n")
    total=sum(v for _,_,v in blocks)
    info[tag]=dict(p=p,N=N,J=J,blocks=blocks,mods=names,total=total,pcN=pc(N),a=(pc(N)+total))
    print(tag,p,J,len(blocks),total,pc(N),pc(N)+total)
import json; json.dump({k:{kk:vv for kk,vv in v.items()} for k,v in info.items()},open("/tmp/w23info.json","w"))
