q = mono(1)
def Gk(k, s=1): return G(k, s)
def Hk(k, s=1): return H(k, s)
def Uf(k=1, s=1):  # U(s q^k)
    return sub(mul(Gk(17*k, s**17), Hk(2*k)), sc(s**(3), mul(mono(3*k), mul(Gk(2*k), Hk(17*k, s**17)))))
def Vf(k=1, s=1):
    return add(mul(Gk(k, s), Gk(34*k)), sc(s**7, mul(mono(7*k), mul(Hk(k, s), Hk(34*k)))))
a1, a2, b1, b2 = chi(1), chi(1, -1), chi(17), chi(17, -1)
