X2 = mono(2)
def chk(name, l, r): print(name, eq(l, r, 250))
chk('hc', mul(a1, a2), c); chk('hd', mul(b1, b2), d)
chk('h14', mul(U, b2), mul(V, a2)); chk('h14m', mul(Um, b1), mul(Vm, a1))
chk('h14q2', mul(Uq2, d), mul(Vq2, c)); chk('h14m2', mul(Um2, e2), mul(Vm2, e1)); chk('h14q4', mul(U4, d4), mul(V4, c4))
