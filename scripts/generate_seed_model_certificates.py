#!/usr/bin/env python3
"""Generate Lean certificates for the saved finite models, not their arithmetic identification."""
import json
from pathlib import Path
from flint import nmod_mat

ROOT = Path(__file__).resolve().parents[1]
data = json.loads((ROOT / 'docs/verification/seed_survival_extended.json').read_text())
text = '''import RamanujanTau.FiniteArithmetic.SeedSurvival

/-!
# Checked survival in five saved finite Katz models

The matrices and seeds are checked here as finite algebraic objects. Their
identification with the actual second-order partition operator remains open.
Thus these theorems do not assert partition stabilization at these primes.
Generated by scripts/generate_seed_model_certificates.py.
-/
namespace RamanujanTau.FiniteArithmetic.SeedModels
set_option maxRecDepth 4096
set_option maxHeartbeats 0

'''
for rec in data['results']:
    if rec['katz_cutoff'] != 3:
        continue
    p, n = rec['prime'], rec['dim_kernel']
    T = rec['theta_matrix']
    B = nmod_mat(T, p).inv()
    inv = [[int(B[i, j]) for j in range(n)] for i in range(n)]
    for name, matrix in [('theta', T), ('inverse', inv)]:
        text += f'def {name}{p} : Matrix (Fin {n}) (Fin {n}) (ZMod {p}) :=\n  !['
        text += ',\n    '.join('![' + ', '.join(map(str, row)) + ']' for row in matrix) + ']\n\n'
    text += f'def seed{p} : Fin {n} → ZMod {p} :=\n  ![' + ', '.join(map(str, rec['seed'])) + ']\n\n'
    text += f'''theorem inverse_checked{p} : inverse{p} * theta{p} = 1 := by decide +kernel

theorem seed_nonzero{p} : seed{p} ≠ 0 := by decide +kernel

/-- Every iterate survives in this checked finite model. -/
theorem survives{p} (n : ℕ) : (theta{p}^n).mulVec seed{p} ≠ 0 :=
  matrix_seed_survives theta{p} inverse{p} inverse_checked{p} seed{p} seed_nonzero{p} n

'''
text += 'end RamanujanTau.FiniteArithmetic.SeedModels\n'
(ROOT / 'RamanujanTau/FiniteArithmetic/SeedModels.lean').write_text(text)
