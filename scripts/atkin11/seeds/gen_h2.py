"""Literal products for the H2 kernel checks (unreduced), written to RamanujanTau/Atkin11Seed/H2Data.lean:
A = S2·S2, B = S2·S3, C = S3·S3, D0 = take 10 A · S2, D1 = drop 10 A · S2."""
import json
import jarith as J
S = json.load(open('S.json'))
S2, S3, S4, S6 = [[J.trim(r) for r in S[k]] for k in ("1", "2", "3", "4")]
A = J.pmul(S2, S2); B = J.pmul(S2, S3); C = J.pmul(S3, S3)
D0 = J.pmul(A[:10], S2); D1 = J.pmul(A[10:], S2)
D = J.padd(D0, J.pshift(D1, 10)); assert D == J.pmul(A, S2) or J.iszero(J.padd(D, J.pmul(A, S2), -1))
def je(dense):
    comps = []
    for r in range(5):
        c = dense[r::5]
        while c and c[-1] == 0: c = c[:-1]
        comps.append("[" + ", ".join(str(x) for x in c) + "]")
    return "⟨" + ", ".join(comps) + "⟩"
out = ["/-", "# Literal products for the H2 checks", "",
       "Generated by `scripts/atkin11/seeds/gen_h2.py`: `A = S₂·S₂`, `B = S₂·S₃`, `C = S₃·S₃`,",
       "`D0 = (take 10 A)·S₂`, `D1 = (drop 10 A)·S₂` (unreduced). Verified in `H2Check`.", "-/",
       "import RamanujanTau.Atkin11Seed.SData", "", "namespace Atkin11Seed", ""]
for nm, v in [("PA", A), ("PB", B), ("PC3", C), ("PD0", D0), ("PD1", D1)]:
    out.append(f"def {nm} : PY := [" + ",\n  ".join(je(row) for row in v) + "]")
    out.append("")
out.append("end Atkin11Seed")
open('../../../RamanujanTau/Atkin11Seed/H2Data.lean', 'w').write("\n".join(out) + "\n")
