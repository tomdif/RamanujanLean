import os, sys, glob
D='certs'
OUT='../../../RamanujanTau/Atkin11Cert'
def readp(fn):
    out=[]
    if not os.path.exists(fn): return out
    for line in open(fn):
        p=line.split()
        if len(p)==6: out.append(([int(x) for x in p[:5]],int(p[5])))
    return out
def pack(e,c):
    m=0
    for v in reversed(e):
        assert v<512
        m=m*1024+v
    assert abs(c)<2**46
    return m*(2**48)+abs(c)*2+(1 if c<0 else 0)
def lit(poly):
    return "[" + ", ".join(str(pack(e,c)) for e,c in poly) + "]"
CH=500
def defs(name, poly):
    """emit chunked definitions; returns Lean source and the expression naming the full poly"""
    parts=[poly[i:i+CH] for i in range(0,len(poly),CH)] or [[]]
    src=""
    names=[]
    for k,pt in enumerate(parts):
        nm=f"{name}_{k}"; names.append(nm)
        src+=f"def {nm} : List ℕ := {lit(pt)}\n"
    src+=f"def {name} : SPoly.Poly := SPoly.ofPacked (" + " ++ ".join(names) + ")\n"
    return src
hdr=lambda title, imp: f"""/-
# Atkin 11^k certificates: {title}

Generated by `scripts/atkin11/step2/gen_cert_lean.py` from Singular output (`scripts/atkin11/step2/certs.sing`).
Variables: `(c₀, c₁, c₂, c₄, c₇)`.
-/
{imp}

set_option autoImplicit false
set_option maxRecDepth 100000
set_option maxHeartbeats 0

namespace Atkin11Cert
"""
# common: W (10), G (25), LG (10 x 25)
nW=len(glob.glob(f'{D}/W*.txt')); nG=len(glob.glob(f'{D}/G*.txt'))
src=hdr("the ten three-term relations and the Gröbner basis","import RamanujanTau.SPoly")
for i in range(1,nW+1): src+=defs(f"W{i}", readp(f'{D}/W{i}.txt'))
src+="def Ws : List SPoly.Poly := [" + ", ".join(f"W{i}" for i in range(1,nW+1)) + "]\n"
for j in range(1,nG+1): src+=defs(f"G{j}", readp(f'{D}/G{j}.txt'))
src+="def Gs : List SPoly.Poly := [" + ", ".join(f"G{j}" for j in range(1,nG+1)) + "]\n"
for j in range(1,nG+1):
    for i in range(1,nW+1): src+=defs(f"LG{j}_{i}", readp(f'{D}/LG_{i}_{j}.txt'))
    src+=f"theorem G{j}_ok : SPoly.certify [" + ", ".join(f"(LG{j}_{i}, W{i})" for i in range(1,nW+1)) + f"] G{j} = true := by decide +kernel\n"
src+="\nend Atkin11Cert\n"
open(f'{OUT}/Common.lean','w').write(src)
names=sys.argv[1:] or ["E3","E4","M6","M5","M4","M3","M2","M1","QU"]
sat={"E3":1,"E4":1}
for nm in names:
    src=hdr(f"identity {nm}","import RamanujanTau.Atkin11Cert.Common")
    T=readp(f'{D}/{nm}_T.txt')
    src+=defs(f"{nm}_T", T)
    for j in range(1,nG+1): src+=defs(f"{nm}_L{j}", readp(f'{D}/{nm}_{j}.txt'))
    k=sat.get(nm,0)
    tgt=f"{nm}_T" if k==0 else f"(SPoly.mulTerm {sum(k*1024**i for i in range(5))} 1 {nm}_T)"
    src+=f"theorem {nm}_ok : SPoly.certify [" + ", ".join(f"({nm}_L{j}, G{j})" for j in range(1,nG+1)) + f"] {tgt} = true := by\n  decide +kernel\n"
    src+="\nend Atkin11Cert\n"
    open(f'{OUT}/{nm}.lean','w').write(src)
print("ok")
