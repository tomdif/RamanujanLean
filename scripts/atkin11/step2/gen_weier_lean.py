import sympy as sp
exec(open('weier_inst.py').read().split("allp={}")[0])
insts=[(-4,-3,1,2),(-4,-3,1,5),(-4,-3,2,5),(-4,0,1,3),(-4,0,3,5),(-4,-2,1,5),(-4,0,2,5),(-4,0,1,5),(-3,0,1,2),(-3,0,2,5)]
def c2(k): return k*(k-1)//2
def norm(e):
    j=e//11; r=e-11*j
    if r==0: return None
    R=r if r<=5 else 11-r
    m=-(11*c2(j+1))-r*j+11*j
    s=1 if j%2==0 else -1
    return (r,j,m,R,s)
Qs=sp.Symbol('Q'); J=sp.symbols('J1:6')
out=[]
for idx,(x,y,u,v) in enumerate(insts):
    groups=[(x+y,x-y,u+v,u-v),(x+v,x-v,u+y,u-y),(y+v,y-v,x+u,x-u)]
    rw=[]; terms=[]
    gstr=[(f"({x} + {y})",f"({x} - {y})",f"({u} + {v})",f"({u} - {v})"),(f"({x} + {v})",f"({x} - {v})",f"({u} + {y})",f"({u} - {y})"),(f"({y} + {v})",f"({y} - {v})",f"({x} + {u})",f"({x} - {u})")]
    for g,gs in zip(groups,gstr):
        prod=1
        for e,es in zip(g,gs):
            n=norm(e)
            if n is None: prod=0; rw.append(f"Jt_norm0 hN hd {es} ({e//11}) (by norm_num)"); continue
            r,j,m,R,s=n
            rw.append(f"Jt_norm hN hd {es} ({r}) ({j}) ({m}) ({R}) ({s}) (by norm_num) (by norm_num [c2]) (by norm_num) (by norm_num)")
            prod*= s*Qs**m*J[R-1]
        terms.append(prod)
    h=sp.expand(terms[0]-terms[1]-Qs**(u-y)*terms[2])
    # normalize: multiply by Q^k to clear negatives, divide by leading coeff
    mins=min(m.as_powers_dict().get(Qs,0) for m in sp.Add.make_args(h))
    target=sp.expand(h*Qs**(-mins))
    lc=sp.Poly(target,Qs,*J).LC()
    target=sp.expand(target/lc)
    coef=sp.simplify(Qs**(-mins)/lc)
    name=f"rel{idx+1}"
    tl=str(target).replace('**','^').replace('Q','Qt hd').replace('J1','Jt hN hd 1').replace('J2','Jt hN hd 2').replace('J3','Jt hN hd 3').replace('J4','Jt hN hd 4').replace('J5','Jt hN hd 5')
    cl=str(coef).replace('**','^').replace('Q','Qt hd')
    out.append(f"""theorem {name} : {tl} = 0 := by
  have h := weierQ hN hd (x := {x}) (y := {y}) (u := {u}) (v := {v}) (by norm_num) (by norm_num) (by norm_num)
  rw [{', '.join(rw)}] at h
  rw [show ({u} : ℤ) - {y} = {u-y} by norm_num] at h
  have hQ := Qt_ne hd
  field_simp at h ⊢
  first | linear_combination h | linear_combination -h
""")
    print(name, target)
