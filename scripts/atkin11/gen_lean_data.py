import json
d=json.load(open('base_C.json'))
rows=[]
for l in range(11):
    for i in range(5):
        c=sorted((int(k),int(v)) for k,v in d[f'{l},{i}'].items())
        rows.append(c)
L=[]
L.append("/-\n# Atkin 11^k: the 55 seed rows `U₁₁(φ^λ J_i) = Σ_ν C^λ_{i,ν} J_ν`, `λ ≤ 10`, `i ≤ 4`\n\nGenerated by `scripts/atkin11/gen_lean_data.py` from `base_C.json` (computed exactly by\n`scripts/atkin11/induct_check.py`). Row `5λ + i`.\n-/\n")
L.append("set_option autoImplicit false\n\nnamespace Atkin11\n")
L.append("/-- the seed rows, indexed by `5λ + i`; entries `(ν, C^λ_{i,ν})`. -/")
L.append("def seedRows : List (List (Nat × Int)) := [")
for k,r in enumerate(rows):
    s=", ".join(f"({n}, {v})" for n,v in r)
    L.append(f"  [{s}]" + ("," if k<len(rows)-1 else ""))
L.append("]\n\nend Atkin11\n")
open('../../RamanujanTau/Atkin11Data.lean','w').write("\n".join(L))
print(sum(len(r) for r in rows))
