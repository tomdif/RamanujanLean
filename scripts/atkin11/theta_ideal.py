"""Do the 5 cubic relations from Jacobi's E^3 identity (+ product relation A0A1A2A4A7 = -Q) generate all relations
among the A_r in a given (degree, Q-degree) box?  Compare numerical nullity with rank of the generated ideal piece."""
import sys, itertools
from sympy import symbols, expand, Poly, Rational
from qs import *
from flint import nmod_mat, fmpq_poly
D, K = int(sys.argv[1]), int(sys.argv[2])
Q, A0, A1, A2, A4, A7 = symbols("Q A0 A1 A2 A4 A7")
Av = {0: A0, 1: A1, 2: A2, 4: A4, 7: A7}
# derive the relations symbolically: (sum_r q^r A_r + q^5)^3, components in classes {2,5,7,8,9} vanish
qq = symbols("qq")
psi = sum(qq**r * Av[r] for r in Av) + qq**5
cube = Poly(expand(psi**3), qq)
rels = []
for cls in (2, 5, 7, 8, 9):
    comp = 0
    for (e,), c in cube.as_dict().items():
        if e % 11 == cls: comp += c * Q**(e//11)
    rels.append(expand(comp))
# the E^3 classes {0,1,3,4,6,10} are nonzero (E^3 components); class 'cls' vanish:
print("E^3-relations (components of (sum q^r A_r + q^5)^3 in classes 2,5,7,8,9):")
for r in rels: print("   ", r, "= 0")
prodrel = expand(A0*A1*A2*A4*A7 + Q)
Rd = expand(4*Q + A0**2*A4 + A0*A2**2 + A1**2*A2 + Q*A1*A7**2 + Q*A4**2*A7)
c4 = 0
for (e,), c in cube.as_dict().items():
    if e % 11 == 4: c4 += c * Q**(e//11)
rel4 = expand(c4 + 11*Q)   # class-4 component of (E/E(q^121))^3 equals -11 q^15  (Jacobi, 2n+1 = 11(2m+1))
print("class-4 Jacobi relation:", rel4, "= 0")
quart = Poly(expand(psi**4), qq)
c9 = 0
for (e,), c in quart.as_dict().items():
    if e % 11 == 9: c9 += c * Q**(e//11)
rel9 = expand(c9 + 11*Q)   # class-9 component of (E/E(q^121))^4 = E*E^3 equals -11 q^20
sq = Poly(expand(psi**2), qq); c10 = 0
for (e,), c in sq.as_dict().items():
    if e % 11 == 10: c10 += c * Q**(e//11)
rel10 = expand(c10 - 0)    # class-10 component of (E/E121)^2 equals q^10 (from n=m=2 mod 11); here q^10 term itself is in psi^2
print("class-9 E^4 relation:", rel9, "= 0"); print("class-10 E^2 component (should be just the q^10 term):", c10)
gens = rels + [prodrel] + ([Rd] if "--Rd" in sys.argv else []) + ([rel4] if "--c4" in sys.argv else []) + ([rel9] if "--c9" in sys.argv else [])
# numerical check + nullity
M = 600
def theta(a, M):
    p = fmpq_poly([1])
    for n in range(0, M):
        for e in (11*n + a, 11*n + 11 - a, 11*n + 11):
            if e < M: p = fmpq_poly((p * fmpq_poly([1] + [0]*(e-1) + [-1])).coeffs()[:M])
    return S(p, 0, M)
th = {a: theta(a, M) for a in range(1, 6)}
An = {0: th[4]*th[2].inv(), 1: -1*th[2]*th[1].inv(), 2: -1*th[5]*th[3].inv(), 4: -1*S(th[1].p, 1, M+1)*th[5].inv(), 7: th[3]*th[4].inv()}
def evalser(expr):
    acc = None
    for mon, c in Poly(expr, Q, A0, A1, A2, A4, A7).as_dict().items():
        t = const(int(c), M)
        for r, e in zip([0, 1, 2, 4, 7], mon[1:]):
            for _ in range(e): t = t * An[r]
        t = S(t.p, t.v + mon[0], t.N + mon[0])
        acc = t if acc is None else acc + t
    return acc
print("generators vanish numerically:", all(S(evalser(g).p, 0, M - 20).is_zero() for g in gens))
keys = [0, 1, 2, 4, 7]
mons = [(m, k) for d in range(0, D + 1) for m in itertools.combinations_with_replacement(keys, d) for k in range(K + 1)]
idx = {mk: i for i, mk in enumerate(mons)}
def vec(expr):
    v = [0]*len(mons)
    for mon, c in Poly(expr, Q, A0, A1, A2, A4, A7).as_dict().items():
        m = tuple(sorted(sum(([r]*e for r, e in zip(keys, mon[1:])), [])))
        k = mon[0]
        if (m, k) not in idx: return None
        v[idx[(m, k)]] += int(c)
    return v
p = 1000003
gen_vecs = []
for g in gens:
    for (m, k) in mons:
        t = expand(g * Q**k * (1 if not m else __import__("functools").reduce(lambda a, b: a*b, [Av[r] for r in m])))
        v = vec(t)
        if v is not None: gen_vecs.append([x % p for x in v])
Gm = nmod_mat(len(gen_vecs), len(mons), [x for v in gen_vecs for x in v], p) if gen_vecs else None
rk_ideal = Gm.rank() if gen_vecs else 0
cols = []
for (m, k) in mons:
    t = const(1, M)
    for r in m: t = t * An[r]
    cols.append(S(t.p, t.v + k, t.N + k))
def md(x): return (int(x.p) % p) * pow(int(x.q) % p, -1, p) % p
Mat = nmod_mat(M - K - 30, len(cols), [md(c.coeff(n)) for n in range(0, M - K - 30) for c in cols], p)
nul = len(cols) - Mat.rank()
print(f"box deg<={D}, Qdeg<={K}: all relations dim = {nul}; generated by E^3-relations+product: {rk_ideal}")
# bigger generation box, intersect with small box
D2, K2 = D + 2, K + 2
mons2 = [(m, k) for d in range(0, D2 + 1) for m in itertools.combinations_with_replacement(keys, d) for k in range(K2 + 1)]
idx2 = {mk: i for i, mk in enumerate(mons2)}
import functools
def vec2(expr):
    v = [0]*len(mons2)
    for mon, c in Poly(expr, Q, A0, A1, A2, A4, A7).as_dict().items():
        m = tuple(sorted(sum(([r]*e for r, e in zip(keys, mon[1:])), [])))
        if (m, mon[0]) not in idx2: return None
        v[idx2[(m, mon[0])]] += int(c)
    return v
GV = []
for g in gens:
    for (m, k) in mons2:
        t = expand(g * Q**k * (functools.reduce(lambda a, b: a*b, [Av[r] for r in m]) if m else 1))
        v = vec2(t)
        if v is not None: GV.append([x % p for x in v])
G2 = nmod_mat(len(GV), len(mons2), [x for v in GV for x in v], p)
rG = G2.rank()
outside = [i for i, mk in enumerate(mons2) if mk not in idx]
Po = nmod_mat(len(GV), len(outside), [GV[a][i] for a in range(len(GV)) for i in outside], p)
print(f"generated in box({D2},{K2}) then intersected with box({D},{K}): {rG - Po.rank()}  (vs all relations {nul})")
