import json, sympy as sp
from packlib import *
inst=json.load(open('weier13_inst.json'))
loc={f'J{i}':J[i-1] for i in range(1,7)}; loc['Q']=Q
lines=['''/-
# Atkin–O'Brien 13^k: the 21 three-term relations in `ℤ⟦q⟧`

`W_i(η₁, …, η₆, q) = 0` for the 21 level-13 Weierstrass relations (`ALz13.rel_i`), where
`η_a = (q^a;q¹³)_∞(q^{13−a};q¹³)_∞`. They are homogeneous of degree 4 in the `J`'s, and
`J_a = θ(q^a; q¹³) = η_a·(q¹³;q¹³)_∞`, so they transfer from the theta point (`Jpt`) to `ηPt`.
Generated by `scripts/atkin13/gen_rel_lean.py`.
-/
import RamanujanTau.Atkin13Weier
import RamanujanTau.Atkin13DissectPS
import RamanujanTau.SPoly7Hom

set_option autoImplicit false

namespace Atkin13
open PowerSeries ALz ALz13 MTC SPoly7
open Atkin11 (PS h1' ιN1_inv X_ι)

''']
for i,(_,t) in enumerate(inst):
    lines.append(lean_list(f'W{i+1}_0',pack_poly(sp.sympify(t,locals=loc))))
    lines.append(f'def W{i+1} : Poly := ofPacked W{i+1}_0')
lines.append('def Wall : List Poly := ['+', '.join(f'W{i+1}' for i in range(len(inst)))+']\n')
lines.append('''section L
lemma h13 : 1 ≤ 13 := by norm_num
lemma hd1 : 13 = 13 * 1 := by norm_num

/-- the theta point `(J₁, …, J₆, Q)` at level `13 = 13·1`. -/
noncomputable def Jpt : List L :=
  [Jt h13 hd1 1, Jt h13 hd1 2, Jt h13 hd1 3, Jt h13 hd1 4, Jt h13 hd1 5, Jt h13 hd1 6, Qt hd1]
''')
for i in range(len(inst)):
    lines.append(f'''lemma W{i+1}_zero_L : evalP Jpt W{i+1} = 0 := by
  have r := rel{i+1} h13 hd1
  simp only [W{i+1}, W{i+1}_0, ofPacked, List.map, decTerm, evalP, evalM, dec, evalL, Jpt] at *
  norm_num
  linear_combination r
''')
lines.append('end L\n\nend Atkin13\n')
open('../../RamanujanTau/Atkin13Cert/Rel.lean','w').write('\n'.join(lines))
