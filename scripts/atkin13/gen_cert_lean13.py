def todict(expr):
    P=sp.Poly(sp.expand(expr),*VARS); return {tuple(int(x) for x in m):int(c) for m,c in P.terms()}
# parse singular polynomials fast: terms like  -3*J1^2*J2*Q^3
termre=re.compile(r'([+-]?)(\d*)\*?((?:[JQ]\d?(?:\^\d+)?\*?)*)')
def parse_sing(s):
    d=defaultdict(int)
    s=s.replace(' ','')
    for tm in re.findall(r'[+-]?[^+-]+',s):
        sign=-1 if tm.startswith('-') else 1
        tm=tm.lstrip('+-')
        parts=tm.split('*'); coef=1; ex=[0]*7
        for p in parts:
            if re.fullmatch(r'\d+',p): coef*=int(p); continue
            base,_,e=p.partition('^'); e=int(e) if e else 1
            if base=='Q': ex[6]+=e
            else: ex[int(base[1])-1]+=e
        d[tuple(ex)]+=sign*coef
    return dict(d)
W=[todict(sp.sympify(t,locals=loc)) for _,t in inst]
lift=defaultdict(dict)
lines=open('lift_out.txt').read().split('\n')
k=0
while k<len(lines)-1:
    if lines[k].startswith('J '):
        _,j,_,i=lines[k].split(); lift[int(j)][int(i)]=parse_sing(lines[k+1]); k+=2
    else: k+=1
def mulp(a,b):
    c=defaultdict(int)
    for ka,va in a.items():
        for kb,vb in b.items():
            c[tuple(x+y for x,y in zip(ka,kb))]+=va*vb
    return c
def pk(ex): return sum(x*1024**i for i,x in enumerate(ex))
def packd(d):
    out=[]
    for ex,c in sorted(d.items(), key=lambda kv: pk(kv[0])):
        if c: out.append(pk(ex)*2**100 + 2*abs(c) + (1 if c<0 else 0))
    return out
