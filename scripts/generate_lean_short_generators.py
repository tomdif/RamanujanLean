#!/usr/bin/env python3
"""Translate the short-generator data to kernel-checked Lean certificates.

Coverage is linear in each prime: each row supplies a canonical square root
or an Euler nonresidue witness. The Lean framework proves that these rows
cover every normalized isotropic triple and identify its integral lattice.
"""
import argparse
from itertools import combinations
import json
from math import gcd, isqrt
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def primes():
    return [p for p in range(7, 1250)
            if all(p % d for d in range(2, isqrt(p)+1))]


def determinant(rows):
    (a,b,c),(d,e,f),(g,h,i) = rows
    return a*(e*i-f*h)-b*(d*i-f*g)+c*(d*h-e*g)


def coordinates(p,j,k,vectors):
    result=[]
    for a,b,c in vectors:
        assert (b-j*a)%p == 0 and (c-k*a)%p == 0
        result.append((a,(b-j*a)//p,(c-k*a)//p))
    divisor=0
    for triple in combinations(result,3):
        divisor=gcd(divisor,determinant(triple))
    assert divisor == 1
    return '['+', '.join(f'(({a}, {b}), {c})' for a,b,c in result)+']'


def prime_source(p,data):
    roots={k*k%p:k for k in range((p+1)//2)}
    rows=[]
    for j in range((p+1)//2):
        d=(-1-j*j)%p
        if d not in roots:
            assert pow(d,(p-1)//2,p) == p-1
            continue
        k=roots[d]
        vs='[]'
        if 1 < j < k and p != 13:
            vs=coordinates(p,j,k,data[p,j,k])
        rows.append(f'  | {j} => some ({k}, {vs})')
    return f'''set_option maxRecDepth 100000 in
set_option maxHeartbeats 0 in
private def rows{p} : ℕ → Option (ℕ × List TernaryIntPoint)
'''+ '\n'.join(rows)+f'''
  | _ => none

set_option maxRecDepth 100000 in
set_option maxHeartbeats 0 in
private theorem checkedRows{p} :
    ∀ j : Fin {(p+1)//2}, NormalizedGeneratorRow {p} j.val (rows{p} j.val) := by
  decide +kernel
'''


def block_source(number,ps,data):
    plist='['+', '.join(map(str,ps))+']'
    source='''/- Kernel-checked short-generator certificate block. Generated; do not edit. -/
import RamanujanTau.MultiQuintupleNormalizedGenerators
namespace Ramanujan.MultiQuintuple

'''+ '\n'.join(prime_source(p,data) for p in ps)
    source+=f'''
set_option maxRecDepth 100000 in
set_option maxHeartbeats 0 in
theorem short_generation_normalized_block{number}
    {{p : ℕ}} [Fact p.Prime] (hblock : p ∈ {plist}) (hp13 : p ≠ 13)
    (j k : ℕ) (hj : 1 < j) (hjk : j < k) (hkp : 2*k < p)
    (hiso : (1 : ZMod p)+(j : ZMod p)^2+(k : ZMod p)^2 = 0) :
    Submodule.span ℤ (shortSupportedDualSet p ((1,(j : ℤ)),(k : ℤ))) =
      projectiveDualLattice p ((1,(j : ℤ)),(k : ℤ)) := by
  simp only [List.mem_cons,List.not_mem_nil,or_false] at hblock
  rcases hblock with '''+' | '.join(f'h{p}' for p in ps)+'\n'
    for p in ps:
        source+=f'''  · subst p
    exact normalized_generation_of_checked_rows (by omega) hp13 rows{p} checkedRows{p}
      j k hj hjk hkp hiso
'''
    return source+'\nend Ramanujan.MultiQuintuple\n'


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--prime',type=int,help='Emit one prime as a build probe.')
    parser.add_argument('--output',type=Path)
    args=parser.parse_args()
    raw=json.loads((ROOT/'docs/verification/short_watson_generators.json').read_text())
    data={(p,v[1],v[2]):vs for p,v,vs in raw['short_generator_certificates']}
    ps=[args.prime] if args.prime else primes()
    assert all(p in primes() for p in ps)
    source='''/-
# Short-generator certificates for every normalized line below 1250

Generated by scripts/generate_lean_short_generators.py from the recorded
integer vectors. Lean checks all arithmetic and the completeness of the rows.
-/
import RamanujanTau.MultiQuintupleNormalizedGenerators

namespace Ramanujan.MultiQuintuple

'''+ '\n'.join(prime_source(p,data) for p in ps)
    if args.prime is None:
        blocks=[ps[n::8] for n in range(8)]
        blockdir=ROOT/'RamanujanTau/MultiQuintupleFiniteGenerators'
        blockdir.mkdir(exist_ok=True)
        for number,subset in enumerate(blocks):
            (blockdir/f'Block{number}.lean').write_text(block_source(number,subset,data))
        source='''/-
# Complete short-generator coverage below 1250

Generated by scripts/generate_lean_short_generators.py. The arithmetic is
split into stable certificate modules so downstream edits do not repeat it.
-/
'''+''.join(f'import RamanujanTau.MultiQuintupleFiniteGenerators.Block{n}\n' for n in range(8))
        source+='\nnamespace Ramanujan.MultiQuintuple\n'
        cases=['p.val ∈ ['+', '.join(map(str,subset))+']' for subset in blocks]
        source+=f'''
set_option maxRecDepth 100000 in
set_option maxHeartbeats 0 in
private theorem primeCoverage :
    ∀ p : Fin 1250, p.val.Prime → 5 < p.val →
      {' ∨ '.join(cases)} := by
  decide +kernel

set_option maxRecDepth 100000 in
set_option maxHeartbeats 0 in
/-- Every normalized admissible line below 1250, except modulus 13,
is integrally generated by its supported vectors of squared norm < p²/2. -/
theorem short_generation_normalized_below_1250
    {{p : ℕ}} [Fact p.Prime] (hp : p < 1250) (hp13 : p ≠ 13)
    (j k : ℕ) (hj : 1 < j) (hjk : j < k) (hkp : 2*k < p)
    (hiso : (1 : ZMod p)+(j : ZMod p)^2+(k : ZMod p)^2 = 0) :
    Submodule.span ℤ (shortSupportedDualSet p ((1,(j : ℤ)),(k : ℤ))) =
      projectiveDualLattice p ((1,(j : ℤ)),(k : ℤ)) := by
  have hc := primeCoverage ⟨p,hp⟩ (Fact.out : p.Prime) (show 5 < p by omega)
  rcases hc with '''+' | '.join(f'h{n}' for n in range(8))+'\n'
        for n in range(8):
            source+=f'''  · exact short_generation_normalized_block{n} h{n} hp13 j k hj hjk hkp hiso
'''
    source+='\nend Ramanujan.MultiQuintuple\n'
    output=args.output or ROOT/'RamanujanTau/MultiQuintupleFiniteGenerators.lean'
    output.write_text(source)
    print(f'Wrote {len(ps)} prime row tables ({len(source.encode())} bytes) to {output}')


if __name__ == '__main__':
    main()
