#!/usr/bin/env python3
"""Derive polynomial affine maps for an infinite four-quintuple family.

Requires SymPy. Emits reproducible data and Lean definitions; the separate
MultiQuintupleFourFamily proof checks the identities for every parameter.
"""
import sympy as s,json,re
from itertools import product
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
t=s.symbols('t');m=72*t+5;n=4;p=s.expand(m*m+n*n)
E=s.Matrix.hstack(s.Matrix([1,0,1,1]),s.Matrix([-1,1,0,1]),s.Matrix([1,1,-1,0]),s.Matrix([0,-1,-1,1]))
H=s.Matrix([[n*n-m*m,-2*m*n],[-2*m*n,m*m-n*n]])/p
J=s.Matrix([[0,-1],[1,0]])
T0=E*s.diag(H,s.diag(-1,1))*E.T/3
T1=E*s.diag(J*H,s.Matrix([[0,-1],[-1,0]]))*E.T/3
P=s.eye(4)[[0,2,3,1],:]
v=s.Matrix([m-4,m,m+4,4]);Ts=[T0,-T1,T1,-T0];Ts=[P*T*P.T for T in Ts]
Rs=[2592*t*t+468*t+21,3240*t*t+477*t+25,1944*t*t+459*t+26,2592*t*t+468*t+30]
a=[s.expand((p-v[i])/4) for i in range(3)];B=s.eye(4);B[3,:]=s.Matrix([a+[p]])
Bi=B.inv()
def canonical_poly(x):
 x=s.cancel(x)
 assert s.denom(x)==1,x
 pp=s.Poly(x,t)
 assert all(c.q==1 for c in pp.all_coeffs())
 return s.expand(x)
def displacement(R,b):
 num=s.Poly(R-(v.T*s.Matrix(b))[0],t)
 q=sum(int(-5*c)%12*t**i[0] for i,c in num.terms())
 return canonical_poly((num.as_expr()+q*p)/12),q
out={'p':str(p),'indices':list(map(str,v)),'residues':list(map(str,Rs)),'basis_last':list(map(str,a)),'cases':[]}
for r,(R,T) in enumerate(zip(Rs,Ts)):
 S=T.subs(t,0).applyfunc(lambda x: int(s.numer(x))*pow(int(s.denom(x)),-1,3)%3).applyfunc(lambda x:-1 if x==2 else x)
 assert S*S.T==s.eye(4)
 A=(Bi*T*B).applyfunc(canonical_poly)
 for b in product([0,1],repeat=4):
  ss=s.Matrix([2*x-1 for x in b]);sp=S*ss;bt=[int((x+1)/2) for x in sp]
  cb,qb=displacement(R,b);ct,qt=displacement(R,bt)
  d=s.Matrix([0,0,0,cb]);dt=s.Matrix([0,0,0,ct])
  shift=(T*(6*v+p*ss)-6*v-p*sp)/(6*p)
  c=(Bi*(T*d+shift-dt)).applyfunc(canonical_poly)
  out['cases'].append({'r':r,'source':b,'target':bt,'c0':str(cb),'q0':str(qb),'matrix':[[str(A[i,j]) for j in range(4)] for i in range(4)],'translation':list(map(str,c))})
 print('residue',r,'max A degree',max(s.degree(x,t) for x in A),'max c degree',max(s.degree(s.sympify(x),t) for z in out['cases'] if z['r']==r for x in z['translation']),flush=True)
(ROOT/'docs/verification/four_quintuple_family.json').write_text(json.dumps(out,indent=2)+'\n')

r=out
def expr(x):return re.sub(r'\bt\b','(t : ℤ)',x.replace('**','^'))
def b(x):return 'true' if x else 'false'
text='''import RamanujanTau.MultiQuintupleFourFortyOne

/-! Polynomial affine maps for a four-factor infinite family.
Generated by scripts/generate_four_quintuple_family.py; checked by FourFamily. -/
namespace Ramanujan.MultiQuintuple
set_option maxRecDepth 10000
set_option maxHeartbeats 0

def fourFamilyP (t : ℕ) : ℕ := 5184*t^2+720*t+41
def fourFamilyI1 (t : ℕ) : ℕ := 72*t+1
def fourFamilyI2 (t : ℕ) : ℕ := 72*t+5
def fourFamilyI3 (t : ℕ) : ℕ := 72*t+9

def fourFamilyR (t : ℕ) (r : Fin 4) : ℕ :=
  match r.val with
  | 0 => 2592*t^2+468*t+21
  | 1 => 3240*t^2+477*t+25
  | 2 => 1944*t^2+459*t+26
  | _ => 2592*t^2+468*t+30

def fourFamilyA1 (t : ℕ) : ℕ := 1296*t^2+162*t+10
def fourFamilyA2 (t : ℕ) : ℕ := 1296*t^2+162*t+9
def fourFamilyA3 (t : ℕ) : ℕ := 1296*t^2+162*t+8
def fourFamilyInv12 (t : ℕ) : ℕ := 3024*t^2+420*t+24

'''
for name,key in [('C0','c0'),('Q0','q0')]:
 for ri in range(4):
  text+=f'def fourFamily{name}_{ri} (t : ℕ) (b1 b2 b3 b4 : Bool) : ℤ :=\n  match b1,b2,b3,b4 with\n'
  for c in r['cases']:
   if c['r']==ri:text+='  | '+', '.join(map(b,c['source']))+' => '+expr(c[key])+'\n'
  text+='\n'
 text+=f'def fourFamily{name} (t : ℕ) (r : Fin 4) (b1 b2 b3 b4 : Bool) : ℤ :=\n  match r.val with\n'
 for ri in range(4):text+=f'  | {ri if ri<3 else "_"} => fourFamily{name}_{ri} t b1 b2 b3 b4\n'
 text+='\n'
text+='''def fourFamilyBitSum (t : ℕ) (b1 b2 b3 b4 : Bool) : ℤ :=
  fourFamilyI1 t*(if b1 then 1 else 0)+fourFamilyI2 t*(if b2 then 1 else 0)+
  fourFamilyI3 t*(if b3 then 1 else 0)+4*(if b4 then 1 else 0)

def fourFamilyFiberPoint (t : ℕ) (r : Fin 4) (b1 b2 b3 b4 : Bool) (n1 n2 n3 z : ℤ) :
    QuadQuintBranchIndex :=
  ((((b1,n1),(b2,n2)),(b3,n3)),
    (b4,fourFamilyA1 t*n1+fourFamilyA2 t*n2+fourFamilyA3 t*n3+
      fourFamilyC0 t r b1 b2 b3 b4+fourFamilyP t*z))

def fourFamilyFiberZ (t : ℕ) (r : Fin 4) (x : QuadQuintBranchIndex) : ℤ :=
  (quadN4 x-fourFamilyA1 t*quadN1 x-fourFamilyA2 t*quadN2 x-fourFamilyA3 t*quadN3 x-
    fourFamilyC0 t r (quadB1 x) (quadB2 x) (quadB3 x) (quadB4 x))/fourFamilyP t

'''
for ri in range(4):
 text+=f'def fourFamilyPartnerFiber_{ri} (t : ℕ) (b1 b2 b3 b4 : Bool) (n1 n2 n3 z : ℤ) :\n    QuadQuintBranchIndex :=\n  match b1,b2,b3,b4 with\n'
 for c in r['cases']:
  if c['r']!=ri:continue
  vals=['('+' + '.join([f'({expr(x)})*{v}' for x,v in zip(row,['n1','n2','n3','z'])]+[f'({expr(a)})'])+')' for row,a in zip(c['matrix'],c['translation'])]
  text+='  | '+', '.join(map(b,c['source']))+f' => fourFamilyFiberPoint t {ri} '+' '.join(map(b,c['target']))+'\n      '+'\n      '.join(vals)+'\n'
 text+='\n'
text+='''def fourFamilyPartnerFiber (t : ℕ) (r : Fin 4) (b1 b2 b3 b4 : Bool) (n1 n2 n3 z : ℤ) :
    QuadQuintBranchIndex :=
  match r.val with
  | 0 => fourFamilyPartnerFiber_0 t b1 b2 b3 b4 n1 n2 n3 z
  | 1 => fourFamilyPartnerFiber_1 t b1 b2 b3 b4 n1 n2 n3 z
  | 2 => fourFamilyPartnerFiber_2 t b1 b2 b3 b4 n1 n2 n3 z
  | _ => fourFamilyPartnerFiber_3 t b1 b2 b3 b4 n1 n2 n3 z

def fourFamilyPartner (t : ℕ) (r : Fin 4) (x : QuadQuintBranchIndex) : QuadQuintBranchIndex :=
  fourFamilyPartnerFiber t r (quadB1 x) (quadB2 x) (quadB3 x) (quadB4 x)
    (quadN1 x) (quadN2 x) (quadN3 x) (fourFamilyFiberZ t r x)

end Ramanujan.MultiQuintuple
'''
(ROOT/'RamanujanTau/MultiQuintupleFourFamilyData.lean').write_text(text)
