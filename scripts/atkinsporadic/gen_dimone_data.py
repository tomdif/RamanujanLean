"""Generate RamanujanTau/AtkinSporadic/DimOneData.lean (the dim-one certificates)."""
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
from dimone_cert import certificate
from sympy import legendre_symbol

def lst(v): return '[' + ', '.join(str(x) for x in v) + ']'
out = ['''import RamanujanTau.AtkinSporadic.DimOne

/-!
# Dimension-one certificates for ℓ = 13, 17, 19, 23 (weights 10, 14, 16, 20)

Generated by `scripts/atkinsporadic/gen_dimone_data.py`. Each `certℓ` is checked by the kernel
(`decide +kernel`): the basis lists agree with `LevelSix.basisL`, the rows are admissible, and
`K L = d·I`.
-/

set_option autoImplicit false

namespace RamanujanTau.AtkinSporadic.DimOne
open RamanujanTau.TheoremA.SignLattice LevelSix
''']
for ell in [13, 17, 19, 23]:
    lam, n, lab, L0, K, d, E = certificate(ell)
    e2 = legendre_symbol(2, ell) * 2**((ell-5)//2)
    e3 = legendre_symbol(3, ell) * 3**((ell-5)//2)
    code = {'c1': 0, 'u2': 1, 'u3': 2}
    rows = '[' + ', '.join(f'({code[k]}, {m})' for k, m in lab) + ']'
    basis = '[' + ',\n    '.join(lst(E[i][:29]) for i in range(n)) + ']'
    Ks = '[' + ',\n    '.join(lst(r) for r in K) + ']'
    out.append(f'''
instance fact{ell} : Fact (Nat.Prime {ell}) := ⟨by norm_num⟩

def cert{ell} : DimCert where
  e2 := {e2}
  e3 := {e3}
  basis := {basis}
  rows := {rows}
  K := {Ks}
  d := {d}

theorem cert{ell}_basis : ∀ i : Fin (2 * halfWt {ell} + 1), cert{ell}.basis.getD i [] = basisL (halfWt {ell}) i := by
  decide +kernel

theorem cert{ell}_rows : ∀ r : Fin (2 * halfWt {ell} + 1), DimCert.rowOK (cert{ell}.rows.getD r (0, 0)) = true := by
  decide +kernel

theorem cert{ell}_inv : ∀ k i : Fin (2 * halfWt {ell} + 1),
    ∑ r : Fin (2 * halfWt {ell} + 1), cert{ell}.Kent k r * cert{ell}.Lrow r i = if k = i then cert{ell}.d else 0 := by
  decide +kernel

theorem eig2_{ell} : eig2 {ell} = cert{ell}.e2 := by
  rw [eig2, jacobiSym.legendreSym.to_jacobiSym]; norm_num [cert{ell}]

theorem eig3_{ell} : eig3 {ell} = cert{ell}.e3 := by
  rw [eig3, jacobiSym.legendreSym.to_jacobiSym]; norm_num [cert{ell}]

/-- **`dim W = 1` in weight {ell-3}.** -/
theorem dimOne_{ell} : DimOneProp {ell} :=
  cert{ell}.sound eig2_{ell} eig3_{ell} cert{ell}_basis cert{ell}_rows cert{ell}_inv (by decide)
''')
out.append('\nend RamanujanTau.AtkinSporadic.DimOne\n')
open(os.path.join(os.path.dirname(__file__), '../../RamanujanTau/AtkinSporadic/DimOneData.lean'), 'w').write(''.join(out))
