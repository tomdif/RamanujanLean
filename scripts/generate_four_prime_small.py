#!/usr/bin/env python3
"""Emit kernel-checked coefficient witnesses for the seven remaining small primes."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def render(case, previous):
    p, m, n = (case[k] for k in ('p', 'm', 'n'))
    indices = (m-n, n, m, m+n)
    args = ' '.join(map(str, (p, *indices)))
    limit = max(p*w['N']+w['R'] for w in case['witnesses'])
    template = (ROOT/'RamanujanTau/MultiQuintupleFourFortyOneConverse.lean').read_text()
    start = template.index('private lemma short_index41')
    end = template.index('\n\nset_option maxHeartbeats 0 in')
    body = template[start:end]
    mapping = dict(zip((1,4,5,9),indices))
    body = re.sub(r'(quintExp2_nonneg b[1-4] |quintupleSpecialized )41 (1|4|5|9)\b',
                  lambda hit: f'{hit[1]}{p} {mapping[int(hit[2])]}',body)
    body = re.sub(r'short_index41 (b[1-4]) (1|4|5|9)\b',
                  lambda hit: f'short_index{p} {hit[1]} {mapping[int(hit[2])]}',body)
    body = body.replace('41 1 4 5 9', args).replace('41', str(p))
    body = body.replace('430', str(2*limit)).replace('215', str(limit))
    body = body.replace('hi9', 'hiMax').replace('i ≤ 9', f'i ≤ {m+n}')
    cut = 5*(p-m-n)-1
    split = body.index('private lemma mem_short_box')
    two = body[:split].replace(f'short_index{p}', f'short_index{p}_two')
    one = two.replace(f'short_index{p}_two', f'short_index{p}_one')
    one = one.replace(f'≤ {2*limit}', f'≤ {2*cut}').replace('natAbs ≤ 2', 'natAbs ≤ 1')
    one = one.replace('-2 ≤ n ∧ n ≤ 2', '-1 ≤ n ∧ n ≤ 1')
    one = one.replace('n ≤ -3 ∨ 3 ≤ n', 'n ≤ -2 ∨ 2 ≤ n').replace('(n+3)', '(n+2)').replace('(n-3)', '(n-2)')
    bridge = f"""def four{p}Radius (K : ℕ) : ℕ := if K ≤ {cut} then 0 else 1

private lemma short_index{p} (b : Bool) (i : ℕ) (n : ℤ) (K : ℕ)
    (hi : 1 ≤ i) (hiMax : i ≤ {m+n}) (hK : K ≤ {limit})
    (he : quintExp2 b {p} i n ≤ 2*(K : ℤ)) : n.natAbs ≤ four{p}Radius K+1 := by
  unfold four{p}Radius
  split_ifs with h
  · exact short_index{p}_one b i n hi hiMax (by omega)
  · exact short_index{p}_two b i n hi hiMax (by omega)

"""
    rest = body[split:]
    rest = rest.replace('quadBox 1', f'quadBox (four{p}Radius K)')
    rest = rest.replace('mem_quintBranchBox_of_natAbs_le 1', f'mem_quintBranchBox_of_natAbs_le (four{p}Radius K)')
    for pos,index in enumerate(indices,1):
        rest = rest.replace(f'short_index{p} b{pos} {index} n{pos} (by norm_num) (by norm_num)',
                            f'short_index{p} b{pos} {index} n{pos} K (by norm_num) (by norm_num) hK')
    body = one+two+bridge+rest
    out = [f'import RamanujanTau.{previous}\n\n',
           '/-! Generated by scripts/generate_four_prime_small.py; kernel-checked nonzero witnesses. -/\n',
           'namespace Ramanujan.MultiQuintuple\nopen PowerSeries\n',
           'set_option maxRecDepth 100000\nset_option maxHeartbeats 4000000\nset_option Elab.async false\n\n',body,'\n\n']
    for w in case['witnesses']:
        degree=p*w['N']+w['R']
        out.append(f"set_option maxHeartbeats 0 in\nprivate theorem coefficient{p}_{w['R']} : four{p}ShortCoeff {degree} = ({w['coefficient']} : ℤ) := by\n  decide +kernel\n\n")
    out.append(f'theorem four{p}_not_persistent (R : ℕ) (hR : R < {p}) :\n    ¬ PersistentFourVanishing {p} (fourPrimeFamilyIndices {m} {n}) R := by\n  intro hz\n  interval_cases R\n')
    for w in case['witnesses']:
        out.append(f"  · have h := hz {w['N']}\n    change coeff ({p}*{w['N']}+{w['R']}) (quintupleSpecialized {p} {indices[0]} * quintupleSpecialized {p} {indices[1]} *\n      quintupleSpecialized {p} {indices[2]} * quintupleSpecialized {p} {indices[3]})=0 at h\n    rw [coeff_four{p}_eq_short _ (by norm_num),coefficient{p}_{w['R']}] at h\n    norm_num at h\n")
    out.append('\nend Ramanujan.MultiQuintuple\n')
    return ''.join(out)

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    data=json.loads((ROOT/'docs/verification/four_prime_converse_certificates.json').read_text())
    previous='MultiQuintupleFourPrimeInvolution'
    for case in data['small_prime_cases']:
        if case['p'] in (41,53,97): continue
        name=f"MultiQuintupleFourPrimeSmall{case['p']}"
        source=render(case,previous)
        path=ROOT/'RamanujanTau'/f'{name}.lean'
        if args.check:
            if not path.exists() or path.read_text()!=source:
                raise SystemExit(f'Stale generated file: {path}')
        else: path.write_text(source)
        previous=name
    print('Seven small-prime Lean certificate modules are reproducible.')

if __name__=='__main__': main()
