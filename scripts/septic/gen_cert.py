"""Elimination certificates (Singular `lift`) for the unconditional page-206 proof.
Normalized point values B=b/a, C=c/a, D=d/a satisfy (lattice identities + R = 7):
  g1 = P_{W1}(1,B,C,D) - 49,  g2 = P_{W2}(1,B,C,D) - 49,  g3 = 8(B^3C+C^3D+D^3B) + 24BCD - 6.
cert1:  f5(8BCD)^2 = h1 g1 + h2 g2 + h3 g3,  f5(t) = (t-1)(t^2-2t+36)(7t^2+22t-36)
cert2:  Bp(1,B,C,D) = k1 g1 + k2 g2 + k3 g3 + k4 (8BCD-1),  Bp = (B^2C^3+C^2D^3+D^2B^3) - BCD - 2B^2C^2D^2
Writes RamanujanTau/Septic/Cert.lean."""
import subprocess, sys, re, os
sys.path.insert(0, os.path.dirname(__file__))
import sympy as sp
from gen_octo import analyse, MATS, poly_of, a, b, c, d
Bs, Cs, Ds = sp.symbols('B C D')
def dehom(P): return sp.expand(P.subs({a: 1, b: Bs, c: Cs, d: Ds}))
P1 = poly_of(analyse(MATS[1])[3]); P2 = poly_of(analyse(MATS[2])[3])
g1 = dehom(P1) - 49; g2 = dehom(P2) - 49
g3 = sp.expand(8 * (Bs**3*Cs + Cs**3*Ds + Ds**3*Bs) + 24*Bs*Cs*Ds - 6)
S = lambda e: str(e).replace('**', '^')
sing = f"""ring r=0,(B,C,D),dp; short=0;
poly g1={S(g1)}; poly g2={S(g2)}; poly g3={S(g3)};
ideal I=g1,g2,g3;
poly t=8*B*C*D;
poly f5=(t-1)*(t^2-2*t+36)*(7*t^2+22*t-36);
matrix L=lift(I,f5^2);
"H1"; print(L[1,1]); "H2"; print(L[2,1]); "H3"; print(L[3,1]);
ideal I2=g1,g2,g3,t-1;
poly Bp=(B^2*C^3+C^2*D^3+D^2*B^3)-B*C*D-2*B^2*C^2*D^2;
matrix L2=lift(I2,Bp);
"K1"; print(L2[1,1]); "K2"; print(L2[2,1]); "K3"; print(L2[3,1]); "K4"; print(L2[4,1]);
"END";
quit;
"""
out = subprocess.run(["Singular", "-q"], input=sing, capture_output=True, text=True).stdout
blocks = {}
cur = None
for line in out.splitlines():
    l = line.strip()
    if l in ("H1", "H2", "H3", "K1", "K2", "K3", "K4", "END"):
        cur = l; blocks[cur] = ""; continue
    if cur: blocks[cur] += l
loc = {'B': Bs, 'C': Cs, 'D': Ds}
H = [sp.sympify(blocks[k].replace('^', '**'), locals=loc) for k in ("H1", "H2", "H3")]
K = [sp.sympify(blocks[k].replace('^', '**'), locals=loc) for k in ("K1", "K2", "K3", "K4")]
t = 8*Bs*Cs*Ds
f5 = (t-1)*(t**2-2*t+36)*(7*t**2+22*t-36)
assert sp.expand(H[0]*g1 + H[1]*g2 + H[2]*g3 - f5**2) == 0
Bp = (Bs**2*Cs**3 + Cs**2*Ds**3 + Ds**2*Bs**3) - Bs*Cs*Ds - 2*Bs**2*Cs**2*Ds**2
assert sp.expand(K[0]*g1 + K[1]*g2 + K[2]*g3 + K[3]*(t-1) - Bp) == 0
print("certificates verified; term counts", [len(sp.Add.make_args(sp.expand(h))) for h in H + K])
L = lambda e: str(sp.expand(e)).replace('**', '^')
lean = f'''/-
# Elimination certificates at the special point — GENERATED by scripts/septic/gen_cert.py (Singular `lift`)

For reals `B, C, D` with `g1 = g2 = g3 = 0` (the two 8-dimensional lattice identities and the quaternion
identity at `R = 7`, normalized by `a = 1`):
* `cert_f5`: `f5(8BCD)² = h1 g1 + h2 g2 + h3 g3` with `f5(t) = (t−1)(t²−2t+36)(7t²+22t−36)`;
* `cert_Bp`: `Bp = k1 g1 + k2 g2 + k3 g3 + k4 (8BCD − 1)`.
-/
import Mathlib.Tactic

set_option autoImplicit false
set_option maxHeartbeats 0

namespace RamanujanTau.Septic

/-- `P_{{W₁}}(1,B,C,D) − 49`. -/
def cg1 (B C D : ℝ) : ℝ := {L(g1)}
/-- `P_{{W₂}}(1,B,C,D) − 49`. -/
def cg2 (B C D : ℝ) : ℝ := {L(g2)}
/-- quaternion identity at `R = 7`. -/
def cg3 (B C D : ℝ) : ℝ := {L(g3)}

theorem cert_f5 (B C D : ℝ) (h1 : cg1 B C D = 0) (h2 : cg2 B C D = 0) (h3 : cg3 B C D = 0) :
    ((8 * B * C * D - 1) * ((8 * B * C * D) ^ 2 - 2 * (8 * B * C * D) + 36)
      * (7 * (8 * B * C * D) ^ 2 + 22 * (8 * B * C * D) - 36)) ^ 2 = 0 := by
  unfold cg1 at h1; unfold cg2 at h2; unfold cg3 at h3
  linear_combination ({L(H[0])}) * h1
    + ({L(H[1])}) * h2
    + ({L(H[2])}) * h3

theorem cert_Bp (B C D : ℝ) (h1 : cg1 B C D = 0) (h2 : cg2 B C D = 0) (h3 : cg3 B C D = 0)
    (hp : 8 * B * C * D = 1) :
    (B ^ 2 * C ^ 3 + C ^ 2 * D ^ 3 + D ^ 2 * B ^ 3) - B * C * D - 2 * B ^ 2 * C ^ 2 * D ^ 2 = 0 := by
  unfold cg1 at h1; unfold cg2 at h2; unfold cg3 at h3
  linear_combination ({L(K[0])}) * h1
    + ({L(K[1])}) * h2
    + ({L(K[2])}) * h3
    + ({L(K[3])}) * hp

end RamanujanTau.Septic
'''
open("RamanujanTau/Septic/Cert.lean", "w").write(lean)
print("wrote RamanujanTau/Septic/Cert.lean", len(lean), "chars")
