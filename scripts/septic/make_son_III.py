U7 = [(0, 1, 4, 0, 3, 6, 6), (1, 0, 2, 1, 4, 2, 4)]
# degree-6 identity (|U| = 343)
M6 = [[1, -3, 3, 2, -5, -1], [-2, 3, 3, 1, -1, 5], [3, -1, -1, -5, -2, 3], [-1, -2, 5, -3, 3, -1],
      [-3, -5, -2, 1, 1, 3], [5, -1, 1, 3, 3, 2]]
