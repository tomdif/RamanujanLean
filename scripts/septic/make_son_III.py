t7, R7, _, _ = gen_iso("S7", M7, U7, n=7)
t6, R6, _, _ = gen_iso("S6", M6, U6, n=6)
Bpol = sp.expand(a*(b**2*c**3 + c**2*d**3 + d**2*b**3) - a**3*b*c*d - 2*(b*c*d)**2)
Q4 = a**4 + 24*a*b*c*d + 8*(b**3*c + c**3*d + d**3*b)
iii = sp.expand(a*Q4**2 + (a**3 - 8*b*c*d)**3 - (2*a**5 + 40*a**2*b*c*d)*Q4)
# solve 3*iii = cB*Bpol + c7*R7 + c6*R6 (cubic, quadratic, cubic)
def ansatz(deg, nm):
    ms = [a**e[0]*b**e[1]*c**e[2]*d**e[3] for e in itertools.product(range(deg+1), repeat=4) if sum(e) == deg]
    xs = sp.symbols(f'{nm}0:{len(ms)}')
    return xs, sum(x*m for x, m in zip(xs, ms))
xB, pB = ansatz(3, 'xb'); x7, p7 = ansatz(2, 'xs'); x6, p6 = ansatz(3, 'xt')
allx = list(xB) + list(x7) + list(x6)
eqs = sp.Poly(sp.expand(pB*Bpol + p7*R7 + p6*R6 - 3*iii), a, b, c, d).coeffs()
sol = sp.solve(eqs, allx, dict=True)[0]
z = {x: 0 for x in allx}
cB, c7, c6 = [sp.expand(p.subs(sol).subs(z)) for p in (pB, p7, p6)]
assert sp.expand(cB*Bpol + c7*R7 + c6*R6 - 3*iii) == 0
for co in (cB, c7, c6): assert all(v.is_integer for v in sp.Poly(co, a, b, c, d).coeffs()), co
print("cB =", cB); print("c7 =", c7); print("c6 =", c6)

def lt(e):  # sympy poly in a,b,c,d -> Lean in T
    s = sp.sstr(sp.expand(e)).replace('**', ' ^ ')
    for v, t in (('a', 'T 0'), ('b', 'T 1'), ('c', 'T 2'), ('d', 'T 3')): s = s.replace(v, f'({t})')
    return f"({s})"
Qs = "(T 0 ^ 4 + 24 * T 0 * T 1 * T 2 * T 3 + 8 * (T 1 ^ 3 * T 2 + T 2 ^ 3 * T 3 + T 3 ^ 3 * T 1))"
