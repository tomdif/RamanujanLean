#!/usr/bin/env python3
"""Generate finite certificates for the prime-modulus reflection-family argument.

The generator uses FLINT for integer row reduction. The independent checker
verifies every integer identity without trusting row reduction. These finite
certificates do not by themselves formalize the analytic converse.
"""
import argparse
import json
from itertools import product
from math import gcd
from pathlib import Path

from flint import fmpz_mat
from quintuple_vanishing_scan import primes_through, product_coefficients
from check_four_plane import residues

ROOT = Path(__file__).resolve().parents[1]


def centered3(x):
    return (x+1) % 3-1


def point(m, n, a, b, c, d):
    p = m*m+n*n
    x, y = m*a-n*b, n*a+m*b
    numerator = (x-y+p*c, y+p*c-p*d, x-p*c-p*d, x+y+p*d)
    if any(t % 3 for t in numerator):
        return None
    return tuple(t//3 for t in numerator)


def supported(w):
    return w is not None and all(t % 3 for t in w)


def generate():
    classes = []
    for m, n in product(range(9), repeat=2):
        if gcd(m*m+n*n, 3) != 1:
            continue
        bases = ((centered3(m-n), centered3(-m-n)),
                 (centered3(m+n), centered3(m-n)))
        points, coordinates = [], []
        for f, (c, d) in enumerate(((1, 0), (0, 1))):
            for a, b in product(range(-7, 8), repeat=2):
                if a*a+b*b > 50 or not supported(point(m, n, a, b, c, d)):
                    continue
                points.append((a, b, c, d))
                aa, bb = bases[f]
                assert (a-aa) % 3 == (b-bb) % 3 == 0
                coordinates.append(((a-aa)//3, (b-bb)//3, c, d))
        matrix = fmpz_mat(coordinates)
        h, transform = matrix.hnf(transform=True)
        assert all(int(h[i, j]) == int(i == j) for i in range(4) for j in range(4))
        inverse = [[int(transform[i, j]) for j in range(len(points))] for i in range(4)]
        classes.append(dict(m=m, n=n, bases=bases, points=points,
                            coordinates=coordinates, spanning_coefficients=inverse))
    primes = set(primes_through(100))
    small = []
    for m in range(2, 11):
        for n in range(1, m):
            p = m*m+n*n
            if p not in primes or 2*(m+n) >= p:
                continue
            zeros = sorted(residues(m, n)) if any(t % 9 == 0 for t in (m, n, m-n, m+n)) else []
            coefficients = product_coefficients(p, (m-n, n, m, m+n), p*(2*p+1)-1)
            first = {}
            for degree, value in sorted(coefficients.items()):
                first.setdefault(degree % p, (degree//p, value))
            assert set(range(p))-first.keys() == set(zeros)
            small.append(dict(m=m, n=n, p=p, zero_residues=zeros,
                              witnesses=[dict(R=r, N=first[r][0], coefficient=first[r][1])
                                         for r in sorted(first)]))
    return dict(scope="Finite certificates for a paper argument; not a complete Lean four-factor converse",
                long_norm_bound=50, large_prime_threshold=100,
                residue_classes=classes, small_prime_cases=small)


def lean_vector(xs):
    return '!['+','.join(str(x) for x in xs)+']'


def lean_data(record):
    out = ['''import RamanujanTau.MultiQuintuplePhaseVacancy

/-! Finite certificates for the prime-family converse argument.
Generated by `scripts/generate_four_prime_converse.py`.
The bridge from these certificates to the analytic converse is separate.
-/
namespace Ramanujan.MultiQuintuple
open scoped BigOperators

structure FourPrimeGeneratorData where
  points : Fin 12 → Fin 4 → ℤ
  inverse : Fin 4 → Fin 12 → ℤ

def fourPrimeGeneratorData (m n : Fin 9) : FourPrimeGeneratorData :=
  match m.val,n.val with
''']
    for case in record['residue_classes']:
        points = case['points']+[case['points'][0]]*(12-len(case['points']))
        inverse = [row+[0]*(12-len(row)) for row in case['spanning_coefficients']]
        out.append(f"  | {case['m']},{case['n']} => ⟨"+
                   lean_vector([lean_vector(row) for row in points])+',\n      '+
                   lean_vector([lean_vector(row) for row in inverse])+'⟩\n')
    out.append('  | _,_ => ⟨fun _ _ => 0,fun _ _ => 0⟩\n\nend Ramanujan.MultiQuintuple\n')
    return ''.join(out)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='compare generated files without writing')
    args = parser.parse_args()
    result = generate()
    outputs = {
        ROOT/'docs/verification/four_prime_converse_certificates.json': json.dumps(result, indent=2)+'\n',
        ROOT/'RamanujanTau/MultiQuintupleFourPrimeGeneratorData.lean': lean_data(result),
    }
    for path, text in outputs.items():
        if args.check:
            if path.read_text() != text:
                raise SystemExit(f'Generated output differs: {path}')
        else:
            path.write_text(text)
    print(f"{'Reproduced' if args.check else 'Generated'} {len(result['residue_classes'])} residue classes "
          f"and {len(result['small_prime_cases'])} small-prime cases")
