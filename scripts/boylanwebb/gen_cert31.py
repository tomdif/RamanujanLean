#!/usr/bin/env python3
"""Emit a Lean certificate for the mod-31 partition cycle.

Python solves for the operator images in the candidate basis ΔE4^4, Δ²E4
using the first two coefficients, then proposes literal lists. Lean checks
every product and applies the proved Sturm bound to the full required prefix.
No Python computation is part of the trusted proof base. This searches within
a supplied modular-form basis, not over arbitrary counting problems.
Usage: python3 scripts/boylanwebb/gen_cert31.py > RamanujanTau/FiniteArithmetic/Cert31.lean
"""

P = 31
D = 31 * 42  # Sturm bound for weight 510, before applying U_31.


def mul(a, b):
    out = [0] * min(D + 1, len(a) + len(b) - 1)
    for i, x in enumerate(a):
        if x:
            for j, y in enumerate(b[: len(out) - i]):
                out[i + j] += x * y
    return [x % P for x in out]


def main():
    out = []
    w = out.append
    w('import RamanujanTau.FiniteArithmetic.ModularCertificate\n')
    w('/-! Generated by `scripts/boylanwebb/gen_cert31.py`.\n'
      'Kernel-checked mod-31 lists through degree 1302.\n'
      '`f = Δ²E₆`, `g = 29ΔE₄³E₆ + 14Δ²E₆`; the odd and even lines differ.\n'
      'This proves a mod-31 cycle, not sharpness at every power of 31. -/\n')
    w('set_option autoImplicit false\nset_option maxRecDepth 8192\n'
      'set_option maxHeartbeats 0\n')
    w('namespace RamanujanTau.FiniteArithmetic.Cert31\n'
      'open PowerSeries BoylanWebb MockTheta5.JTP\n'
      'instance : Fact (Nat.Prime 31) := ⟨by norm_num⟩\n')
    data = {}

    def literal(name, values):
        data[name] = values
        w(f'def {name} : List ℤ := {values}\n')

    def product(name, left, right, expr, proof):
        literal(name, mul(data[left], data[right]))
        w(f'theorem {name}_eq : tmul 31 {D} {left} {right} = {name} := by decide +kernel\n')
        w(f'theorem cg_{name} : Cg 31 {D} ({expr}) (toPS {name}) := by\n'
          f'  rw [← {name}_eq]\n  {proof}\n')

    pent = [0] * (D + 1)
    pent[0] = 1
    m = 0
    while (m + 1) * (3 * m + 2) // 2 <= D:
        for index in ((m + 1) * (3 * m + 2) // 2, (m + 1) * (3 * m + 4) // 2):
            if index <= D:
                pent[index] = (-1 if m % 2 == 0 else 1) % P
        m += 1
    # pentBuild's actual list may stop before degree D.
    last = max((m * (3 * m + 1) // 2), 0)
    literal('Q', pent[: min(last, D) + 1])
    w(f'theorem Q_eq : red 31 (truncList {D} (pentBuild {m})) = Q := by decide +kernel\n')
    w(f'theorem cg_Q : Cg 31 {D} (qfacInf ^ 1) (toPS Q) := by\n'
      f'  rw [pow_one, ← Q_eq]\n'
      f'  exact (Cg_pent {m} (by norm_num)).trans ((Cg_trunc _).symm.trans (Cg_red _).symm)\n')
    names = {1: 'Q'}

    def power(e):
        if e in names:
            return names[e]
        a = e // 2
        b = e - a
        left, right = power(a), power(b)
        name = f'P{e}'
        product(name, left, right, f'qfacInf ^ {e}',
                f'rw [show qfacInf ^ {e} = qfacInf ^ {a} * qfacInf ^ {b} by rw [← pow_add]]\n'
                f'  exact Cg_tmul cg_{left} cg_{right}')
        names[e] = name
        return name

    def shift(name, source, k, expr, rewrite):
        literal(name, ([0] * k + data[source])[: D + 1])
        w(f'theorem {name}_eq : truncList {D} (shiftList {k} {source}) = {name} := by decide +kernel\n')
        w(f'theorem cg_{name} : Cg 31 {D} ({expr}) (toPS {name}) := by\n'
          f'  have h := Cg_shift {k} cg_{source}\n'
          f'  rw [{name}_eq] at h\n  {rewrite}\n')

    power(24)
    power(960)
    shift('LDz', 'P24', 1, 'Dz', 'simpa only [pow_one] using h')
    shift('LD', 'P960', 40, 'Dz ^ δ 31',
          'have he : Dz ^ δ 31 = X ^ 40 * qfacInf ^ 960 := by\n'
          '    rw [show δ 31 = 40 from rfl, mul_pow, ← pow_mul]\n'
          '  rw [he]\n  exact h')
    sigma = [0] * (D + 1)
    for i in range(1, D + 1):
        for j in range(i, D + 1, i):
            sigma[j] += i**3
    literal('E4L', [1] + [(240 * sigma[i]) % P for i in range(1, D + 1)])
    w(f'theorem cg_E4L : Cg 31 {D} RamanujanTau.Mod691.p4 (toPS E4L) :=\n'
      '  Cg_of_formula (fun n => if n = 0 then 1 else 240 * ((ArithmeticFunction.sigma 3 n : ℕ) : ℤ))\n'
      '    RamanujanTau.Mod691.coeff_p4 E4L (by decide +kernel)\n')
    product('E42', 'E4L', 'E4L', 'RamanujanTau.Mod691.p4 ^ 2',
            'simpa only [pow_two] using Cg_tmul cg_E4L cg_E4L')
    sigma5 = [0] * (D + 1)
    for i in range(1, D + 1):
        for j in range(i, D + 1, i):
            sigma5[j] += i**5
    literal('E6L', [1] + [(-504 * sigma5[i]) % P for i in range(1, D + 1)])
    w(f'theorem cg_E6L : Cg 31 {D} RamanujanTau.Mod691.p6 (toPS E6L) :=\n'
      '  Cg_of_formula (fun n => if n = 0 then 1 else -504 * ((ArithmeticFunction.sigma 5 n : ℕ) : ℤ))\n'
      '    RamanujanTau.Mod691.coeff_p6 E6L (by decide +kernel)\n')
    product('E43', 'E42', 'E4L', 'RamanujanTau.Mod691.p4 ^ 3',
            'rw [show RamanujanTau.Mod691.p4 ^ 3 = RamanujanTau.Mod691.p4 ^ 2 * RamanujanTau.Mod691.p4 from pow_succ _ 2]\n'
            '  exact Cg_tmul cg_E42 cg_E4L')
    product('E436', 'E43', 'E6L', 'RamanujanTau.Mod691.p4 ^ 3 * RamanujanTau.Mod691.p6',
            'exact Cg_tmul cg_E43 cg_E6L')
    product('DZ2', 'LDz', 'LDz', 'Dz ^ 2',
            'simpa only [pow_two] using Cg_tmul cg_LDz cg_LDz')
    # Discovery: solve the two-dimensional coefficient system over F_29.
    # These two coefficients only propose candidates. The Sturm checks below,
    # and ultimately the Lean kernel, are what certify the full identities.
    f_coeff = mul(data['DZ2'], data['E6L'])
    h_coeff = mul(data['LDz'], data['E436'])

    def coordinates(first, second):
        determinant = (h_coeff[1] * f_coeff[2] - f_coeff[1] * h_coeff[2]) % P
        inverse = pow(determinant, -1, P)
        return ((first * f_coeff[2] - second * f_coeff[1]) * inverse % P,
                (h_coeff[1] * second - h_coeff[2] * first) * inverse % P)

    ga, gb = coordinates(f_coeff[P], f_coeff[2 * P])
    seed_h, seed = coordinates(data['LD'][P], data['LD'][2 * P])
    assert seed_h == 0, 'The seed does not lie on the proposed odd line'
    w('noncomputable def f : PowerSeries ℤ := Dz ^ 2 * RamanujanTau.Mod691.p6\n'
      'noncomputable def h : PowerSeries ℤ := Dz * (RamanujanTau.Mod691.p4 ^ 3 * RamanujanTau.Mod691.p6)\n'
      f'noncomputable def g : PowerSeries ℤ := C {ga} * h + C {gb} * f\n')
    product('LF', 'DZ2', 'E6L', 'f', 'exact Cg_tmul cg_DZ2 cg_E6L')
    product('LH', 'LDz', 'E436', 'h', 'exact Cg_tmul cg_LDz cg_E436')
    literal('LG', [(ga * a + gb * b) % P for a, b in zip(data['LH'], data['LF'])])
    w(f'theorem LG_eq : red 31 (addList (scaleList {ga} LH) (scaleList {gb} LF)) = LG := by decide +kernel\n')
    w(f'theorem cg_LG : Cg 31 {D} g (toPS LG) := by\n'
      f'  rw [← LG_eq]\n  exact Cg_linear_combination cg_LH cg_LF {ga} {gb}\n')
    product('LDG', 'LD', 'LG', 'Dz ^ δ 31 * g', 'exact Cg_tmul cg_LD cg_LG')
    image_h, multiplier = coordinates(data['LDG'][P], data['LDG'][2 * P])
    assert image_h == 0, 'The two-step image leaves the proposed odd line'
    w('theorem form_f : IntForm 30 f := ((IntForm.disc.pow 2).mul IntForm.E6).cast (by norm_num)\n'
      'theorem form_h : IntForm 30 h := (IntForm.disc.mul ((IntForm.E4.pow 3).mul IntForm.E6)).cast (by norm_num)\n'
      f'theorem form_g : IntForm 30 g := (form_h.C_mul {ga}).add (form_f.C_mul {gb})\n'
      'theorem f_zero : coeff 0 f = 0 := coeff_zero_Dz_pow (by decide : 1 ≤ 2) _\n')
    for source, target, c, bound in [('LD', 'LF', seed, 40), ('LF', 'LG', 1, 2), ('LDG', 'LF', multiplier, 42)]:
        assert all((data[source][P * n] - c * data[target][n]) % P == 0 for n in range(bound + 1))
    w(f'theorem seed : U 31 (Ψ 31 (Dz ^ δ 31)) = C {seed} * Ψ 31 f :=\n'
      '  U_eq_of_certificate 31 (by norm_num) 479 (by norm_num) 30 15 (by norm_num) _ _\n'
      '    ((IntForm.disc.pow 40).cast (by norm_num))\n'
      '    (by simpa using coeff_zero_Dz_pow (by decide : 1 ≤ δ 31) 1)\n'
      f'    form_f {D} (by decide) LD LF cg_LD cg_LF {seed} (by decide +kernel)\n')
    w('theorem even_step : U 31 (Ψ 31 f) = Ψ 31 g := by\n'
      '  simpa using U_eq_of_certificate 31 (by norm_num) 29 (by norm_num) 30 0 (by norm_num) _ _\n'
      f'    form_f f_zero form_g {D} (by decide) LF LG cg_LF cg_LG 1 (by decide +kernel)\n')
    w(f'theorem odd_step : U 31 (Ψ 31 (Dz ^ δ 31) * Ψ 31 g) = C {multiplier} * Ψ 31 f := by\n'
      '  rw [← map_mul]\n'
      '  exact U_eq_of_certificate 31 (by norm_num) 509 (by norm_num) 30 16 (by norm_num) _ _\n'
      '    (((IntForm.disc.pow 40).mul form_g).cast (by norm_num))\n'
      '    (coeff_zero_Dz_pow (by decide : 1 ≤ δ 31) g)\n'
      f'    form_f {D} (by decide) LDG LF cg_LDG cg_LF {multiplier} (by decide +kernel)\n')
    w('end RamanujanTau.FiniteArithmetic.Cert31')
    print('\n'.join(out))


if __name__ == '__main__':
    main()
