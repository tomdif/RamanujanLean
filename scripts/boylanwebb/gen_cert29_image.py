#!/usr/bin/env python3
"""Emit the extra D(f)=21f certificate from the checked Cert29 lists.

This is an untrusted certificate producer. Lean checks its multiplication
and the entire Sturm prefix, as with gen_cert29.py.
"""
import ast
from pathlib import Path
import re

from gen_cert29 import D, mul


def main():
    root = Path(__file__).resolve().parents[2]
    source = (root / "RamanujanTau/FiniteArithmetic/Cert29.lean").read_text()
    lists = {
        name: ast.literal_eval(values)
        for name, values in re.findall(r"^def (\w+) : List ℤ := (\[.*\])$", source, re.M)
    }
    product = mul(lists["LD"], lists["LF"])
    assert all((product[29 * n] - 21 * lists["LF"][n]) % 29 == 0 for n in range(38))
    print('''import RamanujanTau.FiniteArithmetic.Cert29

/-! Generated by `scripts/boylanwebb/gen_cert29_image.py`.
The additional full-series identity needed for the rank of D on M₂₈. -/
set_option autoImplicit false
set_option maxRecDepth 8192
set_option maxHeartbeats 0

namespace RamanujanTau.FiniteArithmetic.Cert29Image
open PowerSeries BoylanWebb Cert29
''')
    print(f"def LDF : List ℤ := {product}\n")
    print(f'''theorem LDF_eq : tmul 29 {D} LD LF = LDF := by decide +kernel

theorem cg_LDF : Cg 29 {D} (Dz ^ δ 29 * f) (toPS LDF) := by
  rw [← LDF_eq]
  exact Cg_tmul cg_LD cg_LF

theorem D_f : U 29 (Ψ 29 (Dz ^ δ 29) * Ψ 29 f) = C 21 * Ψ 29 f := by
  rw [← map_mul]
  exact U_eq_of_certificate 29 (by norm_num) 447 (by norm_num) 28 15 (by norm_num) _ _
    (((IntForm.disc.pow 35).mul form_f).cast (by norm_num))
    (coeff_zero_Dz_pow (by decide : 1 ≤ δ 29) f)
    form_f {D} (by decide) LDF LF cg_LDF cg_LF 21 (by decide +kernel)

end RamanujanTau.FiniteArithmetic.Cert29Image''')


if __name__ == "__main__":
    main()
