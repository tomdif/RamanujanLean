#!/usr/bin/env python3
"""Emit the extra D(f)=29f certificate from the checked Cert31 lists.

This is an untrusted certificate producer. Lean checks its multiplication
and the entire Sturm prefix, as with gen_cert31.py.
"""
import ast
from pathlib import Path
import re

from gen_cert31 import D, mul


def main():
    root = Path(__file__).resolve().parents[2]
    source = (root / "RamanujanTau/FiniteArithmetic/Cert31.lean").read_text()
    lists = {
        name: ast.literal_eval(values)
        for name, values in re.findall(r"^def (\w+) : List ℤ := (\[.*\])$", source, re.M)
    }
    product = mul(lists["LD"], lists["LF"])
    assert all((product[31 * n] - 29 * lists["LF"][n]) % 31 == 0 for n in range(43))
    print('''import RamanujanTau.FiniteArithmetic.Cert31

/-! Generated by `scripts/boylanwebb/gen_cert31_image.py`.
The additional full-series identity needed for the rank of D on M₃₀. -/
set_option autoImplicit false
set_option maxRecDepth 8192
set_option maxHeartbeats 0

namespace RamanujanTau.FiniteArithmetic.Cert31Image
open PowerSeries BoylanWebb Cert31
''')
    print(f"def LDF : List ℤ := {product}\n")
    print(f'''theorem LDF_eq : tmul 31 {D} LD LF = LDF := by decide +kernel

theorem cg_LDF : Cg 31 {D} (Dz ^ δ 31 * f) (toPS LDF) := by
  rw [← LDF_eq]
  exact Cg_tmul cg_LD cg_LF

theorem D_f : U 31 (Ψ 31 (Dz ^ δ 31) * Ψ 31 f) = C 29 * Ψ 31 f := by
  rw [← map_mul]
  exact U_eq_of_certificate 31 (by norm_num) 509 (by norm_num) 30 16 (by norm_num) _ _
    (((IntForm.disc.pow 40).mul form_f).cast (by norm_num))
    (coeff_zero_Dz_pow (by decide : 1 ≤ δ 31) f)
    form_f {D} (by decide) LDF LF cg_LDF cg_LF 29 (by decide +kernel)

end RamanujanTau.FiniteArithmetic.Cert31Image''')


if __name__ == "__main__":
    main()
