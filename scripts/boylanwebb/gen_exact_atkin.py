#!/usr/bin/env python3
"""Generate RamanujanTau/FiniteArithmetic/ExactAtkin<l>.lean for l in {13, 17, 19, 23}.

Proposal generator only: every list, product, inverse and finite check is re-verified
by the Lean kernel. Usage: python3 scripts/boylanwebb/gen_exact_atkin.py 13
"""
import sys
from fractions import Fraction
from itertools import product as iproduct

l = int(sys.argv[1])
Q = l * l
CFG = {
    13: dict(r=1, basis=[(1, 3, 0), (2, 0, 0)], f=(1, 0, 0), B=Fraction(-691, 2730),
             det=(3205, 100, 6, 19, 1007, 3204), kap=6),
    17: dict(r=1, basis=[(1, 5, 0), (2, 2, 0)], f=(1, 1, 0), B=Fraction(-3617, 510),
             det=(6347, 100, 5, 22, 1433, 6346), kap=6),
    19: dict(r=2, basis=[(1, 6, 0), (2, 3, 0), (3, 0, 0)], f=(1, 0, 1), B=Fraction(43867, 798),
             det=(8289, 100, 4, 23, 1429, 8288), kap=10),
    23: dict(r=2, basis=[(1, 8, 0), (2, 5, 0), (3, 2, 0)], f=(1, 1, 1), B=Fraction(854513, 138),
             det=(12675, 100, 1, 24, 507, 12674), kap=5),
}[l]
r = CFG['r']
K = r + 2
d = l * (K - 1)
n = len(CFG['basis'])
w2 = 2 * (l - 1)
delta = (l * l - 1) // 24
QL = f"({l} ^ 2)"
QZ = f"(({l} ^ 2 : ℕ) : ℤ)"

kappa = Fraction(-2 * (l - 1)) / CFG['B']
num, den = kappa.numerator, kappa.denominator
c = num * pow(den, -1, Q) % Q
deninv = pow(den, -1, Q)

N = d + 1


def tm(a, b):
    out = [0] * min(N, len(a) + len(b) - 1)
    for i, x in enumerate(a):
        for j in range(min(len(b), len(out) - i)):
            out[i + j] = (out[i + j] + x * b[j]) % Q
    return out


def sigma(k, m):
    return sum(t ** k for t in range(1, m + 1) if m % t == 0)


lines = []
emit = lines.append
lists = {}


def L(name, vals):
    lists[name] = vals
    emit(f"def {name} : List ℤ := {list(vals)}\n")


# pentagonal
M = 1
while (M + 1) * (3 * M + 2) // 2 <= d:
    M += 1
qf = [0] * N
for k in range(-200, 201):
    x = k * (3 * k - 1) // 2
    if 0 <= x < N:
        qf[x] += (1 if k % 2 == 0 else -1)
qf = [x % Q for x in qf]

header = f"""import RamanujanTau.FiniteArithmetic.ExactAtkinPrecision
import RamanujanTau.FiniteArithmetic.SmallThreshold

/-! Generated by `scripts/boylanwebb/gen_exact_atkin.py {l}`: the finite model of
`ExactAtkin` at `ℓ = {l}`, with coefficient certificates modulo `{l}²` through degree {d}.
Every list identity and finite check below is verified by the kernel. -/
set_option autoImplicit false
set_option maxRecDepth 16384
set_option backward.isDefEq.respectTransparency false
namespace RamanujanTau.FiniteArithmetic.ExactAtkin{l}
open PowerSeries BoylanWebb AtkinOBrienFinal AtkinOBrien ExactAtkin ExactAtkinPrecision MockTheta5.JTP
open RamanujanTau (toPS coeffList truncList shiftList)

instance : Fact (Nat.Prime {l}) := ⟨by norm_num⟩

lemma hℓ : 5 ≤ {l} := by norm_num

"""
emit(header)

# --- base series
L("LQ1", qf[:min(N, M * (3 * M + 1) // 2 + 1)])
emit(f"theorem LQ1_eq : red {QZ} (truncList {d} (pentBuild {M})) = LQ1 := by decide +kernel\n")
emit(f"""theorem cg_Q1 : Cg {QL} {d} qfacInf (toPS LQ1) := by
  rw [← LQ1_eq]
  exact (Cg_pent {M} (by norm_num)).trans ((Cg_trunc _).symm.trans (Cg_red _).symm)
""")

prodcount = [0]


def prod(name, a, b, ea, eb):
    """name := a*b with Cg for (ea * eb)."""
    L(name, tm(lists[a], lists[b]))
    emit(f"theorem {name}_eq : tmul {QZ} {d} {a} {b} = {name} := by decide +kernel\n")
    emit(f"theorem cg_{name} : Cg {QL} {d} (({ea}) * ({eb})) (toPS {name}) := by\n"
         f"  rw [← {name}_eq]; exact Cg_tmul cg_{a[1:] if False else a} cg_{b}\n")


# fix names: cg_ uses list name
def cgname(x):
    return "cg_" + x


def prod2(name, a, b, ea, eb):
    L(name, tm(lists[a], lists[b]))
    emit(f"theorem {name}_eq : tmul {QZ} {d} {a} {b} = {name} := by decide +kernel\n")
    emit(f"theorem {cgname(name)} : Cg {QL} {d} (({ea}) * ({eb})) (toPS {name}) := by\n"
         f"  rw [← {name}_eq]; exact Cg_tmul {cgname(a)} {cgname(b)}\n")


emit(f"theorem cg_LQ1 : Cg {QL} {d} qfacInf (toPS LQ1) := cg_Q1\n")
expr = {"LQ1": "qfacInf"}
# qfac^24 = Q16*Q8
for (nm, a, b) in (("LQ2", "LQ1", "LQ1"), ("LQ4", "LQ2", "LQ2"), ("LQ8", "LQ4", "LQ4"),
                   ("LQ16", "LQ8", "LQ8"), ("LQ24", "LQ16", "LQ8")):
    prod2(nm, a, b, expr[a], expr[b])
    expr[nm] = f"({expr[a]}) * ({expr[b]})"
dz = [0] + lists["LQ24"][:N - 1]
L("LDZ", dz)
emit(f"theorem LDZ_eq : truncList {d} (shiftList 1 LQ24) = LDZ := by decide +kernel\n")
emit(f"""theorem cg_LDZ : Cg {QL} {d} Dz (toPS LDZ) := by
  have h := Cg_shift 1 cg_LQ24
  rw [LDZ_eq] at h
  exact (Cg.of_eq (by simp only [Dz]; ring)).trans h
""")
expr["LDZ"] = "Dz"

# E4, E6
e4 = [1] + [240 * sigma(3, m) % Q for m in range(1, N)]
e6 = [1] + [(-504 * sigma(5, m)) % Q for m in range(1, N)]
for nm, vals, ser, coeff, form in (("LE4", e4, "RamanujanTau.Mod691.p4", "RamanujanTau.Mod691.coeff_p4",
                                    "if n = 0 then 1 else 240 * (ArithmeticFunction.sigma 3 n : ℤ)"),
                                   ("LE6", e6, "RamanujanTau.Mod691.p6", "RamanujanTau.Mod691.coeff_p6",
                                    "if n = 0 then 1 else -504 * (ArithmeticFunction.sigma 5 n : ℤ)")):
    L(nm, vals)
    emit(f"theorem {nm}_formula : ∀ n, n < {d} + 1 → (coeffList {nm} n - ({form})) % (({QL} : ℕ) : ℤ) = 0 := by decide +kernel\n")
    emit(f"theorem cg_{nm} : Cg {QL} {d} {ser} (toPS {nm}) :=\n  Cg_of_formula (fun n => {form}) {coeff} {nm} {nm}_formula\n")
    expr[nm] = ser

# powers
def power(base, k):
    """return list name for base^k with expr base_expr^k via binary chain."""
    nm = f"{base}p{k}"
    if nm in lists:
        return nm
    if k == 1:
        return base
    h = k // 2
    a = power(base, h)
    b = power(base, k - h)
    prod2(nm, a, b, expr[a], expr[b])
    expr[nm] = f"({expr[a]}) * ({expr[b]})"
    return nm


ONE = [1] + [0] * (N - 1)
L("LOne", ONE)
emit(f"theorem LOne_formula : ∀ n, n < {d} + 1 → (coeffList LOne n - (if n = 0 then 1 else 0)) % (({QL} : ℕ) : ℤ) = 0 := by decide +kernel\n")
emit(f"theorem cg_LOne : Cg {QL} {d} 1 (toPS LOne) :=\n  Cg_of_formula (fun n => if n = 0 then 1 else 0) (fun n => coeff_one n) LOne LOne_formula\n")
expr["LOne"] = "1"


def monomial(j, a, b, tag):
    parts = []
    if j: parts.append(power("LDZ", j))
    if a: parts.append(power("LE4", a))
    if b: parts.append(power("LE6", b))
    cur = parts[0]
    for i, p in enumerate(parts[1:]):
        nm = f"{tag}m{i}"
        prod2(nm, cur, p, expr[cur], expr[p])
        expr[nm] = f"({expr[cur]}) * ({expr[p]})"
        cur = nm
    return cur


def lean_mono(j, a, b):
    t = [f"Dz ^ {j}"]
    if a: t.append(f"RamanujanTau.Mod691.p4 ^ {a}")
    if b: t.append(f"RamanujanTau.Mod691.p6 ^ {b}")
    return " * ".join(t)


def lean_poly(j, a, b):
    t = [f"DBound.Pdisc hℓ ^ {j}"]
    if a: t.append(f"MvPolynomial.X 0 ^ {a}")
    if b: t.append(f"MvPolynomial.X 1 ^ {b}")
    return " * ".join(t)


basis_lists = []
for k, (j, a, b) in enumerate(CFG['basis']):
    nm = monomial(j, a, b, f"LB{k}")
    basis_lists.append(nm)
fj, fa, fb_ = CFG['f']
flist = monomial(fj, fa, fb_, "LF")

# E and its inverse
el = [1] + [c * sigma(l - 2, m) % Q for m in range(1, N)]
L("LEL", el)
emit(f"theorem LEL_formula : ∀ n, n < {d} + 1 → (coeffList LEL n - ((if n = 0 then 1 else 0) + {c} * (ArithmeticFunction.sigma ({l} - 2) n : ℤ))) % (({QL} : ℕ) : ℤ) = 0 := by decide +kernel\n")
emit(f"theorem cg_LEL : Cg {QL} {d} (EintG {l} {c}) (toPS LEL) :=\n  Cg_of_formula _ (coeff_EintG (ℓ := {l}) {c}) LEL LEL_formula\n")


def inv(a):
    a = a + [0] * (N - len(a))
    out = [0] * N
    out[0] = pow(a[0], -1, Q)
    for m in range(1, N):
        s = sum(a[t] * out[m - t] for t in range(1, m + 1)) % Q
        out[m] = (-s * out[0]) % Q
    return out


L("LEI", inv(el))
emit(f"theorem LEI_chk : tmul {QZ} {d} LEL LEI = LOne := by decide +kernel\n")
emit(f"""theorem cg_LEI : Cg {QL} {d} (EintInvG {l} {c}) (toPS LEI) := by
  refine Cg_inverse_product (EintG_mul_inv (ℓ := {l}) {c}) cg_LEL ?_
  have h := Cg_tmul (ℓ := {QL}) (d := {d}) (Cg.refl (toPS LEL)) (Cg.refl (toPS LEI))
  rw [LEI_chk] at h
  exact h.trans cg_LOne.symm
""")
expr["LEI"] = f"EintInvG {l} {c}"
prod2("LEI2", "LEI", "LEI", expr["LEI"], expr["LEI"])
expr["LEI2"] = f"(EintInvG {l} {c}) * (EintInvG {l} {c})"

# partitions and Phi
L("LPI", inv(qf))
emit(f"theorem LPI_chk : tmul {QZ} {d} LQ1 LPI = LOne := by decide +kernel\n")
emit(f"""theorem cg_LPI : Cg {QL} {d} partitionGF (toPS LPI) := by
  refine Cg_inverse_product qfac_mul_pgf cg_LQ1 ?_
  have h := Cg_tmul (ℓ := {QL}) (d := {d}) (Cg.refl (toPS LQ1)) (Cg.refl (toPS LPI))
  rw [LPI_chk] at h
  exact h.trans cg_LOne.symm
""")
L("LEV", ONE)
emit(f"theorem LEV_formula : ∀ n, n < {d} + 1 → (coeffList LEV n - (if ({QL} : ℕ) ∣ n then coeffList LQ1 (n / ({QL} : ℕ)) else 0)) % (({QL} : ℕ) : ℤ) = 0 := by decide +kernel\n")
emit(f"""theorem cg_LEV : Cg {QL} {d} (RankProof.Ea ({l} ^ 2) (TauCong.ppow_ne {l} 2) qfacInf) (toPS LEV) := by
  refine (Cg_expand ({l} ^ 2) (TauCong.ppow_ne {l} 2) cg_LQ1).trans ?_
  exact Cg_of_formula (fun n => if ({QL} : ℕ) ∣ n then coeffList LQ1 (n / ({QL} : ℕ)) else 0)
    (fun n => by simp only [RankProof.coeff_Ea, toPS, coeff_mk]) LEV LEV_formula
""")
expr["LEV"] = f"RankProof.Ea ({l} ^ 2) (TauCong.ppow_ne {l} 2) qfacInf"
prod2("LEP", "LEV", "LPI", expr["LEV"], "partitionGF")
phi = ([0] * delta + lists["LEP"])[:N]
L("LPHI", phi)
emit(f"theorem LPHI_eq : truncList {d} (shiftList {delta} LEP) = LPHI := by decide +kernel\n")
emit(f"""theorem cg_LPHI : Cg {QL} {d} (BoylanWebb.Φ {l}) (toPS LPHI) := by
  have h := Cg_shift {delta} cg_LEP
  rw [LPHI_eq] at h
  exact (Cg.of_eq (by simp only [BoylanWebb.Φ, show δ {l} = {delta} from rfl]; ring)).trans h
""")

# G_k = b_k * EI^2 and Phi * G_k
G_lists, PG_lists = [], []
for k, (j, a, b) in enumerate(CFG['basis']):
    gk = f"LG{k}"
    prod2(gk, basis_lists[k], "LEI2", expr[basis_lists[k]], expr["LEI2"])
    pg = f"LPG{k}"
    prod2(pg, "LPHI", gk, f"BoylanWebb.Φ {l}", f"({expr[basis_lists[k]]}) * ({expr['LEI2']})")
    G_lists.append(gk)
    PG_lists.append(pg)
    emit(f"""theorem cgG{k} : Cg {QL} {d} (({lean_mono(j, a, b)}) * (EintInvG {l} {c} * EintInvG {l} {c})) (toPS {gk}) :=
  (Cg.of_eq (by ring)).trans cg_{gk}
theorem cgPG{k} : Cg {QL} {d} (BoylanWebb.Φ {l} * (({lean_mono(j, a, b)}) * (EintInvG {l} {c} * EintInvG {l} {c}))) (toPS {pg}) :=
  (Cg.of_eq (by ring)).trans cg_{pg}
""")

# ---------- Lean: basis, forms, span
fin = lambda xs: "![" + ", ".join(xs) + "]"
emit(f"noncomputable def B : Fin {n} → AtkinOBrienFinal.Poly {l} := {fin([lean_poly(*t) for t in CFG['basis']])}\n")
emit(f"noncomputable def bs : Fin {n} → PowerSeries ℤ := {fin([lean_mono(*t) for t in CFG['basis']])}\n")
emit(f"""lemma iso_X0 : ModP.Iso (MvPolynomial.X 0 : AtkinOBrienFinal.Poly {l}) 4 := by
  simpa [ModP.wt] using MvPolynomial.isWeightedHomogeneous_X ℤ_[{l}] ModP.wt (0 : Fin 2)
lemma iso_X1 : ModP.Iso (MvPolynomial.X 1 : AtkinOBrienFinal.Poly {l}) 6 := by
  simpa [ModP.wt] using MvPolynomial.isWeightedHomogeneous_X ℤ_[{l}] ModP.wt (1 : Fin 2)
""")
iso_cases, ev_cases, form_cases = [], [], []
for (j, a, b) in CFG['basis']:
    t = f"((DBound.iso_Pdisc hℓ).pow {j})"
    if a: t = f"({t}.mul (iso_X0.pow {a}))"
    if b: t = f"({t}.mul (iso_X1.pow {b}))"
    iso_cases.append(f"exact ModP.iso_of_eq {t} (by norm_num)")
    ft = f"(IntForm.disc.pow {j})"
    if a: ft = f"({ft}.mul (IntForm.E4.pow {a}))"
    if b: ft = f"({ft}.mul (IntForm.E6.pow {b}))"
    form_cases.append(f"exact {ft}.cast (by norm_num)")
emit("lemma hB : ∀ k, ModP.Iso (B k) (2 * (" + str(l) + " - 1)) := by\n  intro k; fin_cases k\n" +
     "".join(f"  · simp only [B, Fin.zero_eta, Fin.mk_one, Fin.isValue, Matrix.cons_val_zero, Matrix.cons_val_one, Matrix.head_cons, Matrix.cons_val_two, Matrix.tail_cons]\n    {x}\n" for x in iso_cases))
emit(f"""lemma hev (k : Fin {n}) : ModP.ev ℤ_[{l}] (B k) = PowerSeries.map (Int.castRingHom ℤ_[{l}]) (bs k) := by
  fin_cases k <;>
  · simp [B, bs, map_mul, map_pow, DBound.ev_Pdisc, ModP.ev_X0, ModP.ev_X1, DBound.Dl, ModP.Dq, ModP.E4,
      ModP.E6, Dz]
lemma form_bs (k : Fin {n}) : IntForm ((2 * ({l} - 1) : ℕ) : ℤ) (bs k) := by
  fin_cases k
""" + "".join(f"  · simp only [bs, Fin.zero_eta, Fin.mk_one, Fin.isValue, Matrix.cons_val_zero, Matrix.cons_val_one, Matrix.head_cons, Matrix.cons_val_two, Matrix.tail_cons]\n    {x}\n" for x in form_cases) + f"""lemma hB0 (k : Fin {n}) : coeff 0 (ModP.ev ℤ_[{l}] (B k)) = 0 := by
  rw [hev, coeff_map]
  fin_cases k <;> simp [bs, Dz, coeff_zero_eq_constantCoeff_apply]
""")

# coefficient values of basis mod l from the mod l^2 lists
for k, nm in enumerate(basis_lists):
    vals = [lists[G_lists[k]] and lists[nm][m] % l for m in range(n + 1)]
    emit(f"""lemma cgl_b{k} : Cg {l} {d} (bs {k}) (toPS {nm}) :=
  Cg_of_sq ((Cg.of_eq (by change ({lean_mono(*CFG['basis'][k])}) = _; ring)).trans cg_{nm})
""")
emit(f"""lemma cgl_f : Cg {l} {d} Cert{l}.f (toPS {flist}) :=
  Cg_of_sq ((Cg.of_eq (by simp only [Cert{l}.f]; try ring)).trans cg_{flist})
""")

coeffb0 = [[lists[nm][m] % l for m in range(n + 1)] for nm in basis_lists]
for k in range(n):
    for m in range(n + 1):
        emit(f"lemma b{k}_c{m} : coeff {m} (Ψ {l} (bs {k})) = {coeffb0[k][m]} := by\n  rw [Cg_coeff cgl_b{k} (by norm_num)]; decide\n")
# span via Sturm
coeffb = [[lists[nm][m] % l for m in range(n + 1)] for nm in basis_lists]
NS = (w2 // 12) + 1  # coefficients checked
assert NS == n + 1
cdefs = []
for k in range(n):
    # c_k = coeff (k+1) a - sum_{i<k} c_i * coeffb[i][k+1]
    t = f"coeff {k+1} (Ψ {l} a)"
    for i in range(k):
        t += f" - c{i} * {coeffb[i][k+1]}"
    cdefs.append(t)
sturmN = w2 // 12 + 1
emit(f"""theorem hspan (a : PowerSeries ℤ) (ha : IntForm ((2 * ({l} - 1) : ℕ) : ℤ) a) (ha0 : coeff 0 (Ψ {l} a) = 0) :
    ∃ c : Fin {n} → ZMod {l}, Ψ {l} a =
      ∑ k, C (c k) * PowerSeries.map (PadicInt.toZMod (p := {l})) (ModP.ev ℤ_[{l}] (B k)) := by
""" + "".join(f"  set c{k} : ZMod {l} := {cdefs[k]} with hc{k}\n" for k in range(n)) + f"""  refine ⟨{fin([f'c{k}' for k in range(n)])}, ?_⟩
  simp only [hev, map_map_int, Fin.sum_univ_succ, Fin.sum_univ_zero, Fin.isValue, Matrix.cons_val_zero,
    Matrix.cons_val_succ, Matrix.cons_val_one, Matrix.head_cons, add_zero, Fin.succ_zero_eq_one,
    Fin.succ_one_eq_two]
  set rr := a - {' - '.join(f'PowerSeries.C ((c{k}.val : ℕ) : ℤ) * bs {k}' for k in range(n))} with hrr
  have hr : IntForm ((2 * ({l} - 1) : ℕ) : ℤ) rr :=
    {'(' * (n)}ha{''.join(f'.sub ((form_bs {k}).C_mul _))' for k in range(n))}
  have hΨ : Ψ {l} rr = Ψ {l} a - {' - '.join(f'C c{k} * Ψ {l} (bs {k})' for k in range(n))} := by
    simp only [hrr, map_sub, map_mul, PowerSeries.map_C, Int.coe_castRingHom, Int.cast_natCast,
      ZMod.natCast_zmod_val]
  have hz : Ψ {l} rr = 0 := by
    apply sturm {l} {sturmN} _ (by norm_num) rr hr
    rw [show (((2 * ({l} - 1) : ℕ) : ℤ)).toNat / 12 + 1 = {n + 1} by decide, PowerSeries.X_pow_dvd_iff]
    intro m hm
    rw [hΨ]
    simp only [map_sub, coeff_C_mul]
    interval_cases m
""" + "".join(
    f"    · rw [{', '.join(f'b{k}_c{m}' for k in range(n))}]\n"
    f"      simp only [{', '.join(f'hc{k}' for k in reversed(range(n)))}{', ha0' if m == 0 else ''}]\n"
    f"      ring\n" for m in range(n + 1)) + f"""  rw [hΨ] at hz
  linear_combination hz
""")

# functionals
fl = [lists[flist][m] % l for m in range(K)]
assert fl[0] == 0 and fl[1] == 1
wrows = []
for j in range(r):
    row = [0] * K
    row[1] = (-fl[j + 2]) % l
    row[j + 2] = 1
    wrows.append(row)
emit(f"def w : Fin {r} → ℕ → ℤ := {fin(['fun m => ' + ' '.join(f'if m = {m} then {row[m]} else' for m in range(K)) + ' 0' for row in wrows])}\n")
emit(f"""lemma hw0 : ∀ j, w j 0 = 0 := by intro j; fin_cases j <;> rfl
lemma hwf : ∀ j, ∑ m ∈ Finset.range {K}, (w j m : ZMod {l}) * coeff m (Ψ {l} Cert{l}.f) = 0 := by
  intro j
  simp only [Finset.sum_range_succ, Finset.sum_range_zero, zero_add]
  rw [{', '.join(f'Cg_coeff cgl_f (show {m} ≤ {d} by norm_num)' for m in range(K))}]
  fin_cases j <;> decide
""")

# step data
def coeffs_cv(lst_names):
    return [[lists[nm][l * m] for m in range(K)] for nm in lst_names]


cvU = coeffs_cv(G_lists)
cvD = coeffs_cv(PG_lists)


def taus(cv):
    T = []
    for j in range(r):
        row = []
        for k in range(n):
            s = sum(wrows[j][m] * cv[k][m] for m in range(K)) % Q
            assert s % l == 0, ("not divisible", j, k, s)
            row.append(s // l)
        T.append(row)
    return T


def check(cv, T):
    mu = [cv[k][1] % l for k in range(n)]
    for cc in iproduct(range(l), repeat=n):
        if not any(cc):
            continue
        if sum(a * b for a, b in zip(cc, mu)) % l:
            continue
        if not any(sum(cc[k] * T[j][k] for k in range(n)) % l for j in range(r)):
            return False
    return True


tU, tD = taus(cvU), taus(cvD)
assert check(cvU, tU) and check(cvD, tD), "finite check fails"
for nm, cvl, T, G, op, lem in (("U", cvU, tU, G_lists, "Ulin", "coeff_U_of_list"),
                               ("D", cvD, tD, PG_lists, "Dlin", "coeff_D_of_list")):
    emit(f"def cv{nm} : Fin {n} → ℕ → ℤ := fun k m => coeffList ({fin(G)} k) ({l} * m)\n")
