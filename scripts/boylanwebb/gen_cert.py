#!/usr/bin/env python3
"""Generate RamanujanTau/BoylanWebb/Cert<l>.lean: literal truncated q-series mod l and the
kernel checks feeding BoylanWebb.assemble / boylan_webb_mod.  Usage: gen_cert.py 13 > Cert13.lean"""
import sys

DATA = {13: (0, 0, 11, 8, 4, 6), 17: (1, 0, 7, 7, 13, 6), 19: (0, 1, 5, 6, 8, 10), 23: (1, 1, 1, 5, 1, 5)}

def main(l):
    al, be, c, lam, mu, kappa = DATA[l]
    delta = (l * l - 1) // 24
    d = l * (delta + 1)
    def red(a): return [x % l for x in a]
    def trunc(a): return a[:d + 1]
    def mul(a, b):
        if not a or not b: return []
        out = [0] * (len(a) + len(b) - 1)
        for i, x in enumerate(a):
            if x:
                for j, y in enumerate(b): out[i + j] += x * y
        return out
    def tmul(a, b): return red(trunc(mul(a, b)))
    def shift(k, a): return [0] * k + a
    # pentagonal list
    M = 0
    while not d < (M + 1) * (3 * M + 2) // 2: M += 1
    pent = [1]
    def addl(a, b):
        n = max(len(a), len(b)); return [(a[i] if i < len(a) else 0) + (b[i] if i < len(b) else 0) for i in range(n)]
    for m in range(M):
        s = -1 if m % 2 == 0 else 1
        pent = addl(pent, addl(shift((m + 1) * (3 * m + 2) // 2, [s]), shift((m + 1) * (3 * m + 4) // 2, [s])))
    Q = red(trunc(pent))
    def sig(k, n): return sum(e ** k for e in range(1, n + 1) if n % e == 0)
    E4 = red([1] + [240 * sig(3, n) for n in range(1, d + 1)])
    E6 = red([1] + [-504 * sig(5, n) for n in range(1, d + 1)])
    lit = lambda a: '[' + ', '.join(map(str, a)) + ']'
    out = []
    w = out.append
    w('import RamanujanTau.BoylanWebb.Assemble\n')
    w(f'/-! Generated by `scripts/boylanwebb/gen_cert.py {l}`: the mod-{l} certificate (degree ≤ {d}). -/\n')
    w('set_option autoImplicit false\n')
    w(f'namespace BoylanWebb.Cert{l}')
    w('open PowerSeries RamanujanTau MockTheta5.JTP BoylanWebb\n')
    w(f'instance : Fact (Nat.Prime {l}) := ⟨by norm_num⟩\n')
    w(f'def Q : List ℤ := {lit(Q)}\n')
    w(f'theorem Q_eq : red {l} (truncList {d} (pentBuild {M})) = Q := by decide +kernel\n')
    w(f'theorem cg_P1 : Cg {l} {d} (qfacInf ^ 1) (toPS Q) := by')
    w(f'  rw [pow_one, ← Q_eq]')
    w(f'  exact (Cg_pent {M} (by norm_num)).trans ((Cg_trunc _).symm.trans (Cg_red _).symm)\n')
    P = {1: Q}
    names = {1: 'Q'}
    def step(e, a, b):
        P[e] = tmul(P[a], P[b]); names[e] = f'P{e}'
        w(f'def P{e} : List ℤ := {lit(P[e])}\n')
        w(f'theorem P{e}_eq : tmul {l} {d} {names[a]} {names[b]} = P{e} := by decide +kernel\n')
        w(f'theorem cg_P{e} : Cg {l} {d} (qfacInf ^ {e}) (toPS P{e}) := by')
        w(f'  rw [← P{e}_eq, show qfacInf ^ {e} = qfacInf ^ {a} * qfacInf ^ {b} by rw [← pow_add]]')
        w(f'  exact Cg_tmul cg_P{a} cg_P{b}\n')
    E = 24 * delta
    k = 1
    while 2 * k <= E:
        step(2 * k, k, k); k *= 2
    step(24, 16, 8)
    bits = [1 << i for i in range(E.bit_length()) if E >> i & 1]
    bits.sort(reverse=True)
    acc = bits[0]
    for bt in bits[1:]:
        step(acc + bt, acc, bt); acc += bt
    assert acc == E
    LDz = red(trunc(shift(1, P[24])))
    w(f'def LDz : List ℤ := {lit(LDz)}\n')
    w(f'theorem LDz_eq : truncList {d} (shiftList 1 P24) = LDz := by decide +kernel\n')
    w(f'theorem cg_Dz : Cg {l} {d} Dz (toPS LDz) := by')
    w(f'  have h := Cg_shift 1 cg_P24\n  rw [pow_one, LDz_eq] at h\n  exact h\n')
    LD = trunc(shift(delta, P[E]))
    w(f'def LD : List ℤ := {lit(LD)}\n')
    w(f'theorem LD_eq : truncList {d} (shiftList {delta} P{E}) = LD := by decide +kernel\n')
    w(f'theorem cg_D : Cg {l} {d} (Dz ^ δ {l}) (toPS LD) := by')
    w(f'  have hD : Dz ^ δ {l} = X ^ {delta} * qfacInf ^ {E} := by')
    w(f'    rw [show δ {l} = {delta} from rfl, mul_pow, ← pow_mul]')
    w(f'  have h := Cg_shift {delta} cg_P{E}\n  rw [LD_eq, ← hD] at h\n  exact h\n')
    fexpr = 'Dz'; LF = LDz; cgF = 'cg_Dz'; formF = 'IntForm.disc'
    if al or be:
        if al:
            w(f'def E4L : List ℤ := {lit(E4)}\n')
            w(f'theorem cg_E4 : Cg {l} {d} RamanujanTau.Mod691.p4 (toPS E4L) :=')
            w(f'  Cg_of_formula (fun n => if n = 0 then 1 else 240 * ((ArithmeticFunction.sigma 3 n : ℕ) : ℤ))')
            w(f'    RamanujanTau.Mod691.coeff_p4 E4L (by decide +kernel)\n')
            LF1 = tmul(LF, E4)
            w(f'def LF1 : List ℤ := {lit(LF1)}\n')
            w(f'theorem LF1_eq : tmul {l} {d} LDz E4L = LF1 := by decide +kernel\n')
            w(f'theorem cg_F1 : Cg {l} {d} (Dz * RamanujanTau.Mod691.p4) (toPS LF1) := by')
            w(f'  rw [← LF1_eq]; exact Cg_tmul cg_Dz cg_E4\n')
            fexpr = 'Dz * RamanujanTau.Mod691.p4'; LF = LF1; cgF = 'cg_F1'
            formF = '(IntForm.disc.mul IntForm.E4)'
        if be:
            w(f'def E6L : List ℤ := {lit(E6)}\n')
            w(f'theorem cg_E6 : Cg {l} {d} RamanujanTau.Mod691.p6 (toPS E6L) :=')
            w(f'  Cg_of_formula (fun n => if n = 0 then 1 else -504 * ((ArithmeticFunction.sigma 5 n : ℕ) : ℤ))')
            w(f'    RamanujanTau.Mod691.coeff_p6 E6L (by decide +kernel)\n')
            prevL = 'LDz' if not al else 'LF1'
            LF2 = tmul(LF, E6)
            w(f'def LF2 : List ℤ := {lit(LF2)}\n')
            w(f'theorem LF2_eq : tmul {l} {d} {prevL} E6L = LF2 := by decide +kernel\n')
            w(f'theorem cg_F2 : Cg {l} {d} ({fexpr} * RamanujanTau.Mod691.p6) (toPS LF2) := by')
            w(f'  rw [← LF2_eq]; exact Cg_tmul {cgF} cg_E6\n')
            fexpr = f'{fexpr} * RamanujanTau.Mod691.p6'; LF = LF2; cgF = 'cg_F2'
            formF = f'({formF}.mul IntForm.E6)'
    LFname = {'cg_Dz': 'LDz', 'cg_F1': 'LF1', 'cg_F2': 'LF2'}[cgF]
    w(f'/-- the normalized cusp form `f_{l}` of weight {l - 1} (`Δ·E₄^{al}·E₆^{be}`). -/')
    w(f'noncomputable def f : PowerSeries ℤ := {fexpr}\n')
    w(f'theorem cg_f : Cg {l} {d} f (toPS {LFname}) := {cgF}\n')
    w(f'theorem form_f : IntForm (({l} - 1 : ℕ) : ℤ) f := {formF}.cast (by norm_num)\n')
    w(f'theorem coeff_zero_f : coeff 0 f = 0 := by')
    w(f'  have h := coeff_zero_Dz_pow (k := 1) le_rfl ({ "1" if fexpr == "Dz" else fexpr[5:] })')
    w(f'  rw [pow_one] at h\n  simpa [f, mul_assoc] using h\n')
    LDF = tmul(LD, LF)
    w(f'def LDF : List ℤ := {lit(LDF)}\n')
    w(f'theorem LDF_eq : tmul {l} {d} LD {LFname} = LDF := by decide +kernel\n')
    w(f'theorem cg_DF : Cg {l} {d} (Dz ^ δ {l} * f) (toPS LDF) := by')
    w(f'  rw [← LDF_eq]; exact Cg_tmul cg_D cg_f\n')
    # sanity: python check of the identities
    for n in range(delta + 1): assert (LD[l * n] - c * LF[n]) % l == 0
    for n in range(2): assert (LF[l * n] - lam * LF[n]) % l == 0
    for n in range(delta + 2): assert (LDF[l * n] - mu * LF[n]) % l == 0
    w(f'/-- **The three eigen-congruences mod {l}**: `U(Δ^δ) ≡ {c}·f`, `U f ≡ {lam}·f`, `U(Δ^δ f) ≡ {mu}·f`. -/')
    w(f'theorem eigen : U {l} (Ψ {l} (Dz ^ δ {l})) = C (({c} : ℤ) : ZMod {l}) * Ψ {l} f ∧')
    w(f'    U {l} (Ψ {l} f) = C (({lam} : ℤ) : ZMod {l}) * Ψ {l} f ∧')
    w(f'    U {l} (Ψ {l} (Dz ^ δ {l}) * Ψ {l} f) = C (({mu} : ℤ) : ZMod {l}) * Ψ {l} f :=')
    w(f'  assemble {l} (by norm_num) (by decide) (by decide) (by decide) (by decide) (by decide) (by decide)')
    w(f'    (by decide) (by decide) (by decide) (by decide) (by decide) (by decide) f form_f coeff_zero_f {d}')
    w(f'    (by decide) (by decide) (by decide) LD {LFname} LDF cg_D cg_f cg_DF {c} {lam} {mu}')
    w(f'    (by decide +kernel) (by decide +kernel) (by decide +kernel)\n')
    w(f'theorem f_ne_zero : Ψ {l} f ≠ 0 := by')
    w(f'  intro h')
    w(f'  have h1 := Cg_coeff cg_f (n := 1) (by decide)')
    w(f'  rw [h, map_zero] at h1')
    w(f'  exact absurd h1 (by decide)\n')
    w(f'theorem h24 : 24 * δ {l} + 1 = {l} ^ 2 := by decide\n')
    w(f'/-- `L_{l}(b) mod {l}` lies on the line `𝔽_{l}·f` and is nonzero, for every `b ≥ 1`. -/')
    w(f'theorem rank_one (b : ℕ) (hb : 1 ≤ b) : ∃ x : ZMod {l}, x ≠ 0 ∧ Ψ {l} (L {l} b) = C x * Ψ {l} f :=')
    w(f'  (boylan_webb_mod {l} h24 f {c} {lam} {mu} eigen.1 eigen.2.1 eigen.2.2')
    w(f'    (by decide) (by decide) (by decide) f_ne_zero).1 b hb\n')
    w(f'/-- **`b_{l}(1) = 1`** (Boylan–Webb): `L(b+2) ≡ {kappa}·L(b) (mod {l})` for every `b ≥ 1`. -/')
    w(f'theorem two_step (b : ℕ) (hb : 1 ≤ b) : AtkinOBrien.Dvd ({l} : ℤ) 1 (L {l} (b + 2) - ({kappa} : ℤ) • L {l} b) :=')
    w(f'  Dvd_adjust {l} _ _ _ _ ((boylan_webb_mod {l} h24 f {c} {lam} {mu} eigen.1 eigen.2.1 eigen.2.2')
    w(f'    (by decide) (by decide) (by decide) f_ne_zero).2.1 b hb) (by decide)\n')
    w(f'/-- `L(b) ≢ 0 (mod {l})` for every `b ≥ 1`. -/')
    w(f'theorem not_dvd (b : ℕ) (hb : 1 ≤ b) : ¬ AtkinOBrien.Dvd ({l} : ℤ) 1 (L {l} b) :=')
    w(f'  (boylan_webb_mod {l} h24 f {c} {lam} {mu} eigen.1 eigen.2.1 eigen.2.2')
    w(f'    (by decide) (by decide) (by decide) f_ne_zero).2.2.1 b hb\n')
    w(f'/-- **Partition form**: `p({l}^(b+2)·m − e_(b+2)) ≡ {kappa}·p({l}^b·m − e_b) (mod {l})`, `b ≥ 1`. -/')
    w(f'theorem partition (b : ℕ) (hb : 1 ≤ b) (m : ℕ) :')
    w(f'    ((pZ (({l} : ℕ) ^ (b + 2) * m - eB {l} (b + 2)) : ℤ) : ZMod {l}) =')
    w(f'      ({kappa} : ZMod {l}) * ((pZ (({l} : ℕ) ^ b * m - eB {l} b) : ℤ) : ZMod {l}) := by')
    w(f'  have h := (boylan_webb_mod {l} h24 f {c} {lam} {mu} eigen.1 eigen.2.1 eigen.2.2')
    w(f'    (by decide) (by decide) (by decide) f_ne_zero).2.2.2 b hb m')
    w(f'  rw [show (({lam} * {mu} : ℤ) : ZMod {l}) = {kappa} by decide] at h')
    w(f'  exact h\n')
    w(f'end BoylanWebb.Cert{l}')
    print('\n'.join(out))

main(int(sys.argv[1]))
