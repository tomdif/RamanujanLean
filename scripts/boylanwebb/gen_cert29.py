#!/usr/bin/env python3
"""Emit a Lean certificate for the mod-29 partition cycle.

Python solves for the operator images in the candidate basis ΔE4^4, Δ²E4
using the first two coefficients, then proposes literal lists. Lean checks
every product and applies the proved Sturm bound to the full required prefix.
No Python computation is part of the trusted proof base. This searches within
a supplied modular-form basis, not over arbitrary counting problems.
Usage: python3 scripts/boylanwebb/gen_cert29.py > RamanujanTau/FiniteArithmetic/Cert29.lean
"""

P = 29
D = 29 * 37  # Sturm bound for weight 448, before applying U_29.


def mul(a, b):
    out = [0] * min(D + 1, len(a) + len(b) - 1)
    for i, x in enumerate(a):
        if x:
            for j, y in enumerate(b[: len(out) - i]):
                out[i + j] += x * y
    return [x % P for x in out]


def main():
    out = []
    w = out.append
    w('import RamanujanTau.FiniteArithmetic.ModularCertificate\n')
    w('/-! Generated by `scripts/boylanwebb/gen_cert29.py`.\n'
      'Kernel-checked mod-29 lists through degree 1073.\n'
      '`f = Δ²E₄`, `g = 3ΔE₄⁴ + 6Δ²E₄`; the odd and even lines differ.\n'
      'This proves a mod-29 cycle, not sharpness at every power of 29. -/\n')
    w('set_option autoImplicit false\nset_option maxRecDepth 8192\n'
      'set_option maxHeartbeats 0\n')
    w('namespace RamanujanTau.FiniteArithmetic.Cert29\n'
      'open PowerSeries BoylanWebb MockTheta5.JTP\n'
      'instance : Fact (Nat.Prime 29) := ⟨by norm_num⟩\n')
    data = {}

    def literal(name, values):
        data[name] = values
        w(f'def {name} : List ℤ := {values}\n')

    def product(name, left, right, expr, proof):
        literal(name, mul(data[left], data[right]))
        w(f'theorem {name}_eq : tmul 29 {D} {left} {right} = {name} := by decide +kernel\n')
        w(f'theorem cg_{name} : Cg 29 {D} ({expr}) (toPS {name}) := by\n'
          f'  rw [← {name}_eq]\n  {proof}\n')

    pent = [0] * (D + 1)
    pent[0] = 1
    m = 0
    while (m + 1) * (3 * m + 2) // 2 <= D:
        for index in ((m + 1) * (3 * m + 2) // 2, (m + 1) * (3 * m + 4) // 2):
            if index <= D:
                pent[index] = (-1 if m % 2 == 0 else 1) % P
        m += 1
    # pentBuild's actual list may stop before degree D.
    last = max((m * (3 * m + 1) // 2), 0)
    literal('Q', pent[: min(last, D) + 1])
    w(f'theorem Q_eq : red 29 (truncList {D} (pentBuild {m})) = Q := by decide +kernel\n')
    w(f'theorem cg_Q : Cg 29 {D} (qfacInf ^ 1) (toPS Q) := by\n'
      f'  rw [pow_one, ← Q_eq]\n'
      f'  exact (Cg_pent {m} (by norm_num)).trans ((Cg_trunc _).symm.trans (Cg_red _).symm)\n')
    names = {1: 'Q'}

    def power(e):
        if e in names:
            return names[e]
        a = e // 2
        b = e - a
        left, right = power(a), power(b)
        name = f'P{e}'
        product(name, left, right, f'qfacInf ^ {e}',
                f'rw [show qfacInf ^ {e} = qfacInf ^ {a} * qfacInf ^ {b} by rw [← pow_add]]\n'
                f'  exact Cg_tmul cg_{left} cg_{right}')
        names[e] = name
        return name

    def shift(name, source, k, expr, rewrite):
        literal(name, ([0] * k + data[source])[: D + 1])
        w(f'theorem {name}_eq : truncList {D} (shiftList {k} {source}) = {name} := by decide +kernel\n')
        w(f'theorem cg_{name} : Cg 29 {D} ({expr}) (toPS {name}) := by\n'
          f'  have h := Cg_shift {k} cg_{source}\n'
          f'  rw [{name}_eq] at h\n  {rewrite}\n')

    power(24)
    power(840)
    shift('LDz', 'P24', 1, 'Dz', 'simpa only [pow_one] using h')
    shift('LD', 'P840', 35, 'Dz ^ δ 29',
          'have he : Dz ^ δ 29 = X ^ 35 * qfacInf ^ 840 := by\n'
          '    rw [show δ 29 = 35 from rfl, mul_pow, ← pow_mul]\n'
          '  rw [he]\n  exact h')
    sigma = [0] * (D + 1)
    for i in range(1, D + 1):
        for j in range(i, D + 1, i):
            sigma[j] += i**3
    literal('E4L', [1] + [(240 * sigma[i]) % P for i in range(1, D + 1)])
    w(f'theorem cg_E4L : Cg 29 {D} RamanujanTau.Mod691.p4 (toPS E4L) :=\n'
      '  Cg_of_formula (fun n => if n = 0 then 1 else 240 * ((ArithmeticFunction.sigma 3 n : ℕ) : ℤ))\n'
      '    RamanujanTau.Mod691.coeff_p4 E4L (by decide +kernel)\n')
    product('E42', 'E4L', 'E4L', 'RamanujanTau.Mod691.p4 ^ 2',
            'simpa only [pow_two] using Cg_tmul cg_E4L cg_E4L')
    product('E44', 'E42', 'E42', 'RamanujanTau.Mod691.p4 ^ 4',
            'convert Cg_tmul cg_E42 cg_E42 using 1 <;> ring')
    product('DZ2', 'LDz', 'LDz', 'Dz ^ 2',
            'simpa only [pow_two] using Cg_tmul cg_LDz cg_LDz')
    # Discovery: solve the two-dimensional coefficient system over F_29.
    # These two coefficients only propose candidates. The Sturm checks below,
    # and ultimately the Lean kernel, are what certify the full identities.
    f_coeff = mul(data['DZ2'], data['E4L'])
    h_coeff = mul(data['LDz'], data['E44'])

    def coordinates(first, second):
        determinant = (h_coeff[1] * f_coeff[2] - f_coeff[1] * h_coeff[2]) % P
        inverse = pow(determinant, -1, P)
        return ((first * f_coeff[2] - second * f_coeff[1]) * inverse % P,
                (h_coeff[1] * second - h_coeff[2] * first) * inverse % P)

    ga, gb = coordinates(f_coeff[P], f_coeff[2 * P])
    seed_h, seed = coordinates(data['LD'][P], data['LD'][2 * P])
    assert seed_h == 0, 'The seed does not lie on the proposed odd line'
    w('noncomputable def f : PowerSeries ℤ := Dz ^ 2 * RamanujanTau.Mod691.p4\n'
      'noncomputable def h : PowerSeries ℤ := Dz * RamanujanTau.Mod691.p4 ^ 4\n'
      f'noncomputable def g : PowerSeries ℤ := C {ga} * h + C {gb} * f\n')
    product('LF', 'DZ2', 'E4L', 'f', 'exact Cg_tmul cg_DZ2 cg_E4L')
    product('LH', 'LDz', 'E44', 'h', 'exact Cg_tmul cg_LDz cg_E44')
    literal('LG', [(ga * a + gb * b) % P for a, b in zip(data['LH'], data['LF'])])
    w(f'theorem LG_eq : red 29 (addList (scaleList {ga} LH) (scaleList {gb} LF)) = LG := by decide +kernel\n')
    w(f'theorem cg_LG : Cg 29 {D} g (toPS LG) := by\n'
      f'  rw [← LG_eq]\n  exact Cg_linear_combination cg_LH cg_LF {ga} {gb}\n')
    product('LDG', 'LD', 'LG', 'Dz ^ δ 29 * g', 'exact Cg_tmul cg_LD cg_LG')
    image_h, multiplier = coordinates(data['LDG'][P], data['LDG'][2 * P])
    assert image_h == 0, 'The two-step image leaves the proposed odd line'
    w('theorem form_f : IntForm 28 f := ((IntForm.disc.pow 2).mul IntForm.E4).cast (by norm_num)\n'
      'theorem form_h : IntForm 28 h := (IntForm.disc.mul (IntForm.E4.pow 4)).cast (by norm_num)\n'
      f'theorem form_g : IntForm 28 g := (form_h.C_mul {ga}).add (form_f.C_mul {gb})\n'
      'theorem f_zero : coeff 0 f = 0 := coeff_zero_Dz_pow (by decide : 1 ≤ 2) _\n')
    for source, target, c, bound in [('LD', 'LF', seed, 35), ('LF', 'LG', 1, 2), ('LDG', 'LF', multiplier, 37)]:
        assert all((data[source][P * n] - c * data[target][n]) % P == 0 for n in range(bound + 1))
    w(f'theorem seed : U 29 (Ψ 29 (Dz ^ δ 29)) = C {seed} * Ψ 29 f :=\n'
      '  U_eq_of_certificate 29 (by norm_num) 419 (by norm_num) 28 14 (by norm_num) _ _\n'
      '    ((IntForm.disc.pow 35).cast (by norm_num))\n'
      '    (by simpa using coeff_zero_Dz_pow (by decide : 1 ≤ δ 29) 1)\n'
      f'    form_f {D} (by decide) LD LF cg_LD cg_LF {seed} (by decide +kernel)\n')
    w('theorem even_step : U 29 (Ψ 29 f) = Ψ 29 g := by\n'
      '  simpa using U_eq_of_certificate 29 (by norm_num) 27 (by norm_num) 28 0 (by norm_num) _ _\n'
      f'    form_f f_zero form_g {D} (by decide) LF LG cg_LF cg_LG 1 (by decide +kernel)\n')
    w(f'theorem odd_step : U 29 (Ψ 29 (Dz ^ δ 29) * Ψ 29 g) = C {multiplier} * Ψ 29 f := by\n'
      '  rw [← map_mul]\n'
      '  exact U_eq_of_certificate 29 (by norm_num) 447 (by norm_num) 28 15 (by norm_num) _ _\n'
      '    (((IntForm.disc.pow 35).mul form_g).cast (by norm_num))\n'
      '    (coeff_zero_Dz_pow (by decide : 1 ≤ δ 29) g)\n'
      f'    form_f {D} (by decide) LDG LF cg_LDG cg_LF {multiplier} (by decide +kernel)\n')
    w('end RamanujanTau.FiniteArithmetic.Cert29')
    print('\n'.join(out))


if __name__ == '__main__':
    main()
