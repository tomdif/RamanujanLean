#!/usr/bin/env python3
"""Produce kernel-checkable precision-841 error certificates.

Only a proposal generator: every multiplication and inverse is checked by Lean.
Writes the public certificate, coefficient data, and a serial chain of product
modules. Each numerical product check has at most 64 left-hand coefficients.

Usage: python3 scripts/boylanwebb/gen_cert29_error.py --output-dir RamanujanTau/FiniteArithmetic
"""
import argparse
from pathlib import Path
import gen_cert29 as arithmetic
arithmetic.P, arithmetic.D = 841, 1682
P, D, mul = 841, 1682, arithmetic.mul
BLOCK = 64


def multiply_prefix(a, b, degree):
    out = [0] * min(degree + 1, len(a) + len(b) - 1)
    for i, x in enumerate(a):
        if x:
            for j, y in enumerate(b[:len(out) - i]):
                out[i + j] += x * y
    return [x % P for x in out]


def emit_product(destination, previous, label, left, right, result, data):
    """Each tail is checked only to the degree needed after its eventual shift."""
    offsets = list(range(0, min(len(data[left]), D + 1), BLOCK))
    outputs = {}
    carry = []
    for offset in reversed(offsets):
        degree = D - offset
        block = data[left][offset:offset + BLOCK]
        product = multiply_prefix(block, data[right], degree)
        shifted = [0] * len(block) + carry if carry else []
        length = min(degree + 1, max(len(product), len(shifted)))
        carry = [((product[j] if j < len(product) else 0) +
                  (shifted[j] if j < len(shifted) else 0)) % P for j in range(length)]
        outputs[offset] = carry
    assert outputs[0] == data[result], label
    lines = [f'''import {previous}

/-! Generated by `scripts/boylanwebb/gen_cert29_error.py`.
Product {left} * {right}: left blocks of at most {BLOCK} coefficients.
The import chain serializes certificate checks and caches completed products. -/
set_option autoImplicit false
set_option Elab.async false
set_option maxRecDepth 16384
set_option maxHeartbeats 200000
namespace RamanujanTau.FiniteArithmetic.Cert29Error
open PowerSeries BoylanWebb
namespace Blocks{label}
''']
    w = lines.append
    for offset in offsets:
        for name, values in [(f'tail{offset}', data[left][offset:]),
                             (f'block{offset}', data[left][offset:offset + BLOCK]),
                             (f'out{offset}', outputs[offset])]:
            alias = left if name == 'tail0' else result if name == 'out0' else None
            w(f'set_option maxHeartbeats 0 in\ndef {name} : List ℤ := {alias or values}\n')
    for i in reversed(range(len(offsets))):
        offset = offsets[i]
        degree = D - offset
        if i == len(offsets) - 1:
            w(f'''theorem check{offset} : tmul 841 {degree} tail{offset} {right} = out{offset} := by
  set_option maxHeartbeats 0 in decide +kernel

theorem result{offset} : Cg 841 {degree} (toPS tail{offset} * toPS {right}) (toPS out{offset}) := by
  rw [← check{offset}]
  exact Cg_tmul (Cg.refl _) (Cg.refl _)
''')
        else:
            nxt = offsets[i + 1]
            size = nxt - offset
            w(f'''theorem split{offset} : tail{offset} = block{offset} ++ tail{nxt} := by
  set_option maxHeartbeats 0 in decide +kernel

theorem check{offset} : red 841 (truncList {degree}
    (addList (mulList block{offset} {right}) (shiftList {size} out{nxt}))) = out{offset} := by
  set_option maxHeartbeats 0 in decide +kernel

theorem result{offset} : Cg 841 {degree} (toPS tail{offset} * toPS {right}) (toPS out{offset}) := by
  rw [split{offset}]
  exact Cg_mul_block (d := {D - nxt}) (k := {size}) (by decide +kernel) result{nxt} check{offset}
''')
    w(f'''end Blocks{label}

theorem {label}_check : Cg 841 {D} (toPS {left} * toPS {right}) (toPS {result}) :=
  Blocks{label}.result0

end RamanujanTau.FiniteArithmetic.Cert29Error
''')
    folder = destination / 'Cert29ErrorProducts'
    folder.mkdir(exist_ok=True)
    (folder / f'{label}.lean').write_text('\n'.join(lines))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir', type=Path, required=True)
    args = parser.parse_args()
    products = []
    data_lines = []
    lines = ['''import RamanujanTau.FiniteArithmetic.Precision29
import RamanujanTau.FiniteArithmetic.Cert29ErrorProducts.YG

/-! Generated by `scripts/boylanwebb/gen_cert29_error.py`.
Exact finite certificates for the first divided error at precision 29². -/
set_option autoImplicit false
set_option Elab.async false
set_option maxRecDepth 16384
set_option maxHeartbeats 200000
namespace RamanujanTau.FiniteArithmetic.Cert29Error
open PowerSeries BoylanWebb MockTheta5.JTP Precision29
''']
    w = lines.append
    data = {}
    def literal(name, a):
        data[name] = a
        data_lines.append(f'set_option maxHeartbeats 0 in\ndef {name} : List ℤ := {a}\n')
    def formula_check(name, formula):
        checks = []
        condition = f'(coeffList {name} n - ({formula})) % (841 : ℤ) = 0'
        for start in range(0, D + 1, BLOCK):
            stop = min(start + BLOCK, D + 1)
            label = f'{name}_formula{start}'
            checks.append(label)
            w(f'theorem {label} : ∀ n ∈ Finset.Ico {start} {stop}, {condition} := by decide +kernel\n')
        def join(names):
            if len(names) == 1:
                return names[0]
            middle = len(names) // 2
            return f'(forall_Ico_join {join(names[:middle])} {join(names[middle:])})'
        w(f'''theorem {name}_formula : ∀ n, n < {D + 1} → {condition} := by
  intro n hn
  exact {join(checks)} n (Finset.mem_Ico.mpr ⟨Nat.zero_le n, hn⟩)
''')
    def product(name, a, b, expr, proof):
        literal(name, mul(data[a], data[b]))
        products.append((name, a, b, name))
        proof = proof.replace(f'Cg_tmul cg_{a} cg_{b}', f'Cg_product cg_{a} cg_{b} {name}_check')
        w(f'theorem cg_{name} : Cg 841 {D} ({expr}) (toPS {name}) := by\n  {proof}\n')
    def shift(name, a, k, expr, proof):
        literal(name, ([0]*k+data[a])[:D+1])
        w(f'theorem {name}_eq : truncList {D} (shiftList {k} {a}) = {name} := by decide +kernel\n')
        w(f'theorem cg_{name} : Cg 841 {D} ({expr}) (toPS {name}) := by\n  have h := Cg_shift {k} cg_{a}\n  rw [{name}_eq] at h\n  {proof}\n')
    q = [0]*(D+1); q[0]=1; k=0
    while (k+1)*(3*k+2)//2 <= D:
        for j in ((k+1)*(3*k+2)//2,(k+1)*(3*k+4)//2):
            if j<=D:q[j]=(-1 if k%2==0 else 1)%P
        k+=1
    literal('Q',q[:k*(3*k+1)//2+1])
    w(f'theorem Q_eq : red 841 (truncList {D} (pentBuild {k})) = Q := by decide +kernel\n')
    w(f'theorem cg_Q : Cg 841 {D} qfacInf (toPS Q) := by\n  rw [← Q_eq]\n  exact (Cg_pent {k} (by norm_num)).trans ((Cg_trunc _).symm.trans (Cg_red _).symm)\n')
    names={1:'Q'}
    def power(e):
        if e in names:return names[e]
        a=e//2;b=e-a;x=power(a);y=power(b);name=f'Q{e}'
        left='qfacInf' if a==1 else f'qfacInf ^ {a}'
        right='qfacInf' if b==1 else f'qfacInf ^ {b}'
        product(name,x,y,f'qfacInf ^ {e}',
                f'rw [show qfacInf ^ {e} = qfacInf ^ {a} * qfacInf ^ {b} from pow_add qfacInf {a} {b}]\n'
                f'  simpa only [pow_one] using Cg_tmul cg_{x} cg_{y}')
        names[e]=name;return name
    power(24)
    shift('Delta','Q24',1,'Dz','simpa only [pow_one] using h')
    def sigma(e):
        a=[0]*(D+1)
        for d in range(1,D+1):
            v=pow(d,e,P)
            for n in range(d,D+1,d):a[n]=(a[n]+v)%P
        return a
    s3=sigma(3);s27=sigma(27)
    literal('E4L',[1]+[240*x%P for x in s3[1:]])
    formula_check('E4L', 'if n = 0 then 1 else 240 * (ArithmeticFunction.sigma 3 n : ℤ)')
    w(f'''theorem cg_E4L : Cg 841 {D} Mod691.p4 (toPS E4L) :=
  Cg_of_formula (fun n => if n = 0 then 1 else 240 * (ArithmeticFunction.sigma 3 n : ℤ))
    Mod691.coeff_p4 E4L E4L_formula
''')
    product('E42','E4L','E4L','Mod691.p4 ^ 2','simpa only [pow_two] using Cg_tmul cg_E4L cg_E4L')
    product('E44','E42','E42','Mod691.p4 ^ 4',
            'rw [show Mod691.p4 ^ 4 = (Mod691.p4 ^ 2) ^ 2 from pow_mul Mod691.p4 2 2]\n'
            '  simpa only [pow_two] using Cg_tmul cg_E42 cg_E42')
    product('Delta2','Delta','Delta','Dz ^ 2','simpa only [pow_two] using Cg_tmul cg_Delta cg_Delta')
    product('LF','Delta2','E4L','Cert29.f','exact Cg_tmul cg_Delta2 cg_E4L')
    product('LH','Delta','E44','Cert29.h','exact Cg_tmul cg_Delta cg_E44')
    literal('LG',[(3*a+6*b)%P for a,b in zip(data['LH'],data['LF'])])
    w(f'''theorem LG_eq : red 841 (addList (scaleList 3 LH) (scaleList 6 LF)) = LG := by decide +kernel

theorem cg_LG : Cg 841 {D} Cert29.g (toPS LG) := by
  rw [← LG_eq]
  exact Cg_linear_combination cg_LH cg_LF 3 6
''')
    literal('EL',[1]+[783*x%P for x in s27[1:]])
    literal('EI',[1]+[-783*x%P for x in s27[1:]])
    literal('One',[1]+[0]*D)
    formula_check('EL', '(if n = 0 then 1 else 0) + 783 * (ArithmeticFunction.sigma 27 n : ℤ)')
    formula_check('One', 'if n = 0 then 1 else 0')
    w(f'''theorem cg_EL : Cg 841 {D} Eint (toPS EL) :=
  Cg_of_formula _ coeff_Eint EL EL_formula

theorem cg_One : Cg 841 {D} 1 (toPS One) :=
  Cg_of_formula (fun n => if n = 0 then 1 else 0) (fun n => coeff_one n) One One_formula

theorem cg_EI : Cg 841 {D} EintInv (toPS EI) :=
  Cg_inverse_product Eint_mul_inv cg_EL (EI_check.trans cg_One.symm)
''')
    products.append(('EI', 'EL', 'EI', 'One'))
    inv=[1]+[0]*D
    for n in range(1,D+1):
        inv[n]=-sum(q[j]*inv[n-j] for j in range(1,n+1) if q[j])%P
    literal('PI',inv)
    w(f'''theorem cg_PI : Cg 841 {D} partitionGF (toPS PI) :=
  Cg_inverse_product (qfac_mul_pgf 29) cg_Q (PI_check.trans cg_One.symm)
'''.replace('(qfac_mul_pgf 29)','qfac_mul_pgf'))
    products.append(('PI', 'Q', 'PI', 'One'))
    ev=[0]*(D+1)
    for n in range(0,D+1,841):ev[n]=q[n//841]
    literal('EV',ev)
    formula_check('EV', 'if 841 ∣ n then coeffList Q (n / 841) else 0')
    w(f'''theorem cg_EV : Cg 841 {D} (RankProof.Ea 841 (by decide) qfacInf) (toPS EV) := by
  refine (Cg_expand 841 (by decide) cg_Q).trans ?_
  exact Cg_of_formula (fun n => if 841 ∣ n then coeffList Q (n / 841) else 0)
    (fun n => by simp only [RankProof.coeff_Ea, toPS, coeff_mk]) EV EV_formula
''')
    product('EP','EV','PI','RankProof.Ea 841 (by decide) qfacInf * partitionGF','exact Cg_tmul cg_EV cg_PI')
    shift('Phi','EP',35,'BoylanWebb.Φ 29','simpa only [BoylanWebb.Φ, show δ 29 = 35 from rfl, mul_assoc] using h')
    product('PhiI','Phi','EI','BoylanWebb.Φ 29 * EintInv','exact Cg_tmul cg_Phi cg_EI')
    product('YF','PhiI','LF','BoylanWebb.Φ 29 * EintInv * Cert29.f','exact Cg_tmul cg_PhiI cg_LF')
    product('YG','PhiI','LG','BoylanWebb.Φ 29 * EintInv * Cert29.g','exact Cg_tmul cg_PhiI cg_LG')
    for name,expr,value in [('YF','BoylanWebb.Φ 29 * EintInv * Cert29.f',348),('YG','BoylanWebb.Φ 29 * EintInv * Cert29.g',725),('Phi','BoylanWebb.Φ 29',696)]:
        actual=(3*data[name][1682]-data[name][841])%841
        assert actual==value,(name,actual)
        w(f'''theorem obs_{name} : 3 * coeff 1682 (Ψ 841 ({expr})) - coeff 841 (Ψ 841 ({expr})) = {value} := by
  rw [Cg_coeff cg_{name} (by decide), Cg_coeff cg_{name} (by decide)]
  decide +kernel
''')
    w('end RamanujanTau.FiniteArithmetic.Cert29Error')
    destination = args.output_dir
    destination.mkdir(parents=True, exist_ok=True)
    header = ('import RamanujanTau.FiniteArithmetic.ChunkedCertificate\n\n'
              '/-! Generated coefficient data; all arithmetic is checked in the product modules. -/\n'
              'set_option autoImplicit false\nset_option Elab.async false\n'
              'set_option maxRecDepth 16384\n'
              'namespace RamanujanTau.FiniteArithmetic.Cert29Error\n')
    (destination / 'Cert29ErrorData.lean').write_text(header + '\n'.join(data_lines)
        + '\nend RamanujanTau.FiniteArithmetic.Cert29Error\n')
    (destination / 'Cert29Error.lean').write_text('\n'.join(lines).replace('decide +kernel',
                                  'set_option maxHeartbeats 0 in decide +kernel') + '\n')
    previous = 'RamanujanTau.FiniteArithmetic.Cert29ErrorData'
    for label, left, right, result in products:
        emit_product(destination, previous, label, left, right, result, data)
        previous = f'RamanujanTau.FiniteArithmetic.Cert29ErrorProducts.{label}'

if __name__=='__main__':main()
